	and	0x007
	ld	(kv_stA_p2), a
	ld	(kv_stB_p2), a
;  РУКОЯТЬ НОЖА (задача #54): пять патч-сайтов в сегментных программах 0x45-0x4B. В каждом
;  лежит база сегмента строк рукояти с НУЛЕВЫМ кодом заливки; нужен код 0 (заливка «ноль» ->
