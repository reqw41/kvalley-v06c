;  (vec_mixbuf для тайлов 0xC0+ не заполняется: range-гейт vec_col_store пускает 0x50-0x8F).
;  Маску держим в vbt8_wf: на этом пути белый флаг не нужен (его читает только штатный шаг p1).
;  Вход: C=col, vbt8_e=255-row*8, vw_byte=тайл. Клоб A,B,D,E,H,L (C цел — нужен шагу p2).
;  [УДАЛЕНО ЗАДАЧЕЙ #55, 2026-08-07] vec_mixtiles — 15 Б «какому тайлу какой слот». Список
;  остался ровно в одном месте, в генераторе (MIXTILES, tools/gfx/msx2vec.py): он и раздаёт
;  номера слотов, кладя их прямо в биты 6-3 байта режима. Дублировать его в ПЗУ незачем.
vbt8_mapt:
