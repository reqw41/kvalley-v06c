	ld	a, 96
	call	ADD_A_HL
	ld	(vec_nr_ptr), hl
	ld	a, (vec_nr_srow)
	inc	a
	ld	(vec_nr_srow), a
	cp	23	; ряды 1..22 включительно
	jp	c, vec_nr_row
	pop	af	; восстановить реальную глубину
	ld	(vec_isr_depth), a
	ei
	ret
;  ====== ГРАДИЕНТ ЛОГОТИПА KING'S VALLEY (титул) — post-align хвост ======================
;  MSX красит логотип ПОСТРОЧНО: COLORES_LOGO = 16 байт на колонку из ДВУХ тайлов
;  (coloreaLogo раскатывает их на все 22 колонки, тайлы 0x4B-0x76; хвост «g» 0x77/0x78
;  залит сплошным 0x40). Распакованные цвета (старший ниббл = MSX-перо, младший = 0 = фон):
;    строки 0-7  (верхний тайл): 60 60 60 80 80 90 90 A0
;    строки 8-15 (нижний тайл):  B0 E0 30 70 50 50 40 40
;  Штатный 8C-блит выбирает планы НА ТАЙЛ (white-бит vec_tilemode + vec_col8) => из 10
;  MSX-цветов получалось 3 (idx8 красн / idx12 золото / случайный idx14 от гем-записей
;  vec_col8[0x50]/[0x5C]). Здесь свой блит: p0/p1/p2 пишутся ПОСТРОЧНО по трём маскам,
;  бит7 = строка 0. 10 цветов свёрнуты в 7 слотов (см. vec_pal_title):
;    {6,8}=красный {9}=св.красный {A,B}=жёлтый {E}=серый {3}=зелёный {7}=циан {5,4}=синий.
;  Индекс палитры = (p0<<3)|(p1<<2)|(p2<<1)|p3, p3 схлопнут (пары равны).
;  Вход: HL = адрес name (0x3800..), A = тайл. Сохраняет HL,DE,BC.
;  Зовут ТОЛЬКО drawGameLogo3/drawGameLogo4 (титул) => vbt8_ent/геймплей не тронуты; заодно
;  обходится ловушка «блеск гема» (тайлы 0x51-0x53 на титуле — колонки лого, а vbt8_ent
;  уводил их в vec_blit_brillo и гасил p0). vbt_core не зовём: все строки лого = режим
;  «pattern» (перо>=2, фон=0), т.е. просто копия паттерна -> SP-хайджек и DI не нужны.
vec_logo_blit:
	or	a	; тайл 0 (пустые углы прямоугольника пирамиды) — экран уже очищен
	ret	z
	push	hl
	push	de
	push	bc
	push	af
	ld	a, l	; колонка = L & 31
	and	0x1F
	ld	(vlb_col), a
	ld	a, l	; Etop = 255-row*8; row*8 = (H&3)*64 + (L&0xE0)>>2
	and	0x0E0
	rrca
	rrca
	ld	c, a
	ld	a, h
	and	3
	rlca
	rlca
	rlca
	rlca
	rlca
	rlca
	add	a, c
	cpl
	ld	(vlb_top), a
	pop	af
	push	af
	ld	l, a	; HL = адрес паттерна тайла (tile*8 + база диапазона)
	ld	h, 0
	add	hl, hl
	add	hl, hl
	add	hl, hl
	call	pat_base	; DE = база по диапазону (сохраняет HL/BC)
	add	hl, de
	ld	(vlb_pp), hl
	pop	af
;  Смещение тройки масок в vec_logo_msk:
;    0x40-0x4A (пирамида титула) -> (тайл-0x40)*2 (перекрывающиеся тройки, см. таблицу)
;    0x4B-0x76 (колонки лого)    -> 23 верхний тайл / 26 нижний (по чётности)
;    0x77/0x78 (хвост «g»)       -> 29
	sub	0x40
	cp	0x0B
	jp	nc, vlb_lg
	add	a, a
	ld	e, a
	jp	vlb_grp
vlb_lg:
	sub	0x0B
	ld	e, 29
	cp	0x2C
	jp	nc, vlb_grp
	and	1
	ld	e, 23
	jp	z, vlb_grp
	ld	e, 26
vlb_grp:
	ld	hl, vec_logo_msk
	ld	d, 0
	add	hl, de
	ld	(vlb_mp), hl
	ld	a, 0x0A0	; план 1
	call	vlb_pass
	ld	a, 0x0C0	; план 2
	call	vlb_pass
	ld	a, 0x80	; план 0 (строки вне маски гасятся)
	call	vlb_pass
	pop	bc
	pop	de
	pop	hl
	ret
;  vlb_pass: A = hi плоскости-приёмника. (vlb_mp) = указатель маски (пост-инкремент),
;  (vlb_pp) = паттерн, (vlb_col)/(vlb_top) = колонка/верхняя строка (лежат парой -> lhld).
;  Бит маски=1 -> строка получает шейп, 0 -> ноль. Клоб A,B,C,D,E,H,L.
vlb_pass:
	ld	hl, (vlb_col)	; L = колонка, H = Etop
	add	a, l	; D = плоскость + колонка
	ld	d, a
	ld	e, h	; E = Etop (вниз по строкам)
	ld	hl, (vlb_mp)	; C = маска строк, указатель++
	ld	c, (hl)
	inc	hl
	ld	(vlb_mp), hl
	ld	hl, (vlb_pp)	; HL = паттерн (сверху вниз)
	ld	b, 8
vlb_row:
	ld	a, c	; carry = бит текущей строки
	add	a, a
	ld	c, a
	ld	a, 0	; ld a,imm НЕ трогает флаги (в отличие от xor a)
	jp	nc, vlb_wr
	ld	a, (hl)
vlb_wr:
	ld	(de), a
	inc	hl
	dec	e
	dec	b
	jp	nz, vlb_row
	ret
vec_logo_msk:	; тройки масок (p1, p2, p0); бит7 = строка 0 тайла
;  ПИРАМИДА ТИТУЛА (тайлы 0x40-0x4A, смещение (тайл-0x40)*2): p1=p0=0xFF, т.е. весь шейп в
;  idx12 (БЕЛЫЙ), а p2 = строки СЕРЫХ граней (idx14). Тройки ПЕРЕКРЫВАЮТСЯ (0xFF конца одной
;  = начало следующей) -> 11 тайлов занимают 23Б вместо 33Б. Маски сняты с цвет-таблицы
;  ОРИГИНАЛА (тайлы 0x90-0x9A: E0=серый, F0=белый): 90/91/92 сплошь серые, 93=F5, 94=6E,
;  95=70, 96-9A сплошь белые. Раньше 0x40-0x44 уходили в vbt8_brick (кирпич!) и пирамида
;  получала красно-золотые ступени, а 0x45 терял серые строки.
	db	0x0FF,0x0FF, 0x0FF,0x0FF, 0x0FF,0x0FF, 0x0FF,0x0F5, 0x0FF,0x06E, 0x0FF,0x070
	db	0x0FF,0x000, 0x0FF,0x000, 0x0FF,0x000, 0x0FF,0x000, 0x0FF,0x000, 0x0FF
;  ЛОГО (смещения 23 / 26 / 29):
	db	0x006,0x007,0x0F9	; верх: красн x5 (60/60/60/80/80), св.красн x2 (90), жёлт (A0)
	db	0x04F,0x0F0,0x0C0	; низ: жёлт (B0), серый (E0), бирюза x2 (30/70), синий x4 (50/50/40/40)
	db	0x0FF,0x000,0x000	; хвост «g» (0x77/0x78): весь синий (цвет 40)
;  vsp_title: отложенная загрузка палитры титула + СБРОС flagPiramideMap. Без сброса на ВТОРОМ
;  и последующих заходах в титул (attract: демо -> смерть -> лого Konami -> титул) флаг
;  оставался равен 1 от прошлой партии, и _COLOR2 каждый кадр золотил idx8 (kv_stone_scheme)
;  -> верх логотипа выходил жёлтым вместо красного. Флаг = «мы внутри пирамиды», на титуле он
;  обязан быть 0; любой выход в игру заново ставит 1 через setDatosPartida (ValoresIniciales).
vsp_title:
	xor	a
	ld	(flagPiramideMap), a
;  ЗАДАЧА #21: титул — «вне пирамиды» и БАЗОВАЯ ветка покадрового писателя. Раньше патч
;  vbp_map снимал сам себя (по нечётности flagPiramideMap), и на титул из карты долины
;  (проигрыш на пергаменте: flagEndPergamino -> Game Over -> лого Konami) диспетчер приезжал
;  ВСЁ ЕЩЁ патченным — на титуле крутился бы пульс карты. Теперь патч снимается здесь.
;  HL держит таблицу палитры титула для vsp_defer — сохраняем через стек.
	ld	(vbp_scene), a
	push	hl
	di
	ld	a, 0x03A	; ld a,(GameStatus) — базовые 3 байта патч-сайта
	ld	(vec_brillo_pal), a
	ld	hl, GameStatus
	ld	(vec_brillo_pal+1), hl
	ei
	pop	hl
	jp	vsp_defer
;  vec_pyr_end: снять патч vbr_call -> vec_blit_rect снова зовёт vec_text_blit (двери геймплея).
vec_pyr_end:
	ld	hl, vec_text_blit
	ld	(vbr_call+1), hl
	ret
;  vec_pal_title: палитра титула (грузится setColor через vsp_defer — оба титульных входа).
;  7 слотов градиента + чёрный фон; пары равны (p3 схлопнут: служебное ОЗУ p3 невидимо).
;  idx = (p0<<3)|(p1<<2)|(p2<<1)|p3. Байт Вектора = %BBGGGRRR (R,G по 3 бита, B — 2),
;  подобрано к TMS9918 (11 MSX-цветов титула свёрнуты в 7 слотов):
;    idx0/1   чёрный фон                    idx8/9   0x5F КРАСНЫЙ (MSX 6/8)
;    idx2/3   0xFA БИРЮЗА (MSX 3+7)         idx10/11 0xB7 ЖЁЛТЫЙ (MSX A/B)
;    idx4/5   0xDB СИНИЙ (MSX 5/4)          idx12/13 0xFF БЕЛЫЙ (MSX F): пирамида + тексты
;    idx6/7   0xA7 СВ.КРАСНЫЙ (MSX 9)       idx14/15 0xF6 СЕРЫЙ (MSX E): грани + блик лого
;  Единственное слияние сверх неизбежных — зелёный(3)+циан(7) в бирюзу: они соседи по тону и
;  занимают по ОДНОЙ строке лого, а высвобожденный слот отдан БЕЛОМУ, без которого пирамида
;  (тело F0 / грани E0) и тексты (F0) не воспроизводятся. Красные тона 6/8 неразличимы на
;  3-битном ЦАП Вектора, 5/4 (св./тёмн. синий) тоже -> слиты без потерь.
;  idx4 и idx8 обязаны совпадать с константами vbp_static/_COLOR2 — vec_brillo_pal пишет их
;  КАЖДЫЙ кадр (см. комментарии там).
vec_pal_title:
	db	0x000,0x000,0x0FA,0x0FA, 0x0DB,0x0DB,0x0A7,0x0A7, 0x05F,0x05F,0x0B7,0x0B7, 0x0FF,0x0FF,0x0F6,0x0F6
