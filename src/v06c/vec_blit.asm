;  оригинала): чётные пары строк идут в p0 = idx8, нечётные в p0+p2 = idx10. Цвет второго
;  тона берём из парной таблицы, она лежит сразу за kv_stone_scheme, поэтому индекс тот же
;  плюс 4. Пишем ЗДЕСЬ, а не в vbp_i8w: та метка общая с титулом и картой, где схемы нет.
;  ГРАНИЦА СТРАНИЦЫ. Было `ld a,l / add a,4 / ld l,a` — СЛОЖЕНИЕ ТОЛЬКО ПО МЛАДШЕМУ БАЙТУ,
;  перенос в H терялся, и как только kv_stone_scheme ложится в конец страницы, +4 читает
