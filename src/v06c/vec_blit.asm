	sub	0x0CC	; 0xCC-0xCE (буквы GOAL) -> красные только рамочные строки 0 и 7
	cp	3
	ld	a, 0x0FF
	jp	nc, vbt8_mm
	ld	a, 0x081
vbt8_mm:
	ld	(vbt8_wf), a
	ld	a, (vw_byte)	; HL = адрес паттерна тайла (tile*8 + база диапазона)
	ld	l, a
	ld	h, 0
	add	hl, hl
	add	hl, hl
	add	hl, hl
	call	pat_base	; DE = база по диапазону (сохраняет HL/BC)
	add	hl, de
	ld	a, c	; DE = верх приёмника p0 (0x80+col : vbt8_e)
	add	a, 0x80
	ld	d, a
	ld	a, (vbt8_e)
	ld	e, a
	ld	b, 8
vbt8_mrow:
	ld	a, (vbt8_wf)	; carry = бит строки (1 -> красная)
	add	a, a
	ld	(vbt8_wf), a
	jp	c, vbt8_mred
	ld	a, (hl)	; СИНЯЯ строка: p0 = ~паттерн
