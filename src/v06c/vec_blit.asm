	ld	(de), a
	ld	a, d	; DE -> p1
	add	a, 0x20
	ld	d, a
	ld	a, 0x0FF	; p1 = 0xFF
	ld	(de), a
	jp	vbt8_mnx
vbt8_mred:
	ld	a, 0x0FF	; КРАСНАЯ строка: p0 = 0xFF
	ld	(de), a
	ld	a, d	; DE -> p1
	add	a, 0x20
	ld	d, a
	ld	a, (hl)	; p1 = ~паттерн
	cpl
	ld	(de), a
vbt8_mnx:
	ld	a, d	; DE обратно на p0
	sub	0x20
	ld	d, a
	inc	hl
	dec	e
	dec	b
	jp	nz, vbt8_mrow
	jp	vbt8_p2
