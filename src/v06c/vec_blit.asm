	ld	e, a	; запомнить индекс (E свободен у всех вызывателей)
	ld	a, c
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	ld	a, e
	inc	a	; близнец idx+1
	out	(0x02), a
	ld	a, c
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	ret
