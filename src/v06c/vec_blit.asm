;  === vbp_pair: записать ПАРУ слотов палитры (A и A+1) одним цветом C ================
;  Из-за схлопнутого p3 каждый чётный слот обязан иметь близнеца (иначе служебное ОЗУ p3
;  проступает на экране), поэтому все палитровые записи здесь ходят парами idx/idx+1 с ОДНИМ
;  значением. Раньше пара была расписана дважды по 13-14 Б; теперь это один helper.
;  Вход: A = чётный индекс слота, C = цвет. Клоббер: A, E (оба и так в списке клоббера
;  vec_brillo_pal). HL, B, D НЕ трогает — на них держатся счётчик и таблица у вызывателей.
;  МЕСТО ВЫБРАНО СПЕЦИАЛЬНО: сразу за `ret` метки vbp_titdone, то есть вне всех сквозных
;  проходов (vbp_static -> vbp_out, ... -> vbp_i8w -> vbp_titdone).
