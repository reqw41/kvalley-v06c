;  ЗАДЕРЖКА ЛАТЧА (см. шапку vec_boot про 30 тактов): менять номер слота сразу после
;  последнего out(0x0C) нельзя — цвет догоняет луч и уезжает в соседний слот. Здесь между
;  половинами пары стоит `ld a,e / inc a` = 10 тактов против 7 тактов у прежнего
;  `ld a,5`, то есть запас НЕ уменьшился, а вырос; к тому же обе половины пишут ОДИН
;  цвет, так что перетекание между ними безвредно по определению. После пары вызыватель
;  тратит ещё ret + свою работу, то есть заведомо больше, чем было.
vbp_pair:
