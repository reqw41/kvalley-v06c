; ===== Блиттер тайлов SCREEN2 8x8 =====
; Вход: A=тайл, B=ряд(0-23), C=столбец(0-31).
; ТЕКУЩАЯ СХЕМА (8C): vbt_core рисует ШЕЙП тайла в план 0, затем обёртка vbt8_ent
; докладывает цвет: p1 = шейп при white-флаге (бит7 vec_tilemode), p2 = шейп при
; бите0 цвет-кода cc=vec_col8[tile], p0 очищается при бите1 cc; кирпичи 0x40-0x44 —
; отдельный двутоновый путь (vbt8_brick), блеск 0x51-0x53 — vec_blit_brillo.
; Итог: 8 цветов фона из комбинаций p0/p1/p2 (p3 схлопнут палитрой и невидим).
; [история] Исходно блиттер был двухплановым: фон только в p0 (2 цвета), спрайты
; XOR-ом в отдельный план — отсюда формулировки в старых комментариях ниже.
;  --- Задача 2цв-фон (2026-07-12): обёртка. vbt_core рисует p0; затем p1 пишется
;  по флагу "белый тайл" (bit7 mode-таблицы, calc_mode): белый -> копия паттерна p0
;  в p1 (idx12=БЕЛЫЙ: лестницы/текст); иначе p1=0 (idx8=синие стены / idx0 чёрный).
;  p1(0xA000) свободна (спрайты в p3). Не трогает SP-хайджек ядра (p1-проход после
;  возврата vbt_core, только память). Вызывается из vec_nat_room и vcp_cells.
;  (Весь этот A+/COLOR2 путь эмитится ТОЛЬКО при KV_8COLOR OFF; при ON — 8-цветный ниже.)
;  ================= ФАЗА 1: 8-ЦВЕТНЫЙ КОМПОЗИТ-ФОН (3 плоскости p0/p1/p2) =================
;  vec_blit_tile под KV_8COLOR: vbt_core рисует ШЕЙП тайла в p0 (все режимы: blank/pattern/
;  inverted/solid/mixed). Затем ЦВЕТ через 3 плоскости:
;    p1 = ШЕЙП если тайл БЕЛЫЙ (runtime white-бит vec_tilemode, как в базе: текст/лестн-верх),
;         иначе 0. => БЕЗ vec_col8-правок фон = базовый 2-цв (idx8 стены / idx12 белый), но на
;         8-цв палитре -> сразу КОРРЕКТНЫЙ рендер без мусора.
;    p2 = ШЕЙП если vec_col8[tile] бит0 (доп. цвет-ось: idx8->idx10, idx12->idx14).
;    p0 = ОЧИСТИТЬ если vec_col8[tile] бит1 (увести цвет с p0: idx8->idx0/idx4, +p2 -> idx2/idx6).
;  Пиксель шейпа -> idx=(p0<<3)|(p1<<2)|(p2<<1) (чёт => p3-схлопка); void (нет шейпа) => idx0.
;  Порядок КРИТИЧЕН: p1/p2 копируют p0-шейп ДО очистки p0. brillo гем (0x51-0x53) -> свой путь.
;  Медленнее (до 24 memops/тайл) — correctness-first; скорость (pre-shift p3) = след. фаза.
vec_blit_tile:
;  КООП-ТИК МУЗЫКИ (2026-07-30): вся игровая логика Вектора исполняется ВНУТРИ обработчика
;  прерывания, поэтому долгие серии блитов (карта долины, шторка drawCortinilla, полная
;  перерисовка комнаты) идут одним DI-участком — замерено до 279 кадров подряд, и всё это
;  время музыка стоит. На карте пирамид это давало 23% кадров БЕЗ тика и темп 0.77.
;  Клетка стоит ~0.25 кадра, поэтому тикаем здесь — в общей точке всех блит-путей
;  (vec_text_blit, dt_vec_draw, drawCortinilla, vec_nr_row). Доля в аккумулятор та же,
;  что у скролла; штатный кадровый тик аккумулятор обнуляет, так что в обычном геймплее
;  (пара клеток HUD за кадр) лишних тиков не возникает.
;  vsnd_busy — защита от повторного входа: updateSound не рисует, но блит-путь длинный,
;  и флаг снимает целый класс рисков разом.
	ld	a, (vsnd_busy)
	or	a
	jp	nz, vbt_snd_no
	ld	a, (vtm_have)	; [mus-jitter] с часами опрашиваем чаще: серия клеток идёт под DI, кадровые IRQ тонут.
	dec	a	; vtm_have 0/1 -> 0xFF/0 -> 0xFF&(k_cell-k_clk) + k_clk = k_cell без часов, k_clk с часами
	and	255&(vsnd_k_cell-vsnd_k_clk)
	add	a, vsnd_k_clk
	ld	hl, vsnd_acc
	add	a, (hl)
	ld	(hl), a
	jp	nc, vbt_snd_no
	push	bc	; B=row/C=col нужны блиту ниже
	ld	a, 1
	ld	(vsnd_busy), a
	call	vsnd_tick_coop	; тик РЕШАЮТ часы ВИ53, доля выше лишь прореживает опрос
	xor	a
	ld	(vsnd_busy), a
	pop	bc
vbt_snd_no:
;  _8C_RL2: обёртка — после блита обновить пересекающиеся save-слоты СВЕЖИМ фоном
;  (vec_su_fixup, B=row/C=col). Иначе restore спрайта воскрешал бы стёртый гем/копку.
	push	bc
	call	vbt8_ent
	pop	bc
;  ЗАДАЧА#54: и СРАЗУ ПЕРЕРИСОВАТЬ спрайт, чей фон только что переписали. Иначе фигура
;  лежит стёртой до ближайшей пачки, и луч проходит по пустому месту В ЭТОМ ЖЕ кадре
;  (жалоба «герой мерцает, стоя у закрывающихся ворот»). Гейт и доказательство — в
;  шапке vfr_gate (vec_repair.asm); при снятом vfl_dany это 8 тактов на клетку.
	call	vec_su_fixup
	jp	vfr_gate
;  vec_su_fixup: B=row(0-23), C=col(0-31) свежеблитнутой клетки. Для каждого валидного
;  слота: пересечение по столбцу (col в [c0,c0+ncols)) и строкам (клетка [ytop-7,ytop],
;  слот [lo0-15,lo0], y убывает вверх) -> копировать fb(плоскость слота)->данные слота.
;  Быстрый выход по vsu_any (0 => слотов нет: bulk-отрисовка комнаты почти бесплатна).
;  Клоб A,B,C,D,E,H,L (как сам vec_blit_tile).
vec_su_fixup:
	ld	a, (vsu_any)
	or	a
	ret	z
	ld	a, b
	add	a, a
	add	a, a
	add	a, a
	cpl
	ld	(vfx_ytop), a
	ld	a, c
	ld	(vfx_col), a
	xor	a
	ld	(vfx_idx), a
vfx_loop:
	ld	a, (vfx_idx)	; слот 256Б: H=0xE0+idx, L=0
	ld	l, 0
	add	a, 0x0E0	; HL=слот
	ld	h, a
	ld	a, (hl)	; слот невалиден
	or	a
	jp	z, vfx_next
	inc	hl	; D=hi0
	ld	a, (hl)
	ld	d, a
	inc	hl	; E=lo0
	ld	a, (hl)
	ld	e, a
	inc	hl	; C=ncols
	ld	a, (hl)
	ld	c, a
	inc	hl	; hi0b (0=одна плоскость)
	ld	a, (hl)
	ld	(vfx_hib), a
	inc	hl	; hi0c (0=нет 3-й плоскости; !=0 только у masked-створок ворот)
	ld	a, (hl)
	ld	(vfx_hic), a
	ld	a, c
	add	a, a
	add	a, a
	add	a, a
	add	a, a
	ld	(vfx_n16), a	; ncols*16 = ШАГ между плоскостями в данных слота
	inc	hl	; HL=data (+6: valid,hi0,lo0,ncols,hi0b,hi0c)
;  ФИКС КОРНЯ ЗАВИСАНИЯ (2026-07-29): fixup считал данные с +5, а save/restore кладут
;  с +6 (hi0c добавлен при masked-воротах, fixup не обновили) -> fixup писал фон со
;  сдвигом -1, затирая hi0c клеточным байтом; restore затем "восстанавливал 3-ю
;  плоскость" по мусорному hi0c (напр. 0x0F) ПРЯМО В КОД (0x0F81/0x1081, chkScroll3
;  ld a,0x20 -> nop) => вечный цикл скролла GS 5<->9. В старом формате (верх вперёд)
;  на -1 попадал верхний байт клетки (обычно 0 = шов кирпича) — мина молчала.
	ld	a, d	; B=c0
	and	0x1F
	ld	b, a
	ld	a, (vfx_col)	; col<c0
	sub	b
	jp	c, vfx_next
	cp	c	; off>=ncols
	jp	nc, vfx_next
	add	a, a	; off*16 (off<=2)
	add	a, a
	add	a, a
	add	a, a
	add	a, l
	ld	l, a
	ld	a, h
	adc	a, 0
	ld	h, a
;  P2: формат слота НИЗ-ВВЕРХ. Геометрия пересечения клетки (8 строк) со слотом
;  (16 строк): E=lo_b = НИЗ столбца (240-Y), данные слота идут ПО РОСТУ y.
	ld	a, (vfx_ytop)	; B=ytop (верх клетки, 255-row*8)
	ld	b, a
	ld	a, e	; A=lo_top=lo_b+15 (верх столбца)
	add	a, 15
;  ЗАВОРОТ СТОЛБЦА (найден и доказан замером 2026-08-20). Сложение 8-битное: при lo_b>=241
;  верх столбца переполнялся в 0..14, дальше t=min(ytop,0)=0, bottom=max(ytop-7,lo_b)>=241,
;  и тест «t<bottom -> пересечения нет» ВЫБРАСЫВАЛ слот целиком: фон в нём не подновлялся
;  после блита клетки, а спрайт не метился к перерисовке. Ровно этот случай даёт герой,
;  частично ушедший ВЫШЕ поля (lo0 = 239-Y), то есть верхний ряд + прыжок — баг владельца
;  «половина спрайта остаётся». При заворот-переносе верх столбца заведомо выше ytop,
;  значит t = ytop: уходим прямо на ветку «берём B». ЦЕНА: 3 байта, 10 тактов на клетку.
	jp	c, vfx_tb
	cp	b	; lo_top<ytop -> t=lo_top
	jp	c, vfx_t1
vfx_tb:
	ld	a, b
vfx_t1:
	ld	(vfx_t), a	; t=min(ytop,lo_top)
	ld	a, b	; B=ytop-7 (низ клетки)
	sub	7
	ld	b, a
	ld	a, e	; A=lo_b (низ столбца)
	cp	b
	jp	nc, vfx_b1
	ld	a, b
vfx_b1:
	ld	c, a	; C=bottom=max(ytop-7,lo_b)
	ld	a, (vfx_t)	; t<bottom -> нет пересечения
	cp	c
	jp	c, vfx_next
	sub	c	; B=число строк (1..8)
	inc	a
	ld	b, a
	ld	a, c	; bottom-lo_b = смещение в данных слота (низ-вверх)
	sub	e
	ld	e, c	; E=bottom (старт y, копия идёт ВВЕРХ)
	add	a, l
	ld	l, a
	ld	a, h
	adc	a, 0
	ld	h, a
	ld	a, d	; плоскость слота
	and	0x0E0
	ld	c, a
	ld	a, (vfx_col)	; D=плоскость+col (fb src hi)
	add	a, c
	ld	d, a
	ld	(vfx_dst), hl	; реплей-параметры для 2-й плоскости
	ld	a, b
	ld	(vfx_cnt), a
	ld	a, e
	ld	(vfx_tt), a
;  Пересечение подтверждено: слот получает свежий фон И помечается sticky-dirty ->
;  фаза F следующего кадра перерисует спрайт (иначе фон-блит «съел» бы статичный спрайт).
;  ЗАДАЧА#36: заодно взводим ГЛОБАЛЬНЫЙ vfl_dany — гейт слияния sticky в фазе F. Sticky
;  выставлен лишь в 0.5% кадров, а проход слияния шёл КАЖДЫЙ кадр по всем 21 ячейке.
	push	hl
	ld	a, (vfx_idx)
	add	a, vfl_dirty&255
	ld	l, a
	ld	h, 255&(vfl_dirty>>8)
	ld	(hl), 1
	ld	a, 1
	ld	(vfl_dany), a
	ld	(vfr_need), a	; ЗАДАЧА#54: спрайт этого слота стёрт блитом — перерисовать
	pop	hl
vfx_row:
	ld	a, (de)	; слот <- свежий fb (fb идём вверх: формат низ-вверх)
	ld	(hl), a
	inc	hl
	inc	e
	dec	b
	jp	nz, vfx_row
;  РЕПЛЕЙ ПО ПЛОСКОСТЯМ СЛОТА: та же геометрия, следующая плоскость. Плоскостей может быть
;  ТРИ: hi0 (основная), hi0b (dual/AURA) и hi0c (гасимая p0 у masked-створок ворот).
;  ФИКС 2026-07-31: раньше реплей был ОДИН (только hi0b), и hi0c створки оставался с фоном,
;  снятым при её появлении. Любой блит клетки под створкой (кадр анимации ворот) => restore
;  возвращал в p0 УСТАРЕВШУЮ картинку поверх свежей клетки — «ворота стираются не полностью»
;  в их правом столбце (замер юнит-теста door_fixup: 6-8 Б p0 на каждую клетку).
;  Цепочка hib := hic, hic := 0 даёт ровно столько реплеев, сколько у слота плоскостей.
;  ЗАДАЧА#39 (2026-08-02): ПРЕЖНИЙ ИНВАРИАНТ «hi0c != 0 бывает только вместе с hi0b != 0»
;  БОЛЬШЕ НЕ ДЕЙСТВУЕТ. Непрозрачный герой ставит гасимую p0 слоту ОДЕЖДЫ, а у неё dual
;  нет (hi0b = 0). Со старым гейтом реплей обрывался на первой же плоскости, и фон p0 в
;  слоте оставался протухшим — ровно та мина, что была у створок ворот (см. фикс выше):
;  блит клетки под героем, и стирание вернуло бы в p0 картинку позапрошлого кадра.
;  Поэтому: нет hi0b, но есть hi0c -> реплеим hi0c (в данных слота он идёт вторым блоком,
;  save/restore пропускают отсутствующие плоскости так же, шаг n16 верен).
	ld	a, (vfx_hib)
	or	a
	jp	nz, vfx_chain
	ld	a, (vfx_hic)
	or	a
	jp	z, vfx_next
	ld	(vfx_hib), a
	xor	a
	ld	(vfx_hic), a
	ld	a, (vfx_hib)
vfx_chain:
	and	0x0E0
	ld	c, a
	ld	a, (vfx_hic)
	ld	(vfx_hib), a
	xor	a
	ld	(vfx_hic), a
	ld	a, (vfx_col)	; fb src hi очередной плоскости
	add	a, c
	ld	d, a
	ld	hl, (vfx_dst)
	ld	a, (vfx_n16)
	add	a, l
	ld	l, a
	ld	a, h
	adc	a, 0
	ld	h, a
	ld	(vfx_dst), hl	; следующая плоскость начнётся ещё на n16 дальше
	ld	a, (vfx_tt)
	ld	e, a
	ld	a, (vfx_cnt)
	ld	b, a
	jp	vfx_row
vfx_next:
	ld	a, (vfx_idx)
	inc	a
	ld	(vfx_idx), a
	cp	21
	jp	c, vfx_loop
	ret
vbt8_ent:
	ld	a, (vw_byte)
	cp	0x51
	jp	c, vbt8_norm
	cp	0x54
	jp	c, vec_blit_brillo
vbt8_norm:
	push	bc	; p0 = ШЕЙП (B=row, C=col сохранены)
	call	vbt_core	; план 0 (блиттер не менялся)
	pop	bc
	ld	a, b	; Etop=255-row*8
	add	a, a
	add	a, a
	add	a, a
	cpl
	ld	(vbt8_e), a
	ld	h, 255&(vec_tilemode>>8)
	ld	a, (vw_byte)
	ld	l, a
	ld	a, (hl)
	and	0x80	; white-флаг (0 / 0x80) для p1
	ld	(vbt8_wf), a
; cc = 1 для гем-тайлов, иначе 0. [2026-07-29] БЫЛА ТАБЛИЦА vec_col8 на 256 Б, в которой
; ненулевых всего 8 байт и все = 1 — заменена проверкой диапазонов ПРЯМО ЗДЕСЬ (место
; чтения единственное, поэтому call не нужен и стек не трогается). Бит1 цвет-кода нигде
; не взводился, эмулировать нечего.
;  [2026-08-04, унификация блиттера] ПРОВЕРЯЛОСЬ ТРИ ДИАПАЗОНА (0x50, 0x5C, 0x86-0x8B),
;  ОСТАЛСЯ ОДИН. Два других вычислялись ВХОЛОСТУЮ: 0x5C уходит в vbt8_lever, который
;  cc вообще не читает и задаёт все три плоскости сам, а гемы 0x86-0x8B уходят в
;  vbt8_gem -> vbt8_planes, и тот перезаписывает vbt8_c8 байтом из kv_gem_planes ПОВЕРХ
;  вычисленного. Реально cc доживает до шага p2 только у тайла 0x50. -18 Б, картинка та же.
	ld	a, (vw_byte)
	cp	0x50
	ld	a, 0	; ld (а не xor) — флаги cp обязаны дожить до jp
	jp	nz, vbt8_ccw
	inc	a
vbt8_ccw:
	ld	(vbt8_c8), a
;  2a КИРПИЧИ 2-ТОН: тайлы 0x40-0x44 -> per-row золото(idx8)/красн(idx4), НЕ через p1/p2/cc.
;  ДВА ПАТЧ-САЙТА (задача #15, финальный экран). Тайлы 0x40-0x47 на экране КОНЦОВКИ — это
;  НЕ кирпичи лабиринта, а грани трёх пирамид, песчаный пол и звёзды (setupEnding грузит
;  свой тайлсет в тот же диапазон). vec_ct_ending на входе в финал меняет ДВА поля —
;  теперь это не операнды команд, а ПЕРВАЯ ЗАПИСЬ ТАБЛИЦЫ vbt8_tab (см. ниже): счётчик
;  тайлов 5 -> 0x28 (диапазон 0x40-0x67) и адрес обработчика vbt8_brick -> vec_end_tile.
;  Имена меток vbt8_ecp/vbt8_ecj и смещения +1 сохранены, поэтому vec_ct_ending/vec_ct_base
;  и гейт bonus_ending_gate.js не менялись. Запись стоит ПЕРВОЙ намеренно: в концовке её
;  диапазон накрывает 0x40-0x67 и обязан перебить записи ножа/кирки/рычага/ступеней,
;  а таблица сканируется сверху вниз, первое попадание побеждает.
;  [история, 2026-07-30] Двухцветный путь ловил тут 0x8B и 0x88, считая их кинжалом и
;  киркой, — а это ГЕМЫ: getTileFromID переводит map-код предмета на полу в tilesCuchillo
;  -> 0x4B и tilePico -> 0x4C, тогда как 0x86-0x8B — шесть ЦВЕТОВ ГЕМА (tilesGemas).
;  Гем резался пополам, верх idx6 красный / низ idx12 белый. Это была ПЕРВАЯ половина
;  жалобы «испорченный гем» (вторая — блеск с чужой p2, см. vec_blit_brillo).
;  === НОЖ (0x45-0x4A ПОЛЁТ, 0x4B НА ПОЛУ) И КИРКА (0x4C) — задача #40, 2026-08-03 =======
;  ЭТАЛОН СНЯТ С КАРТРИДЖА, НЕ ПОДОБРАН: legacy/msx/kvalley_z80.rom в headless-WebMSX
;  (MCP msx-emu), геймплей, MSX color table = VRAM 0x0000+тайл*8 (все три банка совпали,
;  сверено на 0x0200/0x0A00/0x1200). Строки цвета (старший ниббл = перо):
