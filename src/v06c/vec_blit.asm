	ld	a, 0x090
	or	c
	ld	(kv_knA_p2), a
	ld	a, 0x088
	or	c
	ld	(kv_knB_p2), a
	ld	a, 0x080
	or	c
	ld	(kv_knC_p2), a
	ld	a, 0x008
	or	c
	ld	(kv_knD_p2), a
	ld	a, 0x010
	or	c
	ld	(kv_knE_p2), a
	ld	d, 0
	ld	hl, kv_stone_scheme
