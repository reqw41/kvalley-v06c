;  (7 Б вместо 14 Б указателей). 0x49/0x4A/0x4B делят одну программу — у них одна граница.
;  Клоб A,H,L; BC/DE целы (ADD_A_HL их не трогает), а C держит столбец, который нужен
;  vbt8_seg. Прыгаем в vbt8_seg напрямую: он ждёт ровно HL = программа.
kv_knife_disp:
	ld	hl, kv_knoff
	call	ADD_A_HL
	ld	a, (hl)
	ld	hl, kv_pg_knA
	call	ADD_A_HL
	jp	vbt8_seg
kv_knoff:
	db	0, 5, 10, 15, 20, 20, 20	; 0x45,0x46,0x47,0x48,0x49,0x4A,0x4B
kv_pg_knA:	; 0x45: лезвие строки 0-2, рукоять строки 3-7
	db	0x09C	; p1: 8 строк нулём
	db	0x00A	; p2: строки 0-2 шейпом (лезвие idx2)
kv_knA_p2:
	db	0x090	; p2: строки 3-7 — ПАТЧ (0x090 ноль = idx8 / 0x092 шейп = idx10)
	db	0x008	; p0: строки 0-2 нулём
	db	0x092	; p0: строки 3-7 шейпом (рукоять)
kv_pg_knB:	; 0x46: лезвие строки 0-4, рукоять строки 5-7
	db	0x09C	; p1: 8 строк нулём
	db	0x012	; p2: строки 0-4 шейпом
kv_knB_p2:
	db	0x088	; p2: строки 5-7 — ПАТЧ
	db	0x010	; p0: строки 0-4 нулём
	db	0x08A	; p0: строки 5-7 шейпом
kv_pg_knC:	; 0x47: лезвие строки 0-6, рукоять строка 7
	db	0x09C	; p1: 8 строк нулём
	db	0x01A	; p2: строки 0-6 шейпом
kv_knC_p2:
	db	0x080	; p2: строка 7 — ПАТЧ
	db	0x018	; p0: строки 0-6 нулём
	db	0x082	; p0: строка 7 шейпом
kv_pg_knD:	; 0x48: рукоять строки 0-2, лезвие строки 3-7
	db	0x09C	; p1: 8 строк нулём
kv_knD_p2:
	db	0x008	; p2: строки 0-2 — ПАТЧ
	db	0x092	; p2: строки 3-7 шейпом (лезвие idx2)
	db	0x00A	; p0: строки 0-2 шейпом (рукоять)
	db	0x090	; p0: строки 3-7 нулём
kv_pg_knE:	; 0x49/0x4A/0x4B: рукоять строки 0-4, лезвие строки 5-7
	db	0x09C	; p1: 8 строк нулём
kv_knE_p2:
	db	0x010	; p2: строки 0-4 — ПАТЧ
	db	0x08A	; p2: строки 5-7 шейпом (лезвие idx2)
	db	0x012	; p0: строки 0-4 шейпом (рукоять)
	db	0x088	; p0: строки 5-7 нулём
kv_pg_lvbot:	; 0x5E, подставка рычага: строка 0 сплошной красный, строки 1-7 перо на чёрном
	db	0x001, 0x09A	; p1: строка 0 горит + строки 1-7 шейпом
	db	0x001, 0x09A	; p2: то же самое — перо и фон строки 0 в idx6
	db	0x09C	; p0: 8 строк нулём
;  kv_pg_pico: КИРКА 0x4C, двухцветная. idx = p0*8 + p1*4 + p2*2:
;    пиксель есть в маске -> p1=1, p2=1 -> idx6  КРАСНЫЙ (как кожа героя)
;    пикселя в маске нет  -> p1=0, p2=1 -> idx2  СЕРЫЙ (как одежда героя)
;  Фон клетки везде idx0 чёрный — все три плоскости тайл ЗАДАЁТ, а не накладывает, поэтому
;  цвет кирки не зависит от того, что было под ней.
;  ЕДИНСТВЕННЫЙ ТАЙЛ С МАРКЕРОМ ИСТОЧНИКА: цвет задан ПОПИКСЕЛЬНО (kv_pico_p1), к сегментам
;  строк не сводится в принципе — строки 2,4,5,6 маски являются собственными подмножествами
;  паттерна. Движок это и умеет: «взять источник отсюда», дальше та же копия 8 строк.
kv_pg_pico:
	db	0x040
	dw	kv_pico_p1	; p1: источник — маска, а не шейп
	db	0x09E	; p1: 8 строк копией маски
	db	0x09E	; p2: 8 строк шейпом (сам силуэт)
	db	0x09C	; p0: 8 строк нулём (иначе idx10/idx14)
;  [удалено 2026-08-04] vbt8_stair2/vbt8_stair/vbt8_stwh (48 Б), vbt8_lever/vbt8_lvup/
;  vbt8_lvbot (135 Б), vbt8_pico (33 Б) — шесть петель «позови vbt8_ad, потом столько-то
;  строк такой-то заливкой». Ровно это теперь описывают программы выше, а исполняет
;  vbt8_seg. Заодно ушла vbt8_red («весь тайл в idx6»): переходов на неё не осталось.
;  [удалено 2026-08-03] vbt8_knife — двухцветная петля ножа (белое лезвие + рукоять по
;  маске kv_knife_rows) и сама таблица масок. Нож стал сплошным серым idx2, его рисует
;  ШТАТНЫЙ путь vbt8_planes с планом 0x03; вся история решения — в шапке у диспетчера
;  0x45-0x4C выше. Освободило 75 Б.
;  kv_pico_p1: КАКИЕ ПИКСЕЛИ КИРКИ КРАСНЫЕ. Бит=1 -> этот пиксель идёт и в p1 (idx6
;  красный), бит=0 -> только в p2 (idx2 серый). Порядок строк сверху вниз, как в паттерне.
;  ПОЧЕМУ ЭТО ДЁШЕВО, ХОТЯ ЦВЕТ ЗАДАН ПОПИКСЕЛЬНО: у кирки p0 пуста во всех строках, а p2
;  совпадает с формой байт в байт — значит хранить надо ОДНУ маску (8 Б), а не три (24 Б),
;  и петля остаётся прежней, меняется лишь указатель источника.
;  Маска — подмножество паттерна (20 18 0C 0C 1A 33 61 C0), проверено побитно: рисовать
;  цветом там, где формы нет, бессмысленно — тайл задаёт все три плоскости, и «пустой»
;  пиксель обязан остаться idx0 чёрным.
;  РИСОВАЛОСЬ В tools/gfx/tile_editor.js (страница снимает паттерны из живой сборки и
;  выдаёт готовые маски). Владелец: «это похоже на то что несет в руках герой когда берет
;  кирку» — красное идёт по верхней диагонали и правому лучу, серое по левому лучу и низу.
kv_pico_p1:
	db	0x020, 0x018, 0x008, 0x00C, 0x002, 0x003, 0x001, 0x000
;  [удалено 2026-07-31] vbt8_item — «предмет целиком в idx6» (p1+p2 = шейп, p0 гасим).
;  Ровно тот же результат даёт ШТАТНЫЙ путь при vbt8_wf=0x80 / vbt8_c8=0x03, поэтому и
;  гемы (kv_gem_planes), и рычаг 0x5C теперь идут через него, а отдельная петля не нужна.
;  ПОРЯДОК ЗАПИСЕЙ РАЗНЫЙ, РЕЗУЛЬТАТ ТОТ ЖЕ: vbt8_item гасил p0 построчно вперемешку с
;  чтением, штатный путь сперва раскатывает p1, потом p2 (оба ЧИТАЮТ p0, который ещё
;  держит шейп от vbt_core), и только затем гасит p0. Пруф: tools/verify/gem_colors.js —
;  рендер всех комнат старым и новым ПЗУ, различаются РОВНО клетки гемов.
;  Таблица плоскостей гемов 0x86-0x8B. Бит7=p1 шейп, бит0=p2 шейп, бит1=гасить p0.
;  idx палитры = (p0<<3)|(p1<<2)|(p2<<1); цвета — vec_pal + рантайм-правки vec_brillo_pal:
;    тайл 0x86 (MSX 4 синий)     p0+p1     -> idx12 БЕЛЫЙ 0FFh
;    тайл 0x87 (MSX 7 циан)      p0+p2     -> idx10 второй тон камня (kv_stone_tone2:
;                                            057h красн / 0E8h ЛАЗУРЬ / 077h золото / 03Fh жёлт)
;    тайл 0x88 (MSX D пурпурный) p1+p2     -> idx6  КРАСНЫЙ 05Fh
;    тайл 0x89 (MSX A жёлтый)    p0        -> idx8  первый тон камня (kv_stone_scheme:
;                                            077h ЗОЛОТО / 0D2h синий / 056h красн / 01Ch зелён)
;    тайл 0x8A (MSX 2 зелёный)   p1 + гашение p0 -> idx4 ЗЕЛЁНЫЙ 030h (SWAP: был idx14)
;    тайл 0x8B (MSX E серый)     p2        -> idx2  СЕРЫЙ 0ADh (#b6b6aa; до 2026-08-04
;                                            0F6h — тот отдавал в сирень, см. vec_pal)
;  ЗАНЯТЫ ВСЕ ШЕСТЬ, кроме двух комбинаций: cc000 (чёрный фон, гем был бы невидим) и
;  cc111 = idx14 — слот АУРЫ (SWAP 2026-08-16; раньше аура была idx4). Аура мерцает по
;  vec_brillo_cols (чёрн/бел/жёлт/жёлт, фаза (timer>>1)&3, полный цикл 8 кадров), то есть
;  ЧЕТВЕРТЬ ВРЕМЕНИ ОНА ЧЁРНАЯ. idx4 теперь стабильный зелёный — третья одноплоскостная
;  мумия (p1) и рама/гем 0x8A.
kv_gem_planes:
	db	0x080, 0x001, 0x083, 0x000, 0x082, 0x003
;  [удалено 2026-08-03] kv_knife_rows — маски строк «второго тона» ножа. Нож одноцветный,
;  кирка красится своей петлёй vbt8_pico по фиксированной границе строк 0-3 / 4-7.
;  2a vbt8_brick: кирпич 0x40-0x44 двухцветный по строкам. p0 уже = шейп (vbt_core). Маска
;  033h (MSB=строка0): бит=0 -> золото (p0=шейп, p1=p2=0 -> idx8); бит=1 -> красный
;  (p0=0, p1=p2=шейп -> idx6 по AURA-раскладке; [история] до AURA красный был idx4 через
;  один p1). C=col, vbt8_e=255-row*8 на входе. Клоб A,B,C,D,E,H,L.
vbt8_brick:
	ld	a, c	; HL = p0 (0x80+col : E)
	add	a, 0x80
	ld	h, a
	ld	a, (vbt8_e)
	ld	l, a
	ld	a, c	; DE = p1 (0xA0+col : E)
	add	a, 0x0A0
	ld	d, a
	ld	a, (vbt8_e)
	ld	e, a
	ld	c, 0x033	; маска строк (MSB=строка0)
	ld	b, 8
vbt8_brk_l:
	ld	a, c	; carry = бит строки (1 -> красн)
	add	a, a
	ld	c, a
	jp	c, vbt8_brk_red
	xor	a	; золото-строка: p1=0
	ld	(de), a
	ld	a, d	; AURA: p2=0 тоже
	add	a, 0x20
	ld	d, a
	xor	a
	ld	(de), a
	ld	a, d
	sub	0x20
	ld	d, a
	jp	vbt8_brk_nx
vbt8_brk_red:
;  ВТОРОЙ ТОН ПЕРЕЕХАЛ В idx10 (2026-07-30). Было: p1=p2=шейп, p0=0 -> idx6, а idx6 это
;  КОЖА ГЕРОЯ. Из-за общего слота второй тон кирпича нельзя было красить по схеме уровня,
;  не перекрасив заодно героя, — и обе расцветки схлопнули в одну (kv_stone_scheme была
;  0xBF x4). Теперь красная строка = p0+p2 (idx10): p0 остаётся шейпом, добавляем p2.
;  Слот idx10 почти свободен — замер по игровому экрану даёт 0.30% пикселей («спрайт p2
;  поверх кирпича»), тогда как idx6 занимал 4.29%. Кожа героя снова чистая.
	xor	a	; p1 = 0
	ld	(de), a
	ld	a, d	; p2 = шейп -> вместе с p0 даёт idx10
	add	a, 0x20
	ld	d, a
	ld	a, (hl)
	ld	(de), a
	ld	a, d
	sub	0x20
	ld	d, a
vbt8_brk_nx:
	dec	l
	dec	e
	dec	b
	jp	nz, vbt8_brk_l
	ret
vbt_core:
;  tile render mode from vec_tilemode (предвычислен эагерно при загрузке цвета,
;  Фаза C1): байт = white(bit7) | mix-slot(биты6-3) | mode(биты2-0). mode: 0=blank
;  1=pattern 2=inverted 3=solid 4=mixed. FF (не вычислен) -> рисуем blank (как
;  baseline на пустом col_shadow); в геймплее не встречается (тайлсет грузится до блита).
	ld	h, 255&(vec_tilemode>>8)	; кэш режимов 1x256 (рабочая RAM)
	ld	a, (vw_byte)	; HL = &mode[tile]
	ld	l, a
	ld	a, (hl)
	cp	0x0FF
	jp	nz, vbtc_ok
	xor	a	; FF -> режим 0 (пусто)
vbtc_ok:
;  [задача #55] КЛАДЁМ ПОЛНЫЙ БАЙТ, А НЕ `and 7`: биты 6-3 у mixed-тайла — НОМЕР СЛОТА
;  построчного цвета, и он нужен vbt_mix. Раньше слот искала линейным сканом vec_slot_of
;  по таблице vec_mixtiles; обе сняты (−43 Б), режим срезается уже у диспетчера ниже.
	ld	(vw_tmp), a
	ld	a, (vw_byte)
	ld	l, a
	ld	h, 0
	add	hl, hl	; tile*8
	add	hl, hl
	add	hl, hl
	call	pat_base	; DE=база по диапазону tile (шаг3): maze/font
	add	hl, de
;  -> work-RAM, меню -> p2 vec_pat_shadow
;  (3 SCREEN2 банка байт-идентичны в геймплее)
	ld	a, c	; D = hi плана 0 (0x80+col)
	add	a, 0x80
	ld	d, a
	ld	a, b	; E = 255-row*8 (младший байт)
	add	a, a
	add	a, a
	add	a, a
	cpl
	ld	e, a
	ld	b, 8
	ld	a, (vw_tmp)	; диспетчер по режиму (биты 0-2; 6-3 = слот, их и срезаем)
	and	0x07
	jp	z, vbt_blank
	cp	2	; 1 -> обычный
	jp	c, vbt_row
	jp	z, vbt_inv	; 2 -> инверсный
	cp	4	; 4 -> построчно-смешанный; 3 (и метка карты 5) -> сплошной
	jp	z, vbt_mix
vbt_solid:
	ld	a, 0x0FF
	jp	vbt_fill8
vbt_blank:
	xor	a
vbt_fill8:	; развёрнутая заливка константой, 8 строк
	ld	(de), a
	dec	e
	ld	(de), a
	dec	e
	ld	(de), a
	dec	e
	ld	(de), a
	dec	e
	ld	(de), a
	dec	e
	ld	(de), a
	dec	e
	ld	(de), a
	dec	e
	ld	(de), a
	ret
vbt_inv:
	ld	a, (hl)
	cpl
	inc	hl
	ld	(de), a
	dec	e
	dec	b
	jp	nz, vbt_inv
	ret
; POP-блиттер (техника OldTower): SP = данные паттерна, POP читает 2 строки за
; 11 тактов. Безопасно: блиттер работает ТОЛЬКО из композитора (ISR, прерывания сняты).
vbt_row:	; DE=адрес fb, HL=указатель паттерна
	di	; весь пролог должен быть атомарным:
	ld	(vbt_pp), hl	; блит ISR-дренажа перезаписал бы
	ld	hl, 0	; vbt_pp/vw_paddr (main заблитил бы
	add	hl, sp
	ld	(vw_paddr), hl
	ld	hl, (vbt_pp)	; клетку ЧУЖИМ паттерном)
	ld	sp, hl
	ex	de, hl	; HL = адрес fb
	pop	de	; строки 0,1
	ld	(hl), e
	dec	l
	ld	(hl), d
	dec	l
	pop	de	; строки 2,3
	ld	(hl), e
	dec	l
	ld	(hl), d
	dec	l
	pop	de	; строки 4,5
	ld	(hl), e
	dec	l
	ld	(hl), d
	dec	l
	pop	de	; строки 6,7
	ld	(hl), e
	dec	l
	ld	(hl), d
	ld	hl, (vw_paddr)	; восстановить SP
	ld	sp, hl
	ld	a, (vec_isr_depth)	; внутри ISR: держим DI
	or	a
	jp	nz, vbt_noei
	ei
vbt_noei:
	ret
; Смешанный тайл (строки разного цвета, напр. лестница: верх чёрный, остальное белое):
; на каждую строку берём байт цвета (тень параллельна: цвет = паттерн + 0x1B00)
; и составляем out = (fg видим ? pat : 0) | (bg видим ? ~pat : 0).
vbt_mix:
;  [ЗАДАЧА #55, 2026-08-07] СЛОТ ПОСТРОЧНОГО ЦВЕТА ЛЕЖИТ В САМОМ БАЙТЕ РЕЖИМА (биты 6-3),
;  поэтому адрес слота — это одна маска, а не поиск. Было: `slot = vec_slot_of(tile-0x50)`,
;  линейный скан 15-байтной vec_mixtiles. Обе сняты (28 Б скана + 15 Б таблицы), и с ними
;  ушла развилка vbt_mix_no (5 Б) — «слота нет» стало невозможным состоянием: слот кладёт
;  тот же генератор (tools/gfx/msx2vec.py), который ставит режим 4, из одного списка.
;  ЕДИНСТВЕННЫЕ, КОМУ РАНЬШЕ ДОСТАВАЛСЯ slot==0, — ТАЙЛЫ КАРТЫ ДОЛИНЫ 0xC2/0xC3 (замер:
;  168 и 132 попадания за прогон). Их режим 0x74 (метка карты 0x70 в поле счётчика) даёт
;  теперь `and 0x78` = 0x70, то есть чтение слота 15 — адрес В ПРЕДЕЛАХ vec_mixbuf, чужая
;  память не читается. Картинка не меняется: карта уходит в vbt8_mapt, а он переписывает
;  ВСЕ ТРИ плоскости из сырого паттерна, вклад vbt_core у неё был мёртв и при slot==0.
;  Поле «счётчик строк» у mix-тайлов было нулевым реликтом рантайм-сведения (снято #27),
;  так что номер слота положен на пустое место, а не отнят у живого признака.
;  ПЕРЕНОСА НЕТ: слот*8 <= 15*8 = 0x78, база vec_mixbuf-8 = 0x0078, сумма 0x0F0 < 0x100 —
;  старший байт адреса нулевой, поэтому сложение однобайтное. DE (приёмник p0) больше не
;  затирается => прежние push de/pop de (C1-fix) не нужны.
	push	hl	; HL = указатель паттерна, его затирает расчёт адреса слота
	ld	a, (vw_tmp)	; полный байт режима: биты 6-3 = слот
	and	0x078	; = слот*8
	add	a, 255&(vec_mixbuf-8)
	ld	l, a
	ld	h, 0
	ld	(vbt_mc), hl
	pop	hl
vbt_mix_l:
	push	hl
	ld	hl, (vbt_mc)
	ld	c, (hl)
	inc	hl
	ld	(vbt_mc), hl
	pop	hl
	ld	a, (hl)	; байт паттерна
	inc	hl
	ld	(vw_tmp), a
	ld	a, c	; fg видим?
	and	0x0F0
	cp	0x20
	ld	a, (vw_tmp)
