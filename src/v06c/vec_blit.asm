	add	a, a	; x32
	add	a, a
	add	a, a
	add	a, a
	add	a, a
	ld	hl, MapaRAM
	call	ADD_A_HL	; HL = база ряда 0 окна (ProtaRoom*32)
	xor	a	; всё окно: столбцы 0..31
	ld	(vec_nr_c0), a
	ld	a, 32
	ld	(vec_nr_cend), a
vec_nr_win:	; HL = база ряда 0 окна карты; vec_nr_c0/vec_nr_cend = столбцы [c0,cend)
	di
	ld	a, (vec_isr_depth)	; сохранить реальную глубину (DI: push/pop безопасен)
	push	af
	ld	a, 1	; форсируем !=0: vbt_row держит DI всё время
	ld	(vec_isr_depth), a
	ld	(vec_nr_ptr), hl
	ld	a, 1	; экранные ряды 1..22 (ряд 0 = HUD, не трогаем)
	ld	(vec_nr_srow), a
vec_nr_row:
;  _COOPSND: своего тика звука здесь БОЛЬШЕ НЕТ (2026-07-30). Ряд — это 4 или 32 блита
;  клетки, а тик теперь стоит в самой vec_blit_tile, то есть считается по фактической
;  работе и покрывает заодно карту долины и шторку. Два счётчика на один и тот же ряд
;  дали бы двойной учёт и разгон темпа.
	ld	a, (vec_nr_c0)	; ряд начинается с первого столбца окна
	ld	(vec_nr_col), a
vec_nr_cloop:
