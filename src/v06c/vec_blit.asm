;  Тайл держим в B: он свободен (ни один обработчик его на входе не читает — ряд им не
;  нужен, все считают адрес из C и vbt8_e), а перечитывать vw_byte каждый виток дорого.
vbt8_disp:
	ld	a, (vw_byte)
	ld	b, a
	ld	hl, vbt8_tab
vbt8_dl:
	ld	a, b
	sub	(hl)	; тайл ниже начала диапазона -> и ниже всех следующих
	inc	hl	; (inc hl флаги не трогает — это INX H)
	jp	c, vbt8_chk_map
	cp	(hl)	; вошёл в счётчик -> попадание
	jp	c, vbt8_dhit
	inc	hl
	inc	hl
	inc	hl
	jp	vbt8_dl
vbt8_chk_map:
;  --- КАРТА ПИРАМИД: метка РЕЖИМ 5 в vec_tilemode ставится vec_map_whiteforce для тайлов
;  0xC0-0xE7 с MSX-цветом «шейп на БЕЛОМ фоне» (пирамиды 6F/8F/9F и рамка GOAL 4F/6F).
;  Штатный путь красил бы их сплошным idx8 (шейп потерян, оранжевая плашка). Здесь — свой
;  двухплановый блит, см. vbt8_mapt.
;  [ЗАДАЧА #55, 2026-08-07] МЕТКА ПЕРЕЕХАЛА ИЗ ПОЛЯ СЧЁТЧИКА В ПОЛЕ РЕЖИМА. Была «счётчик
;  = 14», то есть биты 6-3 == 0x70. С этой задачи биты 6-3 у mixed-тайла несут НОМЕР СЛОТА,
;  и слот 14 (тайл 0x82, верхняя площадка лестницы) давал ровно 0x70 — тайл лабиринта
;  уезжал в блиттер карты и рисовался красным. Ловится гейтом coltab_frame_parity: 207
;  тиков расхождения, клетки лестниц. Режимы 5-7 не заняты никем (0 blank, 1 pat, 2 ~pat,
;  3 solid, 4 mix), поэтому метка живёт там и с полем слота не пересекается В ПРИНЦИПЕ.
;  Диспетчер vbt_core доводит режим 5 до vbt_solid — что бы он ни положил в p0, vbt8_mapt
;  ниже переписывает ВСЕ ТРИ плоскости из сырого паттерна.
	ld	h, 255&(vec_tilemode>>8)
	ld	a, (vw_byte)
	ld	l, a
	ld	a, (hl)
	and	0x07
	cp	0x05
	jp	z, vbt8_mapt
vbt8_p1:
;  --- p1 = шейп если тайл белый, иначе 0 ---
	ld	a, c	; HL = верх источника p0
	add	a, 0x80
	ld	h, a
	ld	a, (vbt8_e)
	ld	l, a
	ld	a, c	; DE = верх приёмника p1
	add	a, 0x0A0
	ld	d, a
	ld	a, (vbt8_e)
	ld	e, a
	ld	a, (vbt8_wf)
	call	vbt8_wrow
vbt8_p2:
;  --- p2 = шейп если cc бит0, иначе 0 ---
	ld	a, c	; HL = верх источника p0
	add	a, 0x80
	ld	h, a
	ld	a, (vbt8_e)
	ld	l, a
	ld	a, c	; DE = верх приёмника p2
	add	a, 0x0C0
	ld	d, a
	ld	a, (vbt8_e)
	ld	e, a
	ld	a, (vbt8_c8)
	and	1
	call	vbt8_wrow
;  --- p0: очистить если cc бит1 ---
	ld	a, (vbt8_c8)	; бит1=0 -> p0 хранит шейп
	and	2
	ret	z
	ld	a, c	; DE = верх приёмника p0
	add	a, 0x80
	ld	d, a
	ld	a, (vbt8_e)
	ld	e, a
	xor	a
;  peephole: здесь был `call vbt8_wrow / ret`. Хвостовой вызов свёлся к прыжку на
;  СЛЕДУЮЩУЮ инструкцию, поэтому и прыжок снят — просто проваливаемся в vbt8_wrow.
;  (-4 Б суммарно, -17 тактов.) ОСТОРОЖНО: vbt8_wrow обязана и дальше идти сразу за
;  этим местом; если её будут переносить — вернуть явный `jp`.
;  vbt8_wrow: A=флаг (0 -> очистить 8 строк нулём; !=0 -> копировать HL(p0 src)->DE, 8 строк).
;  dec l/dec e построчно (low-байт адреса = Y). Клоб. A,B,HL,DE.
vbt8_wrow:
	or	a
	jp	z, vbt8_clr
	ld	b, 8
vbt8_cp:
	ld	a, (hl)
	ld	(de), a
	dec	l
	dec	e
	dec	b
	jp	nz, vbt8_cp
	ret
vbt8_clr:
	ld	b, 8
	xor	a
vbt8_cl:
	ld	(de), a
	dec	e
	dec	b
	jp	nz, vbt8_cl
	ret
;  ============ СЕГМЕНТНАЯ ПРОГРАММА ТАЙЛА (расширенный формат плана, 2026-08-04) ========
;  ЧТО ЭТО. Однобайтный план vbt8_planes умеет на плоскость только «шейп или ноль», и
;  источником у него всегда p0 после vbt_core. Рычагу, ступеням и кирке этого не хватало —
;  каждому написали свою петлю (283 Б на шесть тайлов). Сегментная программа выражает их
;  все ОДНИМ движком: описание тайла = список сегментов «столько-то строк такой-то заливкой»
;  на каждую из трёх плоскостей, источник — СЫРОЙ ПАТТЕРН.
;  БАЙТ СЕГМЕНТА:
;    биты 0-1  чем заполнять: 0 = ноль, 1 = 0xFF, 2 = копия шейпа, 3 = ~шейп
;    биты 2-4  число строк минус 1 (1..8)
;    бит  6    в сегментном байте не встречается (см. маркер источника ниже)
;    бит  7    ПОСЛЕДНИЙ сегмент этой плоскости (иначе следом идёт ещё один)
;  Плоскости идут в программе строго p1, p2, p0 — порядок не важен, потому что все три
;  читают паттерн и ни одна не читает чужую плоскость (у штатного пути наоборот: p1/p2
;  копируют p0, и порядок КРИТИЧЕН).
;  МАРКЕР ИСТОЧНИКА: байт 0x40 перед сегментами плоскости означает «следующие 2 Б — адрес
;  источника вместо паттерна». Нужен ровно кирке: её p1 задан ПОПИКСЕЛЬНОЙ маской
;  kv_pico_p1, к строкам она не сводится (см. блок у маски). Значение 0x40 сегментом быть
;  не может: в сегменте бит6 всегда 0.
;  ПОЧЕМУ ИСТОЧНИК — ПАТТЕРН, А НЕ ПЛОСКОСТЬ 0. Штатные шаги vbt8_p1/p2 читают шейп из p0,
;  куда его положил vbt_core. Но vbt_core рисует ПО РЕЖИМУ тайла (vec_tilemode): у рычага
;  режим «mixed» и в p0 приезжает НЕ шейп, а построчная смесь (замер: у тайла 0x5D в p0
;  лежало 7E FF FF FF FF FF FF FF вместо 7E E7 C3 C3 E7 E7 E7 FF). Поэтому эти тайлы берут
;  паттерн НАПРЯМУЮ и задают все три плоскости сами.
;  vbt8_seg: HL = программа. C = столбец, vbt8_e = верхняя строка, vw_byte = тайл.
;  Клоб A,B,D,E,H,L и vbt8_c8/vbt8_wf (см. ниже); C цел.
vbt8_seg:
;  УКАЗАТЕЛЬ ПРОГРАММЫ ЖИВЁТ В vbt8_pg = vbt8_c8/vbt8_wf (нулевая страница, 0 новых байт
;  ОЗУ). Это не экономия на спичках, а факт: цвет-код и white-флаг читают ТОЛЬКО шаги
;  vbt8_p1/p2/p0 и vbt8_mapt, а сегментный тайл туда не попадает никогда. Тот же приём и по
;  той же причине уже применён в vbt8_mapt (маска строк лежит в vbt8_wf).
	ld	(vbt8_pg), hl
	ld	a, 0x0A0	; p1
	call	vbt8_pl
	ld	a, 0x0C0	; p2
	call	vbt8_pl
	ld	a, 0x80	; p0 — хвостом, ret плоскости вернёт из блита
vbt8_pl:	; A = смещение плоскости; проиграть её сегменты
	call	vbt8_ad	; HL = паттерн тайла, DE = верх приёмника
	push	de	; DE освобождаем: указатель источника разбираем в нём
	ex	de, hl	; DE = паттерн (источник по умолчанию)
	ld	hl, (vbt8_pg)
	ld	a, (hl)
	cp	0x40	; маркер «источник задан программой»
	jp	nz, vbt8_pl1
	inc	hl
	ld	e, (hl)
	inc	hl
	ld	d, (hl)	; DE = внешний источник (маска)
	inc	hl
	ld	(vbt8_pg), hl
vbt8_pl1:
	ex	de, hl	; HL = источник
	pop	de	; DE = приёмник
vbt8_sgs:	; очередной сегмент плоскости
	push	hl	; источник цел, HL нужен под программу
	ld	hl, (vbt8_pg)
	ld	a, (hl)
	inc	hl
	ld	(vbt8_pg), hl
	pop	hl
;  БАЙТ СЕГМЕНТА ДОЖИВАЕТ НА СТЕКЕ до конца сегмента: в нём бит7 «плоскость кончилась»,
;  а регистров под него нет (A под разбор, B под счётчик, C столбец, DE приёмник,
;  HL источник). Снимает его vbt8_sgd — по одному push на сегмент, ровно.
	push	af
	and	0x1C	; биты 2-4 = число строк минус 1
	rrca
	rrca
	inc	a
	ld	b, a
	pop	af
	push	af
	and	3	; чем заполнять
	jp	z, vbt8_sg0
	dec	a
	jp	z, vbt8_sg1
	dec	a
	jp	z, vbt8_sgc
	jp	vbt8_sgi
;  Четыре одинаковые петли «B строк, HL(источник) -> DE(приёмник плоскости)», отличаются
;  лишь тем, ЧТО кладут. HL идёт ВПЕРЁД (inc hl, паттерн лежит сверху вниз), DE — ВНИЗ ПО
;  ЭКРАНУ (dec e, младший байт адреса = 255-Y). Оба указателя двигаются ВСЕГДА, чтобы
;  сегменты одной плоскости ложились подряд без пересчёта адресов.
vbt8_sg0:	; B строк нулём
	xor	a
	jp	vbt8_sgf
vbt8_sg1:	; B строк единицами (плоскость «горит» на всей ширине тайла)
	ld	a, 0x0FF
vbt8_sgf:
	ld	(de), a
	inc	hl
	dec	e
	dec	b
	jp	nz, vbt8_sgf
	jp	vbt8_sgd
vbt8_sgc:	; B строк копией шейпа
	ld	a, (hl)
	ld	(de), a
	inc	hl
	dec	e
	dec	b
	jp	nz, vbt8_sgc
	jp	vbt8_sgd
vbt8_sgi:	; B строк инверсией шейпа
	ld	a, (hl)
	cpl
	ld	(de), a
	inc	hl
	dec	e
	dec	b
	jp	nz, vbt8_sgi
vbt8_sgd:	; сегмент отработан: бит7 байта решает, кончилась ли плоскость
	pop	af
	or	a
	jp	p, vbt8_sgs
	ret
;  vbt8_ad: A = смещение плоскости (0x80 p0 / 0x0A0 p1 / 0x0C0 p2) -> DE = ВЕРХ приёмника
;  этой плоскости, HL = начало паттерна тайла. C = столбец, vbt8_e = верхняя строка.
;  Зовётся по разу на плоскость, поэтому и указатель паттерна переустанавливается здесь.
vbt8_ad:
	push	af
	ld	a, (vw_byte)
	ld	l, a
	ld	h, 0
	add	hl, hl	; tile*8
	add	hl, hl
	add	hl, hl
	call	pat_base	; DE = база по диапазону тайла (HL и BC сохраняет)
	add	hl, de
	pop	af
	add	a, c
	ld	d, a
	ld	a, (vbt8_e)
	ld	e, a
	ret
;  ================== ТАБЛИЦА ДИАПАЗОНОВ ТАЙЛОВ И РАЗБОР ПОПАДАНИЯ ====================
;  Цикл сканирования — vbt8_disp (в прологе, чтобы туда проваливаться без прыжка);
;  почему таблица, а не цепочка `sub/cp/jp`, и как читается слово действия — см. там же.
;  ПОРЯДОК ЗАПИСЕЙ ЗНАЧИМ ТОЛЬКО ДЛЯ ПЕРВОЙ: в концовке её диапазон разрастается до
;  0x40-0x67 и обязан перебить нож/кирку/рычаг/ступени (сканируем сверху вниз).
vbt8_tab:
vbt8_ecp:
	db	0x40	; ПАТЧ-САЙТ vbt8_ecp+1 (= vbt8_ecj): в концовке 0x28, диапазон 0x40-0x67
vbt8_ecj:
	db	5
	dw	vbt8_brick	; ПАТЧ-САЙТ vbt8_ecj+1: в концовке vec_end_tile
;  НОЖ 0x45-0x4B — ПО-ПРЕЖНЕМУ ОДНА ЗАПИСЬ (задача #54, 2026-08-06). Была «0x45, 7 -> план 3»
;  = сплошной idx2 СЕРЫЙ; стало «0x45, 7 -> обработчик», а тот выбирает программу по номеру
;  тайла. РУКОЯТЬ жёлтая, ЛЕЗВИЕ прежнее серое; разбор — у kv_knife_disp ниже.
;  ПОЧЕМУ ОБРАБОТЧИК, А НЕ ПЯТЬ ОТДЕЛЬНЫХ ЗАПИСЕЙ (первая версия правки была именно такой).
;  Границ строк у ножа пять, и напрашивались пять записей на 0x45/0x46/0x47/0x48/0x49-0x4B.
;  Но ТАБЛИЦА СКАНИРУЕТСЯ ЛИНЕЙНО СВЕРХУ ВНИЗ, и +4 записи удлиняют скан ВСЕМ тайлам, чья
;  запись лежит ниже, а также всем, кто доходит до замыкающей 0xFF. ЗАМЕР (детерминированная
;  первая отрисовка лабиринта пирамиды 1, такты внутри блиттера): лестница 0x75, которой в
;  таблице нет вовсе и которая поэтому сканирует её целиком, дорожала 3260 -> 3628 т, то есть
;  +368 т НА КАЖДУЮ отрисовку ни за что; тем же +368 платили 0x5C/0x5D/0x63/0x64/0x67.
;  Обработчик стоит 23 Б против 16 Б у четырёх лишних записей — на 7 Б дороже в образе и
;  БЕСПЛАТЕН для всех прочих тайлов.
	db	0x45, 7
	dw	kv_knife_disp	; НОЖ: рукоять в жёлтый слот схемы, лезвие idx2 серое
	db	0x4C, 1
	dw	0x8000+kv_pg_pico	; КИРКА: серая рукоять + красная головка
	db	0x5C, 1
	dw	0x8000+kv_pg_lever	; рычаг вниз (мигающая сердцевина)
	db	0x5D, 1
	dw	0x8000+kv_pg_lvup	; рычаг вверх
	db	0x5E, 1
	dw	0x8000+kv_pg_lvbot	; подставка рычага
	db	0x5F, 2
	dw	0x8000+kv_pg_close1	; закрывающиеся кирпичи, верхний ряд
	db	0x61, 2
	dw	0x8000+kv_pg_close2	; закрывающиеся кирпичи, нижний ряд
;  ПРОЁМ ВОРОТ 0x63-0x67: потолок — «самый жёлтый слот схемы» (тот же, что рукоять ножа:
;  idx8 на схеме 0, idx10 на 1..3; патчит vbp_scheme). Ступени/лестница — те же сегменты,
;  что вход на финальном экране (kv_pg_door65/66 + kv_pg_stair).
	db	0x63, 2
kv_ceil_pl:
	dw	0	; ПОТОЛОК: план = жёлтый слот рукояти ножа (задача #54 / vbp_scheme)
	db	0x65, 1
	dw	0x8000+kv_pg_door65	; ступени справа — как на концовке
	db	0x66, 1
	dw	0x8000+kv_pg_door66	; верх ступеньки — как на концовке (не stair2)
	db	0x67, 1
	dw	0x8000+kv_pg_stair	; лестница проёма: белый на сером
	db	0x6C, 7
	dw	0x82	; РАМА И СТОЛБЫ ВОРОТ: p1 + гашение p0 -> idx4 ЗЕЛЁНЫЙ (аура уехала в idx14)
;  ВЕРХНЯЯ ПЛОЩАДКА ЛЕСТНИЦЫ (задача #55) — ЧЕТЫРЕ ОТДЕЛЬНЫЕ ЗАПИСИ, А НЕ ДВЕ ПО СЧЁТЧИКУ 2:
;  соседние тайлы пары просят РАЗНЫЕ программы (у левого и правого фон строки 1 не совпадает,
;  см. эталон у kv_pg_stA), а одна запись отдаёт обоим один адрес. Диспетчер «A&1 -> A или B»
;  обошёлся бы в 13 Б против 8 Б лишних записей, то есть дороже; он экономил бы 2 витка скана
;  тайлам 0x75+, но это ~90 тактов на клетку ОДИН РАЗ ЗА КОМНАТУ, а байты тут дефицит.
	db	0x73, 1
	dw	0x8000+kv_pg_stA	; верх лестницы ВНИЗ-ВПРАВО, левая клетка
	db	0x74, 1
	dw	0x8000+kv_pg_stB	; она же, правая клетка
	db	0x7B, 7
	dw	0x82	; второй диапазон рамы — та же зелень (idx4)
	db	0x82, 1
	dw	0x8000+kv_pg_stA	; верх лестницы ВНИЗ-ВЛЕВО, правая клетка (зеркало 0x73)
	db	0x83, 1
	dw	0x8000+kv_pg_stB	; она же, левая клетка (зеркало 0x74)
	db	0x86, 6
	dw	vbt8_gem	; шесть цветов сокровища, каждому свой план
	db	0x0FF, 1
	dw	vbt8_chk_map	; ЗАМЫКАЮЩАЯ: тайлы выше 0x8B обрывают скан здесь (и сам 0x0FF —
			; чтобы «непосчитанный» тайл не читал таблицу дальше конца)
vbt8_dhit:	; попадание: HL -> счётчик записи, A = тайл - первый (его ждёт обработчик)
	inc	hl
	ld	e, (hl)
	inc	hl
	ld	h, (hl)	; HL = слово действия
	ld	l, e
	ld	d, a	; A нужна для разбора вида записи -> тайл-первый прячем в D
	ld	a, h
	or	a
	jp	z, vbt8_dpl	; старший байт 0 -> план плоскостей
	jp	p, vbt8_dcode	; старший байт без бита7 -> адрес обработчика
	and	0x7F	; иначе СЕГМЕНТНАЯ ПРОГРАММА (образ живёт ниже 0x8000, бит7 свободен)
	ld	h, a
	jp	vbt8_seg
vbt8_dcode:
	ld	a, d
	jp	(hl)	; PCHL (i8080) — адрес обработчика
vbt8_dpl:
	ld	a, l	; старший байт нулевой -> младший это план плоскостей
vbt8_planes:
	ld	(vbt8_c8), a	; биты 0/1 читают шаги p2 и p0 (`and 1` / `and 2` их и выделяют)
	and	0x80
	ld	(vbt8_wf), a	; бит7 читает шаг p1
	jp	vbt8_p1
vbt8_gem:	; A = тайл-0x86; шесть сокровищ, каждому свой план из kv_gem_planes
