;  fg=6/8/9 красный или 4 синий, bg=F белый). Пишет ОБЕ плоскости построчно:
;    КРАСНАЯ строка: p0 = 0xFF, p1 = ~паттерн -> шейп idx8 КРАСНЫЙ, фон idx12 БЕЛЫЙ;
;    СИНЯЯ строка:   p0 = ~паттерн, p1 = 0xFF -> шейп idx4 СИНИЙ,  фон idx12 БЕЛЫЙ.
;  Синие строки — только буквы GOAL (тайлы 0xCC-0xCE, MSX-цвет 4F в строках 1-6; строки 0 и 7
