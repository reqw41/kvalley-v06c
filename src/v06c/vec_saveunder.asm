;  === RENDER-LIST save-under/restore-under (post-align: pre-align padding занят
;  === text_blit/blit_rect, поэтому весь новый код здесь, в хвостовом запасе < 0x6598).
;  vec_su_ptr: HL = адрес слота для vec_nsp_idx (=0xE000 + idx*256). Клоб A,B; сохр C,D,E.
vec_su_ptr:
	ld	a, (vec_nsp_idx)	; слот 256Б: H=0xE0+idx, L=0
	ld	l, 0
	add	a, 0x0E0	; H = 0xE0+idx (0xE0 = vec_spr_save>>8)
	ld	h, a
	ret
;  vec_su_restore: слот -> фон в fb (стирание спрайта БЕЗ порчи HUD/лестниц).
;  P1 POP-ХАЙДЖЕК (2026-07-28): SP = данные слота (подряд через все плоскости), POP читает
;  2 байта за 11т (~5.5т/Б против 26т/Б старой петли). P2: формат слота НИЗ-ВВЕРХ: lo0 = НИЗ
;  столбца (240-Y), данные по росту y -> fb пишем через inc l. ПРАВИЛА ХАЙДЖЕКА: DI на весь
;  хайджек, ЗАПРЕТ call/push внутри, SP восстановить на всех путях, ei-протокол vbt_row
;  (vec_isr_depth!=0 -> остаёмся DI, ei сделает эпилог ISR).
vec_su_restore:
	ld	hl, vsu_rcol	; ОПЕРАНД общего хвоста плоскостей (vsu_np): сюда возвращаться
	ld	(vsu_npj+1), hl
	ld	(vsu_colj+1), hl	; и ОПЕРАНД конца столбца общего тела (vsu_body)
	call	vec_su_ptr
	ld	a, (hl)	; невалиден -> нечего делать
	or	a
	ret	z
	jp	vtm_restore
;  H уже = страница слота: non-MASK — из vec_su_restore через vtm_restore;
;  MASK — восстановил vtm_mclr (A←H до ld hl,vtm_zclip). vec_su_ptr не нужен.
vsu_rcont:
	ld	a, h
	ld	hl, vsu_rdone
	ld	(vsu_done+1), hl
	ld	h, a
vsu_rcont_go:
	ld	l, 0
;  [2026-08-04] РЕЗЕРВ «страница fb в B»: hi столбца живёт в РЕГИСТРЕ B (в петлях
;  restore и save он свободен: save доразвёрнут на все 16 строк, см. vsu_scol), lo0 —
;  САМОМОДИФИЦИРУЕМЫЙ операнд `mvi l` (lo0 общий для всех столбцов и плоскостей:
;  меняется только страница). Было на столбец: lhld(16) + lda/inr/sta(31); стало
;  mov h,b + mvi l(12) + inr b(5) — минус 30 тактов на столбец и минус 15 Б кода.
;  Патч операнда — та же степень (не)реентерабельности, что и прежние ячейки vsu_lo/
;  vsu_hi: их setup писал, петля читала; вложенный вызов клобберил и их.
	inc	hl	; hi0
	ld	b, (hl)	; B = страница fb (плоскость+столбец)
	inc	hl	; lo0
	ld	a, (hl)
	ld	(vsur_ld+1), a	; lo0 -> операнд `mvi l` петли restore
	inc	hl	; ncols
	ld	a, (hl)
	ld	c, a
	ld	(vsu_nc), a	; копия ncols для 2-го прохода
	inc	hl	; hi0b
	ld	a, (hl)
	ld	(vsu_hib), a
	inc	hl	; hi0c
	ld	a, (hl)
	ld	(vsu_hic), a
	inc	hl	; HL = данные слота
	di	; === начало SP-хайджека ===
	ld	(vsu_rchl), hl
	ld	hl, 0
	add	hl, sp
	ld	(vsu_sp), hl
	ld	hl, (vsu_rchl)
	ld	sp, hl	; SP = данные слота
vsu_rcol:
	ld	h, b	; HL = fb НИЗ столбца: H из B (страница)…
vsur_ld:
	ld	l, 0	; …L = lo0 (самомодифицируемый операнд, патчится в setup)
;  vsu_body: ОБЩЕЕ ТЕЛО СТОЛБЦА restore и save (2026-10-16, идея из БК-версии: там save и
;  restore — одна процедура). Тело у обоих было байт в байт одно: 8 x (pop de; 2 x mov m +
;  inr l). Различается лишь, КТО в SP (restore: данные слота, save: столбец fb) и КТО в HL —
;  это делают пролог vsu_rcol (провалом) и пролог vsu_scol (jp сюда). Конец столбца уходит
;  по ОПЕРАНДУ vsu_colj (vsu_rcol / vsu_scol), его патчит setup рядом с vsu_npj — та же
;  (не)реентерабельность. Цена: +1 jp (12 т) на столбец save; минус 36 Б кода.
vsu_body:
vsu_srow:	; метка оставлена для инструментов (.sym-пробы z80_gain/su_loop_census)
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	inc	b	; следующий столбец (страница fb в B)
	dec	c
vsu_colj:
	jp	nz, vsu_rcol	; ОПЕРАНД: vsu_rcol у restore, vsu_scol у save
;  vsu_np: ОБЩИЙ ХВОСТ «СЛЕДУЮЩАЯ ПЛОСКОСТЬ» (2026-08-06, финансирование задачи #53).
;  Этот блок стоял ЧЕТЫРЕЖДЫ — по два одинаковых (19 Б) у restore и у save, — и различался
;  ровно одним операндом: адресом петли столбцов. Он и стал самомодифицируемым (vsu_npj),
;  а патчится в setup обеих процедур ДО хайджека: `call` внутрь звать нельзя (SP держит
;  данные слота), `ret` тоже — поэтому возврат в петлю только прямым jp.
;  Реентерабельность НЕ изменилась: setup уже патчил vsur_ld+1/vsus_ld+1 и писал
;  vsu_hib/vsu_hic, вложенный вызов клобберил и их (см. шапку «страница fb в B»).
;  Restore ВПАДАЕТ сюда провалом, save приходит jp: 76 Б -> 49 Б, минус 27 Б.
vsu_np:
	ld	a, (vsu_hib)	; dual: 2-я плоскость
	or	a
	jp	z, vsu_np3
	ld	b, a	; страница 2-й плоскости -> B
	xor	a	; гейт: после 2-го прохода дальше
	ld	(vsu_hib), a
	jp	vsu_npg
vsu_np3:
	ld	a, (vsu_hic)	; masked: 3-я (гасимая) плоскость
	or	a
	jp	z, vsu_done
	ld	b, a	; страница 3-й плоскости -> B
	xor	a
	ld	(vsu_hic), a
vsu_npg:
	ld	a, (vsu_nc)
	ld	c, a
vsu_npj:
	jp	vsu_rcol	; ОПЕРАНД: vsu_rcol у restore, vsu_scol у save
vsu_done:
	jp	vsu_rdone
vsu_rdone:
	ld	hl, (vsu_sp)	; === конец хайджека: вернуть настоящий SP ===
	ld	sp, hl
;  ОТРАВЛЕНИЕ vsu_hi (2026-08-04, найдено гейтом door_fixup). Hide-путь подготовки
;  (vsp_hide -> vsp_wrec в vec_sprout.asm) пишет в запись вывода СКРЫТОГО объекта
;  ПРОТУХШИЕ ячейки vsu_hi/vsu_lo/vsu_nc, а vso_static сравнивает эту запись с шапкой
;  слота: совпало -> створку «не надо стирать». Пока петли save/restore гоняли номер
;  страницы через ячейку vsu_hi, каждая пачка оставляла в ней «страница+1» — протухшая
;  запись почти никогда не совпадала с шапкой (случайная защита). Теперь страница живёт
;  в B, и без противоядия ячейки хранят ПОСЛЕДНЮЮ ВИДИМУЮ подготовку этого же слота —
;  запись hide совпадает с шапкой ГАРАНТИРОВАННО, и скрытая створка не стиралась
;  (юнит-тест: 0/63). Пишем в vsu_hi ноль: hi0 любой шапки >= 0x80, ноль не совпадает
;  НИКОГДА — строже прежней случайной защиты. 4 Б, ~18 тактов на вызов (0.6 вызова/кадр).
	xor	a
	ld	(vsu_hi), a
;  ФИКС ЖЕЛЕЗА (2026-07-29): БЕЗУСЛОВНЫЙ ei. vsu-хайджеки зовутся ТОЛЬКО из
;  игрового тика (H_TIMI, там EI). Старый depth-протокол (depth!=0 -> держать DI)
;  оставлял DI до конца тика => RST7 исполнялся с опозданием => палитра писалась
;  ВНЕ VBlank => на железе (латч по лучу) p3-схлопка разъезжалась: видна теневая
;  плоскость (кэши тайлов в p3), тёмная карта. Эмуляторы латч огрубляют — не видели.
	ei
	ret
;  vec_su_save: сохранить фон под НОВЫМ footprint'ом объекта vec_nsp_idx.
;  ГЕОМЕТРИЮ БОЛЬШЕ НЕ СЧИТАЕТ: её посчитала ПОДГОТОВКА (vec_spr_prep) и положила в
;  ЗАПИСЬ ВЫВОДА слот+0x96 (pending, hi0, lo0, ncols, hi0b, hi0c). Здесь запись лишь
;  переносится в шапку слота, дальше — прежний POP-хайджек fb->слот. Вызывается ТОЛЬКО
;  из пачки вывода vec_spr_out (начало кадра, фон уже чист: restore группы прошёл).
vec_su_save:
	ld	hl, vsu_sc_e	; ОПЕРАНД общего хвоста плоскостей (vsu_np)
	ld	(vsu_npj+1), hl
	ld	hl, vsu_scol	; ОПЕРАНД конца столбца общего тела vsu_body
	ld	(vsu_colj+1), hl
	ld	hl, vsu_rdone
	ld	(vsu_done+1), hl
	call	vec_su_ptr	; HL = слот
	ld	l, 0x96
	ld	a, (hl)	; pending>=2 -> слот невалиден: 2 = объект скрыт, 3 = ЗАДАЧА#37
	cp	2	; «выводить, но фон не снимать» (его снимает сосед по плоскости)
	jp	nc, vsu_hide
	inc	l
	ld	b, (hl)	; B = страница fb (см. блок «страница fb в B» у restore)
	inc	l
	ld	a, (hl)
	ld	(vsus_ld+1), a	; lo0 -> операнд `mvi l` петли save
	inc	l
	ld	a, (hl)
	ld	(vsu_nc), a
	ld	c, a	; C = ncols (его ждёт петля столбцов)
	inc	l
	ld	a, (hl)
	ld	(vsu_hib), a
	inc	l
	ld	a, (hl)
	ld	(vsu_hic), a
;  ЗАДАЧА#49 (2026-08-04): сейв кладёт в блок СВЕЖИЙ фон из fb, значит прежнее
;  доказательство «блок целиком нулевой» (ZFLAG +0xD1) больше не действует. Снимаем —
;  vsp_fastmark в следующем тике докажет заново. Одна инструкция, 13 тактов.
	ld	l, 0x0D1
	ld	(hl), 0
	ld	l, 0	; --- шапка слота ---
	ld	(hl), 1	; valid=1
	inc	l
	ld	a, 1	; гейт fixup: есть слоты
	ld	(vsu_any), a
	ld	(hl), b	; hi0 (страница fb уже в B)
	inc	l
	ld	a, (vsus_ld+1)	; lo0 — из свежепатченного операнда
	ld	(hl), a
	inc	l
	ld	(hl), c	; ncols
	inc	l
	ld	a, (vsu_hib)
	ld	(hl), a
	inc	l
	ld	a, (vsu_hic)
	ld	(hl), a
	inc	l
;  P3 POP-ХАЙДЖЕК SAVE (2026-07-29): SP = fb-столбец (НИЗ, адреса растут вверх), pop
;  читает 2 байта fb за 11т; слот-приёмник в HL (данные подряд через плоскости; slot —
;  страница 256Б => inc l валиден). Между столбцами SP переставляется (столбцы fb
;  разрывны). ПРАВИЛА ХАЙДЖЕКА: DI на весь хайджек, запрет call/push, SP восстановить
;  на всех путях, ei-протокол vbt_row.
	di	; === начало SP-хайджека ===
	ld	(vsu_rchl), hl
	ld	hl, 0
	add	hl, sp
	ld	(vsu_sp), hl
	ld	hl, (vsu_rchl)	; HL = слот (данные, +6)
;  [2026-08-04] Столбец доразвёрнут на все 16 строк (был полуанролл 2x4 pop ради байтов):
;  минус mvi b/dcr b/jp nz — освободившийся B держит страницу fb (см. блок у restore).
;  +14 Б кода на анролл, но в сумме с regs-in-B файл стал КОРОЧЕ на 15 Б.
;  ===== РАУНД 2 (2026-08-12): РАЗВИЛКА ПО ЗАВОРОТУ СТОЛБЦА ===========================
;  Клип vclp пустил габарит в зазор над полем (lo0 до 248, см. vec_sprout.asm), значит
;  столбец fb ТЕПЕРЬ МОЖЕТ ЗАВОРАЧИВАТЬСЯ 255->0. Для ВСЕХ петель это безобидно — они
;  ходят через `inc l` / `inc c`, а те заворачиваются ВНУТРИ страницы, то есть внутри
;  того же столбца. САЙВ — ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ: он читает fb через POP, а POP
;  инкрементирует SP ЦЕЛИКОМ, с переносом в старший байт. На завороте он ушёл бы читать
;  СОСЕДНИЙ СТОЛБЕЦ (страница+1, строки 0..k) и записал бы в слот чужой фон — а restore
;  честно вернул бы его в наш столбец, оставив мусор в зазоре.
;  ПОЭТОМУ: lo0 >= 241 -> отдельный проход vsu_scw (тот же контракт, адресация через
;  `ld a,(bc)` + `inc c`). Проверка стоит ЗДЕСЬ, а не в setup, потому что сюда же
;  возвращается общий хвост плоскостей vsu_np (операнд vsu_npj указывает на vsu_sc_e).
;  Порог 241, а не 249: заворачивается ЛЮБОЙ габарит с lo0 > 240 — клип лишь ограничил
;  сверху, насколько далеко заворот заходит.
vsu_sc_e:
