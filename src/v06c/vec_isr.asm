	call	vec_nested_countdown	; засчитать кадр после пачки, не сдвигая её старт
	pop	af
	ld	(vw_col), a
	pop	af
	ld	(vw_lowbase), a
	pop	af
	ld	(vw_tmp), a
	pop	af
	ld	(vw_byte), a
	xor	a	; тик состоялся -> счёт работы кооп-тиков с нуля
	ld	(vsnd_acc), a
	call	vsnd_tick	; конкурентно с потоком прерванного тика (состояние голосов — в ячейках, не в регистрах)
vec_isr_done:
	pop	hl
	ld	(il_a), hl
	pop	hl
	ld	(il_tmp2), hl
	pop	hl
	ld	(il_tmp), hl
	pop	hl
	ld	(z80_hl_alt), hl
	pop	hl
	ld	(z80_de_alt), hl
	pop	hl
	ld	(z80_bc_alt), hl
	pop	hl
	ld	(z80_af_alt), hl
	pop	hl
	ld	(z80_iy), hl
	pop	hl
	ld	(z80_ix), hl
	ld	a, (vec_isr_depth)	; отпустить уровень
	dec	a
	ld	(vec_isr_depth), a
	pop	hl
	pop	de
	pop	bc
	pop	af
	ei
	ret
vec_isr_skip:
	pop	af
	ei
	ret
;----------------------------------------------------------------------------------------
;  Замок F1+F3, скан в VBlank и обработка N/H/G/D/E после пачки.
	.include "vec_cheats.asm"
;----------------------------------------------------------------------------------------
;  [snd-vi53] Здесь была дырка оверлея AY/ВИ53 (WRTPSG, apply, hush): оверлей, проба AY и копирование снесены.
;  vec_snd_apply / vec_snd_hush теперь обычные процедуры в v06c/vec_snd.asm.
;  ЧАСЫ МУЗЫКИ. vtm_start программирует канал 2 ВИ53 генератором с периодом кадра —
;  он становится часами, а не голосом ([snd-vi53] AY в игре больше нет; прежние упоминания AY ниже — история).
;  ЧАСТОТА CPU НА ЧАСЫ НЕ ВЛИЯЕТ: ВИ53 тактируется clk_pit = 1.5 МГц. Период 60000 и
;  порог 29952 — под 50 Гц кадра. Сборка только 3 МГц.
;  Период 30000 = 1.5 МГц / 50 Гц; выход даёт один короткий импульс за кадр, на слух это
;  тише любой ноты. Управляющее слово 0x0B4: канал 2, LSB+MSB, режим 2, двоичный счёт.
;  АРЕНДА КАНАЛА C В РЕЖИМЕ ВИ53 (задача #26, 2026-07-31). Раньше в режиме 1 часов не было
;  вовсе — канал C считался занятым нотами навсегда, и темп на скролле держали доли по
;  работе (доля по работе на скролле разгоняла музыку, и это было слышно).
;  На деле канал C занят вспышками: замер по vec_vch+2 в геймплее — 10% кадров под нотой,
;  90% молчит. Поэтому часы БЕРУТ ЕГО В АРЕНДУ НА ПРОСТОЕ и отдают по первому требованию:
;  vtm_grab забирает канал, когда vec_vi_ch зажигает на нём ноту, а выключение C возвращает
;  его сюда. ТРИ ГОЛОСА ПРИ ЭТОМ ЦЕЛЫ: аренда занимает паузу между нотами, а не голос.
;  Режим 2 (rate generator) выбран не случайно: его выход опускается на ОДИН такт из 60000,
;  скважность 0.001% — на слух это не тон, а ничто, поэтому аренда не подмешивается к музыке.
vtm_start:
	ld	a, (vec_snd_mode)
	cp	2
	jp	z, vtm_arm	; тишина: канал C свободен под часы
	ld	a, (vec_vch+2)	; звук: C под нотой -> часов нет
	or	a
	jp	nz, vtm_off
;  ВОЗВРАТ КАНАЛА ИЗ АРЕНДЫ. Накопитель взводим ПОЧТИ ПОЛНЫМ, чтобы ближайший опрос сразу
;  дал тик. Обнулённый накопитель здесь съедает целый кадр музыки: канал отдаёт vec_vi_ch,
;  часто в том же ISR, что и ближайший опрос часов — тот приходит с пустым накопителем
;  и пропадает. Замер: без этого возвратный кадр давал 0.21 тика вместо 1.00.
;  [mus-jitter, 2026-10-19] Взвод ВАЖЕН только вне шапки ISR (скролл, серии блитов: там тикают одни опросы, а
;  аренда канала на скролле мигает каждые 1-2 кадра и без взвода тик съедается — проба с нулём: скролл x0.90).
;  В обслуженном кадре взвод давал ВТОРОЙ тик сразу после пачки (по 12-20% кадров с двумя тиками в сценах
;  с нотами на C; mus_trace: «2k шапка, 5k vec_end_no»), поэтому опрос сразу после пачки (vsnd_tick_pp) узнаёт
;  этот взвод по значению 29952 и гасит его до VTM_BIAS (в шапке, до пачки, лишние такты — мерцание).
	call	vtm_arm
	ld	hl, 29952
	ld	(vtm_acc), hl
	ret
vtm_arm:
	ld	a, 0x0B4	; канал 2, LSB+MSB, режим 2, двоичный счёт
	out	(0x08), a
;  Период 60000 отсчётов = два кадра. Ноль (то есть 65536) НЕ годится: ядро MiSTer с ним
;  счётчик не запускает — на железе часы стояли, тик не наступал никогда, и получилась
;  полная тишина плюс зависание после смерти героя (игра ждёт конца мелодии, а плеер стоит).
;  Два кадра выбраны так, чтобы опрос раз в кадр гарантированно попадал внутрь периода.
	ld	a, 255&(60000)
	out	(0x09), a
	ld	a, 60000>>8
	out	(0x09), a
	xor	a
	ld	(vtm_prev), a
	ld	(vtm_prev+1), a
	ld	(vtm_acc), a
	ld	(vtm_acc+1), a
	ld	(vtm_dead), a
	ld	(vbw_ok), a	; BEAMW: счётчик перепрограммирован, vbw_t0 устарел до следующей шапки
;  ПРОВЕРКА, ЧТО ЧАСЫ ИДУТ: читаем счётчик, тратим время, читаем снова. Не сдвинулся —
;  часов нет (иное железо, иная разводка), и мы обязаны вернуться к счёту по работе:
;  молчащий плеер хуже неровного темпа.
	ld	a, 1
	ld	(vtm_have), a
	call	vtm_read
	push	hl
	ld	b, 6	; [mus-jitter] ~90 тактов (было 40 = 600): счётчик уходит на ~45 отсчётов, хватает; проба идёт в КАЖДОМ возврате канала из аренды, то есть в шапке ISR перед пачкой
vtm_wait:
	dec	b
	jp	nz, vtm_wait
	call	vtm_read
	pop	de
	ld	a, l
	cp	e
	jp	nz, vtm_ok
	ld	a, h
	cp	d
	jp	nz, vtm_ok
	jp	vtm_off	; стоит -> часов нет
vtm_ok:
	ret
vtm_off:
	xor	a
	ld	(vtm_have), a
	ret
;  vtm_grab: КАНАЛ C ПОНАДОБИЛСЯ МУЗЫКЕ — часы отдают его немедленно. Вызывается, когда
;  vec_vi_ch зажигает молчавший C. Снимает vtm_have (темп снова считают доли по работе)
;  и пишет управляющее слово 0x0B6: оно останавливает счётчик, делитель пишет вызывающий.
;  СОХРАНЯЕТ HL — в нём уже лежит посчитанный делитель ноты. Клоб: только A.
vtm_grab:
	ld	a, 0x0B6	; канал 2: режим 3 (меандр), LSB+MSB
	out	(0x08), a
	ld	a, 1
	ld	(vec_vch+2), a
	xor	a
	ld	(vtm_have), a
	ret
;  vtm_read: HL = показание счётчика канала 2 через защёлку. Пара байтов читается всегда
;  целиком — иначе внутренний указатель полуслова ВИ53 разъедется.
vtm_read:
	ld	a, 0x80	; latch канала 2 (0x08: биты 7-6 = номер канала)
	out	(0x08), a
	in	a, (0x09)	; порядок обязателен: сначала младший
	ld	l, a
	in	a, (0x09)
	ld	h, a
	ret
;  vtm_delta: DE = СКОЛЬКО ОТСЧЁТОВ ВИ53 прошло с прошлого опроса (и запомнить новое показание).
;  Меряем ВРЕМЯ как разность показаний, а не ловим переворот: период таймера почти равен кадру,
;  а опрос идёт раз в кадр — попадали всегда в одну фазу счётчика и переворот не видели (замер:
;  темп падал вдвое). Счётчик крутится по кругу, поэтому (прошлое - текущее) по модулю 65536 =
;  сколько отсчётов прошло, сколько бы работы между вызовами ни было.
;  ОБЩАЯ для vst_hw (тик по порогу) и vsnd_tick_frm (синхронизация часов под кадровый тик):
;  два экземпляра этой арифметики разъехались бы при первой же правке. Клоб: A, HL, DE.
;  vtm_read РАЗВЁРНУТ ЗДЕСЬ, а не вызван: замер стоит в шапке ISR, ПЕРЕД пачкой вывода спрайтов,
;  и каждый лишний call/ret там — прямой сдвиг пачки под луч (замер: 11 пикселей транзиента на
;  такт). Отдельный vtm_read остался ради пробы «часы идут» в vtm_arm, где такты не важны.
vtm_delta:
	ld	a, 0x80	; latch канала 2
	out	(0x08), a
	in	a, (0x09)	; порядок обязателен: сначала младший
	ld	l, a
	in	a, (0x09)
	ld	h, a
	ld	a, (vtm_prev)
	sub	l
	ld	e, a
	ld	a, (vtm_prev+1)
	sbc	a, h
	ld	d, a	; DE = prev - now
	ld	(vtm_prev), hl	; ld (nn),hl флагов не трогает — перенос ниже ещё жив
	ret	nc
	ld	hl, 60000	; счётчик успел перезарядиться: добавляем период
	add	hl, de
	ex	de, hl
	ret
;  vsnd_tick: тик музыки ПО ЧАСАМ. Счётчик ВИ53 считает ВНИЗ, поэтому новое показание больше
;  прошлого = счётчик перезарядился, то есть прошёл ровно кадр -> двигаем плеер. Работа между
;  вызовами роли не играет: темп одинаков в геймплее, в скролле и на загрузке уровня.
;  Без часов (канал 2 отдан ноте, мёртвый ВИ53) — прежнее поведение: тикаем, когда позвали.
;  Клоб: A, HL, DE (как сам updateSound); вызывающие обязаны спасать своё.
;  ЧЕТЫРЕ ВХОДА, потому что «часов нет» каждый из них должен переживать по-своему:
;   vsnd_tick_clk  — обвязка ISR. Вызов добавлен ТОЛЬКО ради часов; без них тикать нельзя,
;                    иначе tickMain ниже тикнет второй раз за кадр.
;   vsnd_tick      — кадровые точки (tickMain, вложенный ISR). Без часов тикают как раньше.
;   vsnd_tick_coop — кооперативные точки в длинных операциях. Опрос там вдвое чаще, чем была
;                    прежняя калибровка по работе, поэтому без часов тикаем через раз.
;   vsnd_tick_hdr  — шапка ISR: тик по факту кадра в постоянной фазе + догон по часам (см. ниже).
vsnd_tick_clk:
	ld	a, (vtm_have)
	or	a
	ret	z
	jp	vst_hw
;  vsnd_tick_hdr — ЧЕТВЁРТЫЙ вход: ТИК В ШАПКЕ ISR, в ПОСТОЯННОЙ фазе кадра, до пачки вывода.
;  [2026-09-12, «музыка подтормаживает» в трёхплоскостной линии] До этого здесь стоял ТОЛЬКО
;  замер (vsnd_sample: доливка накопителя без тика), а тикали рабочие точки ПОСЛЕ пачки
;  (vec_isr_nr / vec_isr_nested / tickMain). В 4+4 пачка ~15 тыс. тактов и фаза тика гуляет
;  на четверть кадра; в 8-цветной пачка до 45 тыс. — тик уезжал на 0.75 кадра, и интервалы
;  между тиками плеера болтались 0.28..1.74 кадра (snd_interval_probe, демо: 41% интервалов
;  вне окна 0.5..1.5 кадра против 1.5% у 4+4) — это и слышно как «подтормаживает».
;  Вдобавок vsnd_sample складывал БЕЗ проверки переноса: когда прерывание кадра пропадало
;  (на Векторе оно не защёлкивается, запрос под DI пачки теряется — 87 кадров из 3500 в демо),
;  сумма переваливала за 65536 и перенос съедал 2.19 кадра музыки: 22 переноса = 48 кадров,
;  темп 0.985 тика/кадр.
;  СХЕМА ТЕПЕРЬ: обслуженное прерывание = кадр = ТИК, безусловно (фаза шапки постоянна, поэтому
;  интервалы ровно по кадру). Часы ВИ53 нужны только чтобы ДОГНАТЬ потерянные прерывания: в
;  накопителе остаётся всё, что сверх кадра, и первая же рабочая точка после пачки (vst_hw,
;  порог кадр) тикает ещё раз. Недобор до кадра (тик пришёл раньше, чем накопился полный кадр —
;  бывает только после такого догона) ПРОЩАЕМ, обнуляя накопитель: иначе фаза тика прилипала к
;  рабочей точке за пачкой и шапка больше не набирала кадр (проба: 22.8% шапок без тика, недобор
;  ровно полкадра). Темп от прощения не плывёт: тиков ровно столько, сколько кадров.
;  Переполнение при сложении (сумма >= 65536 — минимум 2.19 кадра) — тоже кадр, минус кадр по
;  модулю как в vst_frame. Без часов — как прежде: тикает tickMain.
;  ЦЕНА: updateSound в шапке (в среднем ~3000 тактов, p90 6500) сдвигает старт пачки — в
;  трёхплоскостной линии beam_tear 3.61 -> 3.81 рваных строк на кадр (+5.5%), beam_color в
;  верхней полосе 21.7% -> 23.2%. Плата принята: линия и так не влезает в луч (×2.7), а
;  музыка — слышна. Замер после: интервалы вне окна 0.5..1.5 кадра 41% -> см. отчёт.
;  Отвергнутый промежуточный вариант («долг кадров»: перенос в шапке -> vtm_debt, платит рабочая
;  точка): темп 0.999, но дрожание не лечит (48% вне окна, 666 слипшихся пар).
;  Клоб: A, HL, DE — к этому месту шапки ISR все регистры уже на стеке.
;  [mus-jitter, 2026-10-19] ДОГОН ПО ЧАСАМ В ОКНАХ DI И РОВНЫЙ ИНТЕРВАЛ. Замер tools/verify/mus_trace.js: у
;  кадров без тика (zero_pct 1.9-5.9%) причина ОДНА — кадровый IRQ пришёл под DI и не защёлкнулся (на Векторе
;  запрос живёт одну команду: MiSTer Vector-06C.sv:606, int ставится на фронт retrace только при INTE=1).
;  DI открывают SP-хайджеки save/restore внутри долгой пачки (BEAMW-ожидания растягивают её на кадр), блиты
;  клеток и текста, шторка (серии под DI дольше кадра) и dt_vec_draw. Потерянный кадр чинили позже или не
;  чинили: следующий IRQ давал ДВА тика подряд.
;  Теперь: (1) vsu_poll (vec_bw.asm) зовётся в конце окна DI у dt_vec_draw и vec_text_blit и тикает по
;  часам, если с прошлого тика прошёл кадр (порог vst_hw; накопитель смещён на VTM_BIAS = 1536 тактов — меньше
;  обычной фазы шапки 2.1-2.7 тыс., поэтому в обслуженном кадре ложного догона нет, а потерянный IRQ догоняется
;  не позже конца окна); (2) шапка тикает только если с прошлого тика прошло >= ~0.25 кадра (иначе его уже
;  сделал догон); (3) остаток после тика в шапке сбрасывается в VTM_BIAS: разброс фазы шапки не копится
;  в ложный догон; (4) опрос сразу после пачки (vsnd_tick_pp) без часов отдаёт начисленную шапкой ожидаемую
;  потерю (vth_nc); (5) опросы блитов клеток с часами в 5 раз чаще (vsnd_k_clk).
VTM_BIAS:	equ 768	; смещение накопителя, отсчёты ВИ53 (1536 тактов)
vsnd_tick_hdr:
	ld	a, (vtm_have)
	or	a
	jp	z, vth_nc
	call	vtm_delta	; DE = отсчёты с прошлого опроса (vtm_prev обновлён)
	push	de	; DE = дельта нужна ниже накопителю
	ld	hl, (vtm_prev)	; BEAMW: показание в шапке = опорная точка фазы луча
	ld	de, VBW_KB	; прибавка: отсчёты от запроса IRQ до этого показания (шапка вложенного ISR раньше)
	ld	a, (vec_isr_depth)
	dec	a
	jp	nz, vth_k1
	ld	de, VBW_KA	; внешний ISR: до шапки палитра, скан клавиш
vth_k1:
	add	hl, de
	ld	(vbw_t0), hl
	ld	a, 1
	ld	(vbw_ok), a
	pop	de
	ld	hl, (vtm_acc)
	add	hl, de
	jp	c, vth_fo	; сумма >= 65536: кадр (и больше) накоплен наверняка
	ld	a, h
	cp	0x20	; [mus-jitter] меньше ~0.25 кадра с прошлого тика: его уже сделал догон из окна DI
	jp	nc, vth_frame
	ld	(vtm_acc), hl	; тик этого кадра отдан раньше — не дублируем
	ret
vth_frame:
	ld	a, h	; остаток после тика: меньше ~1.3 кадра — это не потерянные кадры, а разброс фазы шапки:
	cp	0xA0	; сбрасываем его в смещение VTM_BIAS (иначе разброс копится и даёт ложный догон)
	jp	nc, vth_fo
	ld	hl, VTM_BIAS
vth_st:
	ld	(vtm_acc), hl
	jp	updateSound
vth_fo:
	ld	de, 0x08B00	; 65536-29952: минус кадр (для перевалившей суммы остаток верен по модулю)
	add	hl, de
	jp	vth_st
vth_nc:
	xor	a
	ld	(vbw_ok), a	; BEAMW: часов нет (C под SFX) — фазы нет
	ld	a, (vsp_n)	; [mus-jitter] ожидаемая потеря IRQ в предстоящей пачке растёт с числом объектов (хайджеков) в ней:
	add	a, a	; начисляем 32*n в vtm_dead (без часов он свободен; vtm_arm обнуляет), тик отдаёт vsnd_tick_pp
	add	a, a
	add	a, a
	add	a, a
	add	a, a
	ld	hl, vtm_dead
	add	a, (hl)
	ld	(hl), a
	jp	updateSound	; тик всё равно по кадру
;  vsnd_tick_pp — опрос СРАЗУ ПОСЛЕ ПАЧКИ (vec_isr_nr). С часами — прежний vsnd_tick_clk. Без часов (канал C под нотой)
;  потерянный IRQ узнать нечем: начисленные шапкой 32*n/112 тика на кадр (vth_nc) отдаём тиком по достижении 112.
;  Это ожидаемое значение, а не детектор: темп верный в среднем (snd_tempo), но какой кадр потерян — неизвестно.
vsnd_tick_pp:
	ld	a, (vtm_have)
	or	a
	jp	z, vtp_nc
vtp_cl:
;  Возврат канала C из аренды внутри тика шапки (vtm_start) взвёл накопитель ровно в 29952 («почти полный»): в обслуженном
;  кадре тик уже сделан, и этот взвод дал бы второй тик прямо сейчас — гасим его до смещения. Скролл/блиты взвод не гасят
;  (там нет шапок, опрашивают vst_hw напрямую), для них он нужен.
	ld	hl, (vtm_acc)
	ld	a, h
	cp	29952>>8	; страница взвода 0x75xx (после пачки обслуженного кадра накопитель всегда ниже: смещение + прошедшее)
	jp	nz, vst_hw
	ld	hl, VTM_BIAS
	ld	(vtm_acc), hl
	ret
vtp_nc:
	ld	hl, vtm_dead
	ld	a, (hl)
	sub	112
	ret	c
	ld	(hl), a
	jp	updateSound
vsnd_tick_coop:
	ld	a, (vtm_have)
	or	a
	jp	nz, vst_hw
;  Часов нет — тик ПО РАБОТЕ. Без этого нота висит на отрисовке уровня и на титуле:
;  длинный DI (блит комнаты, лого Konami), шапка ISR не вызывается.
	ld	hl, vtm_alt
	inc	(hl)
	ld	a, (vsnd_cdiv)
	cp	(hl)
	ret	nz
	ld	(hl), 0
	jp	updateSound
vsnd_tick:
	ld	a, (vtm_have)
	or	a
	ret	z	; часов нет: шапка уже тикнула в этом кадре (не 1.5× на титуле)
	jp	vtp_cl	; [mus-jitter] как vsnd_tick_pp с часами: гасит взвод аренды в обслуженном кадре, иначе vst_hw
vst_hw:
;  Меряем ВРЕМЯ как разность показаний, а не ловим переворот: период таймера почти равен
;  кадру, а опрос идёт раз в кадр — попадали всегда в одну фазу счётчика и переворот
;  не видели (замер: темп падал вдвое). Счётчик крутится по кругу с периодом 65536, поэтому
;  (прошлое - текущее) по модулю 65536 = сколько отсчётов прошло, сколько бы работы между
;  вызовами ни было. Накопили кадр (29952 отсчёта = 59904 такта / 2) -> тик, остаток
;  переносим, так что дробные части не теряются и темп не дрейфует.
	call	vtm_delta	; DE = отсчёты с прошлого опроса
;  СТРАХОВКА ОТ МОЛЧАНИЯ: если счётчик стоит (delta = 0) много опросов подряд, часы
;  считаем неработающими и уходим на счёт по работе — иначе плеер замолчит навсегда.
	ld	a, d
	or	e
	jp	nz, vtm_alive
	ld	hl, vtm_dead
	inc	(hl)
	ld	a, (hl)
	cp	200
	jp	c, vtm_hold
	xor	a
	ld	(vtm_have), a	; сдаёмся: дальше тикаем по работе
	jp	updateSound
vtm_hold:
	ret
vtm_alive:
	xor	a
	ld	(vtm_dead), a
	ld	hl, (vtm_acc)
	add	hl, de
;  ПЕРЕПОЛНЕНИЕ НАКОПИТЕЛЯ = ТОЖЕ КАДР (и даже с запасом). Без этой проверки перенос из
;  16 бит молча съедал 65536 отсчётов — больше двух кадров музыки разом. Ловится это редко
;  и только когда накопитель стоит высоко (после возврата канала из аренды он взводится
;  почти полным), а опрос пришёл с большой задержкой: замер показал 390 кадров без тика
;  на 3000. vst_frame ниже вычитает кадр сложением с 0x8B00, то есть по модулю 65536 —
;  для перевалившего значения это ровно тот же верный остаток.
	jp	c, vst_frame
	ld	a, l	; накопили кадр?
	sub	255&(29952)
	ld	a, h
	sbc	a, 29952>>8
	jp	nc, vst_frame
	ld	(vtm_acc), hl	; ещё нет — просто запомнить
	ret
vst_frame:
	ld	de, 0x08B00	; 65536-29952: вычитаем кадр, остаток переносим
	add	hl, de
	ld	(vtm_acc), hl
	jp	updateSound
RDPSG:	; A=14 (joystick). Читаем РЕАЛЬНЫЙ порт джойстика Вектор-06Ц 0x0E
;  (RTL MiSTer Vector-06C.sv:294/635 io_data=joyA_o, active-low байт: b0=RIGHT b1=LEFT b2=UP
;  b3=DOWN b6=FIRE1 b7=FIRE2, idle b4/5=1; отд.чип, PPI-инициализация не нужна). Переставляем в
;  MSX-формат RDPSG(14) active-low: b0=Up b1=Down b2=Left b3=Right b4=trigA b5=trigB (ReadKeys cpl).
	in	a, (0x0E)	; active-low Вектора
	cpl	; active-high: b0=R b1=L b2=U b3=D b6=F1 b7=F2 (1=нажато)
	ld	b, a
	rrca	; ror2: U->b0 D->b1 F1->b4 F2->b5 (маска 33h)
	rrca
	and	0x33
	ld	c, a
	ld	a, b	; L: Vp b1 -> Mp b2
	rlca
	and	0x04
	or	c
	ld	c, a
	ld	a, b	; R: Vp b0 -> Mp b3
	rlca
	rlca
	rlca
	and	0x08
	or	c
	cpl	; Mp active-high -> vec_joy active-low (покой b6/7=1)
	ret
WRTVDP:	; B=данные C=регистр : игнор (таблицы SCREEN2 фиксированы)
	ret
SETWR:
	ld	(vec_vdp_ptr), hl
	ret
;  [СНЯТО] SETRD (4 Б): подготовка VDP к чтению. Единственный вызов был в блоке за
;  setVDPWrite, помеченном в оригинале «(!?) Неиспользуемый код», и снят вместе с ним.
;  [ЗАДАЧА #12, 2026-08-01] УДАЛЁН vec_spr_load (46 Б): нативный RLE-загрузчик спрайтов в
;  vec_spr_buf. Его единственный вызов был в loadAnimation, а распаковывать больше нечего —
;  наборы героя лежат в образе готовыми таблицами (src/gen/vec_sprdata.asm), loadAnimation
;  лишь переставляет базу паттернов. Остатки sprites2/спрайтов карты грузятся прежним
;  bulk-путём unpackGFXset -> vec_de_sprb/vcw_spr.
;  [2026-07-29] УДАЛЁН vec_pat_load (69 Б): нативный RLE-загрузчик паттернов остался
;  от выпиливания soft-VDP — НИ ОДНОЙ ссылки во всём src, недостижим (перед ним безусловный
;  jp vsl_2). Проверено статическим анализом ссылок + покрытием на 30К кадров attract.
;  vec_pat_wr: A=байт, HL=VDP addr -> пишет в pat-кэш (fold+pat_base ПЕР-БАЙТ, корректно
;  через range-границы). Сохраняет HL/DE/BC/A (pat_base бережёт BC; DE/HL на стеке; A=байт).
vec_pat_wr:
	ld	b, a	; байт в B (pat_base бережёт BC; НЕ vw_byte —
;  иначе ISR во время загрузки перезатрёт ячейку)
	push	hl
	push	de
	ld	a, h	; фолд адреса VDP
	and	7
	ld	h, a
	call	pat_base	; HL = приёмник (base+folded)
	add	hl, de
	ld	a, b	; запись байта из B
	ld	(hl), a
	pop	de	; восстановить VDP addr + RLE source (A=байт)
	pop	hl
	ret
;  === СТАДИЯ 6 (_NATVDP): vec_cache_wr — ПРЯМОЙ range-роутер записи в нативные кэши, БЕЗ
;  vec_vdp_ptr-латча/диспетчера. Вход: A=байт, HL=VDP addr (mode-биты 0x4000/0x8000 допустимы).
;  Маршрут по H&0x3F: <0x18 цвет->vec_col_store (gem-фильтр+fold, как vw_colw); 0x18-0x1F
;  спрайт->vec_spr_buf (как vw_spr); 0x20-0x37 паттерн->vec_pat_wr (fold+pat_base, как vw_wcol
;  МИНУС re-blit — загрузка идёт ДО отрисовки, td_mark не нужен); 0x38+ name/SAT -> skip (bulk-
;  писатели туда не пишут во время загрузки, histogram name=0). Сохраняет BC/DE/HL. Клоббер: A.
;  Байт-в-байт эквивалент кэш-эффекта vec_vram_write на путях InviertePatron/VRAM_write2/vec_de_slow.
;  ПОПРАВКА К КОММЕНТАРИЮ НИЖЕ (задача #30, 2026-07-31): «ВСЕ 3 банка паттернов -> тень (6К)»
;  читается так, будто под тень отведено 6 КБ. Это НЕ ТАК и никогда не было так в 8C-порту:
;  vec_pat_wr первым делом делает `and 7` по H, то есть банки 0x2000/0x2800/0x3000 СХЛОПЫВАЮТСЯ
;  в один свёрнутый диапазон 0x000-0x7FF, а дальше pat_base раздаёт физические базы только
;  реально живым поддиапазонам: лабиринт+карта -> pat_maze_cell (608 Б в p3), шрифт -> ROM
;  (vec_font_rom, задача #1). Физически занято 608 Б, а не 6 КБ; свободных 4 КБ тут нет.
;  Замер (tools t30/audit.js, геймплей+карта+переходы): разных VDP-адресов паттернов, дошедших
;  до vec_pat_wr, — 295, ВСЕ в банке 0x2000 (0x2200-0x23C7); в банках 0x2800/0x3000 ровно 0.
;  Аналогично «цвет->vec_col_store»: с задачи #27 vec_col_store — одинокий `ret`, то есть ВЕСЬ
;  диапазон <0x18 (MSX colour table) на Векторе никуда не оседает.
vec_cache_wr:
	push	bc
	push	de
	push	hl
	ld	c, a	; C = данные
	ld	a, h	; снять VDP mode-биты
	and	0x3F
	ld	h, a
	cp	0x18	; 0x0000-0x17FF таблица цвета -> тень + режим тайла
	jp	c, vcw_col
	cp	0x20
	jp	c, vcw_spr
	cp	0x38	; 0x2000-0x37FF ВСЕ 3 банка паттернов -> тень (6К)
	jp	c, vcw_pat
;  ФИКС КАРТЫ 2026-07-29: 0x3800-0x3AFF = ТАБЛИЦА ИМЁН -> ПРЯМОЙ БЛИТ тайла.
;  Раньше сюда стоял безусловный skip («bulk-писатели в name не пишут») — это неверно для
;  ЭКРАНА КАРТЫ: unpackGFXset (gfxSprMapa) после спрайтов переключает VRAM-указатель на
;  0x3867 и льёт заголовок «- Pyramid's Map -» И ВСЮ таблицу имён пергамента bulk-потоком
;  (DEtoVRAM -> vec_de_slow -> сюда). Skip выбрасывал их => пергамент не рисовался вообще,
;  на экране оставались лишь HUD и спрайты карты (силуэт/стрелка идут другим путём).
	cp	0x3B	; 0x3B00+ = SAT: по-прежнему пропуск (свой путь vec_de_satb)
	jp	nc, vcw_end
	ld	a, c
	call	vec_text_blit	; HL=адрес клетки, A=тайл; сохраняет HL/DE/BC
	jp	vcw_end
vcw_pat:
	ld	a, c	; A=байт, HL=addr -> pat-кэш (fold внутри)
	call	vec_pat_wr
	jp	vcw_end
vcw_spr:
	ld	a, h
	ld	de, vec_spr_buf-0x1800
	cp	0x1E
	jp	c, vcw_spr_w
	ld	de, vec_spr_buf-0x1D00	; h>=0x1E -> sprites2 (сжатие -0x500)
vcw_spr_w:
	add	hl, de
	ld	a, c
	ld	(hl), a
	jp	vcw_end
vcw_col:	; gem-фильтр + fold + vec_col_store (как vw_colw)
	ld	a, l
	rrca
	rrca
	rrca
	and	0x1F
	ld	e, a
	ld	a, h
	rrca
	rrca
	rrca
	and	0x0E0
	or	e
	call	vec_is_gem_col	; ptr уже сдвинут в vec_vram_write
	jp	z, vcw_end
	ld	a, h	; фолд банка -> свёрнутый адрес цвета
	and	7
	ld	h, a
	ld	a, c
	call	vec_col_store
vcw_end:
	pop	hl
	pop	de
	pop	bc
	ret
;  pat_base: развилка баз фон-кэша паттернов (Фаза A+ шаг3). Вход HL=folded pat-адрес
;  (tile*8+row, 0..0x7FF, банк уже свёрнут). Выход DE=база (phys=DE+HL). Клоббер: только A
;  (сохраняет HL,BC,C). Границы по folded: <0x200 tiles<0x40 ; 0x200-0x45F tiles 0x40-0x8b
;  (maze); >=0x460 tiles>=0x8c (меню, p2). Шаг3a: только maze в work-RAM, шрифт пока в p2.
pat_base:
	ld	a, h	; HL<0x200 (tiles<0x40): шрифт 0x10-0x3f или p2
	cp	2
	jp	c, pb_lo
	cp	4	; 0x200-0x3FF (тайлы 0x40-0x7f) -> лабиринт
	jp	c, pb_maze
	jp	nz, pb_p2	; HL>=0x500 (тайлы>=0xa0) -> p2
	ld	a, l	; H==4: 0x400-0x45F (тайлы 0x80-0x8b) -> лабиринт
	cp	0x60
	jp	c, pb_maze
;  MAPDIRECT: pb_p2 (folded 0x460-0x7FF, тайлы 0x8c-0xff) целит в НЕВИДИМЫЙ low-RAM вместо
;  видимой p2 vec_pat_shadow. Единств. реальный писатель/читатель этого диапазона — КАРТА
;  (тайлы 0xC0-0xE7 = folded 0x600-0x73F); прочие 0x8c-0xff мёртвы во всех экранах (меню/титул/
;  финал эвакуированы в 0x40-0x78, см. remap ниже; nonzero maxWrite/maxRead=none). Смена ТОЛЬКО
;  КОНСТАНТЫ базы => 0 добавленных инструкций => тайминг байт-в-байт (гейт 4 честного рендера).
pb_p2:
	ld	de, pat_menu_base
	ret
pb_maze:
	ld	de, pat_maze_base
	ret
pb_lo:	; HL<0x200: шрифт HUD 0x10-0x3f (folded 0x80-0x1FF)
	ld	a, h	; H==1 (folded 0x100-0x1FF) -> шрифт
	or	a
	jp	nz, pb_font
	ld	a, l	; H==0,L<0x80 (тайлы 0x00-0x0f) -> p2
	cp	0x80
	jp	c, pb_p2
pb_font:	; tiles 0x10-0x3f -> дыра2 work-RAM
	ld	de, pat_font_base
	ret
