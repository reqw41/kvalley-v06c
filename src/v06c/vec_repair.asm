; ===== ПОЧИНКА СПРАЙТА ПОСЛЕ ФОН-БЛИТА (ЗАДАЧА#54, 2026-08-06) ======================
;  ЖАЛОБА С ЖЕЛЕЗА (MiSTer): «после входа в пирамиду, когда герой СТОИТ НА МЕСТЕ и
;  ворота закрываются, его спрайт МЕРЦАЕТ».
;
;  ПРИЧИНА (замер tools/verify/door_stand_beam.js, стоянка 284 кадра на пирамиде 1,
;  часы луча из эмулятора, сверка по байтам fb): анимация закрытия ворот блитит клетки
;  лабиринта, и часть их накрывает габарит героя — ТАЙЛ ПИШЕТ ФОН ПОВЕРХ НАРИСОВАННОГО
;  СПРАЙТА. Атрибуция затирателей по PC: 0x4d9e / 0x4da9 / 0x4e0b / 0x4e00, все внутри
;  тайлового блиттера vbt8_*, ни одного vec_su_restore. То есть это НЕ гонка с лучом,
;  не порядок в пачке и не отказ vmx_check — все три гипотезы замер отверг.
;  ПОЧЕМУ ДЫРА БЫЛА ТРИ КАДРА. vec_su_fixup честно подновляет фон в слоте и взводит
;  sticky vfl_dirty, но воспользоваться им можно только на СЛЕДУЮЩЕМ тике: подготовка
;  (фаза F, слияние sticky) в этом тике уже прошла — блиты идут ПОСЛЕ неё. Подготовка
;  тика N+1 пишет запись вывода, и рисует героя только пачка кадра N+2.
;
;  ЛЕЧЕНИЕ: спрайт, чей фон переписали, ПЕРЕРИСОВАТЬ ТУТ ЖЕ. Стирать и пересохранять
;  нечего — fixup уже положил в слот СВЕЖИЙ фон (с новой клеткой), а запись вывода
;  описывает ровно ту позицию, в которой герой нарисован. Повторный вывод по той же
;  записи ИДЕМПОТЕНТЕН: OR теми же битами, ANDN той же маской, композит створки
;  (vsc_leaf) на своём же результате даёт себя.
;  ДВЕ ТОЧКИ ВЫЗОВА:
;    1) ОБЁРТКА ПАЧКИ vso_fix — пачка зовётся ТОЛЬКО отсюда (оба места в vec_isr.asm,
;       глубина 1 и вложенная). Ловит блиты, случившиеся при недовыведенном списке;
;    2) ХВОСТ БЛИТА КЛЕТКИ (vec_blit.asm, сразу за vec_su_fixup) — без него луч успевает
;       пройти по стёртому герою В ТОМ ЖЕ кадре: замер после одной только точки (1) дал
;       дыры 2,2,2,1 кадра, потому что блиты одного шага анимации ложатся на два кадра.
;
;  ГЕЙТ vsp_rdy (общий, обязателен для точки 2). Подготовка достроила список => записи
;  вывода описывают позиции следующего кадра. Раньше любой ненулевой rdy молчал, и
;  drawPuerta (после vec_nat_sprites, rdy=1) писал p1 створки поверх одежды без починки
;  — idx6, «голый». rdy=2 (список СТРОИТСЯ) по-прежнему нельзя: запись ещё пишется.
;  rdy=1 при стоящем герое (ворота) совпадает с экраном; vss_or слота 4 гасит p1.
;  ГЕЙТ vfr_need — «есть непочиненный спрайт», ставит fixup, снимает проход починки.
;  Отдельный от vfl_dany: тот живёт до слияния sticky, то есть весь тик, и починка на
;  нём шла бы на КАЖДОМ следующем блите. Замер 6000 кадров случайной прогулки: на
;  vfl_dany — 1804 прохода, 5855 перерисовок, 5021 такт на кадр (8.4% кадра) при 194
;  реальных попаданиях блита в слот; на vfr_need — 310 перерисовок, 370 тактов на кадр
;  (0.62%), и метрика дефекта та же.
;  ПОВТОРНОГО ВХОДА НЕТ: серии блитов идут одним DI-участком (см. кооп-тик музыки в
;  vec_blit_tile; замер 12000 кадров: 19369 вызовов vec_su_fixup, из них под EI — НОЛЬ),
;  а при vsp_rdy=0 вложенная пачка и так вышла бы на первой инструкции.
;
;  ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ И ПОЧЕМУ ЗА ВЫРАВНИВАНИЕМ. Перед `.align 256` в образе
;  оставалось 7 свободных байт, и 45 байт, положенные ДО выравнивания, выталкивали
;  pre-align через границу страницы: образ рос сразу на 256 Б. За align он стоит ровно
;  свой размер. Тот же приём уже применён к vec_ending.asm и gen/vec_hoptab.asm.
vso_fix:
;  ===== BEAMW: вложенная починка посреди пачки = «призрак» героя (раунд 2, 2026-10-16) =====
;  Жалоба с железа: серый след героя после последнего гема. Пока внешняя пачка ждёт луч (vbw_wait)
;  и идёт, список уже забран (vsp_rdy=0), а записи вывода ОПЕРЕЖАЮТ экран. Вложенное прерывание
;  звало vso_fix -> vfr_gate; vfr_need взведён блитом гема/ворот под спрайтом, гейт считал «список
;  выведен» и рисовал героя по НОВОЙ записи ещё до save пары; save снимал героя как «фон», и каждый
;  restore печатал его обратно (тот же ghost -> save -> вечный мусор, что описан в vec_sprites.asm у
;  vsp_rdy=2). Без ожидания пачка короче кадра, и вложенный кадр внутрь неё почти не попадал.
;  Стенд tools/verify/bw_repair_gate.js воспроизводит: 15 Б остатка героя. vbw_busy — счётчик вложенности
;  пачек (inc в call-сайтах vec_isr.asm перед call vso_fix, dec здесь после пачки): пока он не ноль, vfr_gate не чинит; vfr_need остаётся взведённым,
;  и внешний vso_fix чинит всё сразу после пачки.
	call	vec_spr_out	; пачка всегда выполняет необходимые restore/save (ВТОРОЙ адрес возврата vso_fix+3 — на нём стоят стенды)
	ld	hl, vbw_busy
	dec	(hl)	; inc делают call-сайты в vec_isr.asm прямо перед call vso_fix
	di	; починка идёт под DI, как и весь хвост пачки (см. call-сайты)
vfr_gate:
	ld	a, (vbw_busy)	; пачка идёт (BEAMW): записи вывода опережают экран, чинить нельзя (ghost -> save)
	or	a
	ret	nz
	ld	a, (vsp_rdy)	; список не выведен -> записи ОПЕРЕЖАЮТ экран, чинить нельзя
	or	a		; (см. разбор ниже: ghost -> save -> вечный мусор)
	ret	nz
	ld	hl, vfr_need	; ставит vec_su_fixup при попадании блита в слот
	ld	a, (hl)
	or	a
	ret	z
	ld	(hl), 0		; чиним сейчас; rdy=2 выше нас развернул — признак цел
	ld	hl, vfl_dirty+20
vfr_lp:
	ld	a, (hl)
	or	a
	jp	z, vfr_nx
	push	hl
	ld	a, l	; страница слота = 0xE0 + (L - vfl_dirty&255)
	add	a, 0x0E0-(vfl_dirty&255)
	ld	h, a
	sub	0x0E0	; A = индекс слота
	ld	(vec_nsp_idx), a
	ld	l, 0x96	; запись вывода: 1 = «нарисован» (2 = скрыт, 0 = записи нет)
	ld	a, (hl)
	dec	a
	call	z, vec_spr_show
	pop	hl
vfr_nx:
	ld	a, l	; с конца: мумии, потом герой, створки 0-3 ПОСЛЕДНИМИ —
	cp	vfl_dirty&255	; MSX SAT, младший индекс накрывает. Иначе idx2
	ret	z	; одежды поверх листа (drawPuerta -> vfr_gate).
	dec	l
	jp	vfr_lp
;  vec_su_menu: ВОЗВРАТ НА ТИТУЛ ПОСЛЕ ПАРТИИ — СНЯТЬ ГЕЙТ SAVE-UNDER И ОЧИСТИТЬ ЭКРАН.
;  Зовётся из chkPushAnyKey вместо голого `call clearScreen` (kvalley_game.asm), то есть
;  ровно там, где игра уходит из партии в меню и стирает экран.
;  ЗАЧЕМ (жалоба «стартовая мелодия при первом запуске ускоренная», 2026-08-12). vsu_any —
;  гейт быстрого выхода vec_su_fixup: 0 = валидных слотов нет, и блит клетки не платит
;  проход по 21 слоту. Взводят его vec_su_save и vso_fastall (КАЖДАЯ непустая пачка вывода),
;  а гасит ТОЛЬКО vec_spr_flush — шторка смерти и смена предмета в руках. Пути «game over ->
;  титул» среди них нет: замер (diff ОЗУ на титуле до первой и до второй партии) показал
;  vsu_any = 0 перед первой партией и 1 перед второй, и дальше 1 НАВСЕГДА. Слоты при этом
;  хранят фон комнаты, которой на экране уже нет, а каждый блит текста платит за их скан.
;  ЧТО ЭТО СТОИЛО (замер профилем PC, конфигурация без AY, GameStatus=3 = мигание
;  PLAY START под джингл): ПЕРВАЯ партия 7468 команд на игровой тик, 81 кадр на 80 тиков;
;  ВТОРАЯ — 16300 команд на тик, из них ~3500 в vfx_loop/vfx_next по мёртвым слотам. Тик
;  перестаёт укладываться в кадр, tickInProgress пропускает каждый второй, и статус 3
;  растягивается на 160 кадров вместо 80. В режиме ВИ53 (часы музыки заняты нотой, темп
;  считается ПО РАБОТЕ) это тянет темп джингла: 0.951 тика/кадр против 1.182 у первой партии,
;  266 кадров против 209 — то самое «первый быстрее второго».
;  ПОЧЕМУ НЕ vec_spr_flush: он делает restore-under, то есть ВПЕЧАТАЛ БЫ старый фон в экран,
;  который следующей же командой очищается. Нам нужно снять гейт, а не вернуть картинку.
;  ПОЧЕМУ НЕ ИНВАЛИДИРУЕМ САМИ СЛОТЫ: читателей у них до первого vec_su_save новой партии
;  нет — vec_su_fixup закрыт этим флагом, vso_fix идёт по списку вывода (vsp_n=0 на титуле),
;  restore зовётся только из пачки по тому же списку. То есть 21 запись «невалиден» ничего
;  бы не изменила, а стоила бы ещё 8 байт.
;  ГДЕ ЛЕЖИТ: ЗА `.align 256` (vec_tables.asm) — та же причина, что у vec_ending/vec_hoptab/
;  vec_repair: перед выравниванием свободен 1 байт, и любые 4 байта, положенные ДО него,
;  растят образ сразу на 256 (проверено: 29848 -> 30104 Б, потолок пробит).
;  ЦЕНА: 7 байт образа, 0 байт на месте вызова (тот же call, другой операнд).
;  КЛОБ: A и флаги — оба мертвы, ниже по коду chkPushAnyKey идёт `call setColor`.
vec_su_menu:
	xor	a
	ld	(vsu_any), a
	jp	clearScreen
