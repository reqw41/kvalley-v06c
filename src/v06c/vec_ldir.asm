; ===== Дефляция ldir/lddr: общие stack-safe циклы копирования (call, не инлайн) =====
; Копирует BC байт (HL)->(DE); на выходе BC=0, HL/DE за диапазоном. Адрес возврата
; держится в il_tmp2 (не на стеке), поэтому заливка с dest поверх SP безопасна.
vec_ldir_fwd:
	ex	(sp),hl
	ld	(il_tmp2),hl
	pop	hl
vec_ldir_fwd_lp:
	ld	a,(hl)
	ld	(de),a
	inc	hl
	inc	de
	dec	bc
	ld	a,b
	or	c
	jp	nz,vec_ldir_fwd_lp
	push	hl
	ld	hl,(il_tmp2)
	ex	(sp),hl
	ret
