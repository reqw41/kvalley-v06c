;  ===== БУТ-ОВЕРЛЕЙ (mummy-zx, 2026-11-09) =====
;  vec_init исполняется ровно один раз — из jp на 0x0100 (или из стартера обложки) — и до
;  того, как игра впервые пишет MapaRAM. Поэтому он живёт не в резиденте, а в хвосте образа
;  за romCeil (с 0x7600, внутри MapaRAM): первая же загрузка карты его затирает.
;  Потолок хвоста — 0x7800 (там стартер обложки, tools/cas/make_splash_rom.py).
;  Начало — 0x7600 через .align 256: org в sjasm 0.39 не дополняет образ нулями, ds не понимает
;  Devector, а .align оба ассемблера дополняют одинаково. 0x75A5-0x75FF в образе — нули.
kv_res_end:	; [mummy-zx] конец резидента — tools/page_guard.py требует kv_res_end <= romCeil
	.align	256
vec_init:	; вход @0x100 (.rom). Ставим вектор RST7, затем init.
	ld	sp, stackTop	; 0x0F7A5 (kvalley_vars.asm): ЗАДАЧА#48 — стек в p3, невидимой
				; плоскости (палитра схлопнута), а не в нижней ОЗУ.
				; Цикл зануления ниже пройдёт по окну стека, и это безопасно:
				; на стеке между этими двумя строками ничего не лежит, а во
				; время прерывания цикл не исполняется.
;  ПОПРАВКА 2026-08-03: тут стояло «бут-SP=0xC300 — ВНУТРИ фреймбуфера!». Это реликт: с
;  задачи #37 окно стека 256Б (было 1024). ЗАДАЧА#48: stackArea=0x0F6A5, stackTop=0x0F7A5.
;  Пик замера — 108Б (min SP=0x0F739 за 9016 кадров: бут/меню/демо, геймплей, 4 скролла
;  комнаты, 6 переходов через карту, GameStatus 6/7/8/10), запас 2.4x — ровно как до
;  переезда, ведь поток команд не изменился. Бут-SP тот же самый.
	ld	hl, 0x8000
; Очистка ВСЕХ 4 планов (0x8000-0xFFFF). В p3 живут save-under слоты и кэши (в 8C
; p3 невидим) — бут-мусор в них дал бы фантомные «валидные» слоты и битые паттерны ->
; зануляем один раз на буте. Цикл до заворота HL 0xFFFF->0x0000.
vec_init_clr:
	ld	(hl), 0
	inc	hl
	ld	a, h
	or	l
	jp	nz, vec_init_clr
; ЗАДАЧА#34: скретч блиттера/save-under переехал в НУЛЕВУЮ страницу (0x5C-0x72) — её
; «заливка по площади» вроде p3 не покрывает, поэтому зануляем явно. Иначе бут-мусор в
; vsu_any/vnc_maskon (читаются как флаги ДО первой записи в кадре) дал бы фантомные слоты.
	ld	hl, vec_zp_lo
	ld	b, vec_zp_n
vec_init_zp:
	ld	(hl), 0
	inc	hl
	dec	b
	jp	nz, vec_init_zp
;  [snd-vi53] ПРОБА AY, ВЫБОР ЧИПА И КОПИРОВАНИЕ ОВЕРЛЕЯ СНЕСЕНЫ: игра поддерживает только ВИ53.
;  Режим слушания (клавиша S) на буте — «музыка+эффекты».
	xor	a
	ld	(vec_snd_mode), a
;  [mummy-zx-a] «прошлые» клавиши УС/ВК/АР2 = все нажаты: зажатая (или ложно отданная эмулятором) на старте
;  клавиша не считается свежим нажатием — иначе первый же кадр выключал музыку (режим 1: на заставке один
;  канал, в игре тишина — жалоба из Emu80).
	ld	a, 0x0FF
	ld	(vec_kbs_p), a
; SAT-стоп-маркер убран: sat_shadow/sat_drawn МЕРТВЫ (нативные спрайты рисуют из
; sprAttrib/enemyAttrib; SAT-тень при рендере не читается). nsp_prev праймит стирание.
	ld	a, 0x0C3	; 0x0038 = JP vec_isr (RST7 vblank)
	ld	(0x0038), a
	ld	hl, vec_isr
	ld	(0x0039), hl
	xor	a
	ld	(vec_isr_depth), a
	ld	a, 0x0FF
	ld	(vec_kb8), a	; покой (active-low: ничего не нажато)
	ld	(vec_joy), a
	call	vec_setpal
;  [mummy-zx] ППИ2 для джойстика «П»: B и низ C — вход, верх C — выход (выбор устройства, порт C = 9Fh, как в Monty).
;  Порт A — ВХОД (0x93, а не 0x83 как в Monty): на нём Covox/принтер, выход A давал на ЦАП ноль (в Emu80 — смещение и искажение звука).
	ld	a, 0x93
	out	(0x04), a
	ld	a, 0x9F
	out	(0x05), a
	ld	a, 0x8A	; режим порта: 02=вход (скан клавиатуры)
	out	(0x00), a
	ld	hl, vwant	; ВИ53: «хочу-состояние» трёх каналов (3x3 Б) и vec_vch (3 Б) — нули (все каналы выкл)
	ld	b, 12
vini_snd:
	ld	(hl), 0
	inc	hl
	dec	b
	jp	nz, vini_snd
	xor	a
	ld	(vec_name_gen), a
	ld	(vec_td_slot), a
	ld	(vec_spr_parity), a
;  (снят `ld (vec_sat_dl),a` — флаг был write-only, его единственный писатель vec_de_satb удалён)
	ld	(vec_fr_par), a
;  праймим кэш режимов vec_tilemode (256Б work-RAM) в FF=пересчитать (раньше это делала
;  заливка плана 2; кэш теперь вне p2 -> init_clr его не трогает, праймим явно до блитов).
	ld	hl, vec_tilemode
	ld	b, 0
vini_tm:
	ld	(hl), 0x0FF
	inc	hl
	dec	b
	jp	nz, vini_tm
; 2.4: пометить prev-снапшот нативных спрайтов «все скрыты» (Y=0xD0), чтобы
; первый вызов vec_nat_sprites ничего не стирал (мусор RAM наXORил бы фантомы).
	ld	hl, vec_nsp_prev
	ld	b, 21
vini_nsp:
	ld	(hl), 0x0D0
	inc	hl
	inc	hl
	inc	hl
	dec	b
	jp	nz, vini_nsp
;  ЗАДАЧА#47: фаза F стала set-only (нулевые флаги не переписываются каждый тик),
;  поэтому мусор RAM в vfl_flags/vfl_dirty (смежные 42Б, 0xFC00-0xFC29) обязан быть
;  снят на буте — иначе первый же тик употребил бы случайные флаги как «перерисовать».
	ld	hl, vfl_flags
	ld	b, 42
vini_vfl:
	ld	(hl), 0
	inc	hl
	dec	b
	jp	nz, vini_vfl
;  (снят `ld a,1 / ld (vec_sat_dirty),a` — флаг был write-only, читателей нет ни одного;
;   его единственный рантайм-писатель vec_de_satb удалён вместе с SAT-веткой soft-VDP)
;  ГЛУШИМ ОБА ИСТОЧНИКА, А НЕ ТОЛЬКО ВИ53 (2026-08-01, задача «первая нота»). Здесь стояли
;  три управляющих слова ВИ53, и AY на буте не приводился в определённое состояние ВООБЩЕ:
;  что осталось в чипе от предыдущей программы (а на MiSTer ROM грузится в УЖЕ РАБОТАЮЩЕЕ
;  ядро, без сброса AY), с тем игра и стартовала — в том числе с чужой огибающей R11-R13 и
;  с громкостями, у которых взведён бит 4 «громкость по огибающей». Первая нота такой канал
;  не оживляет: плеер пишет громкость, но пока в чипе висит чужой микшер/огибающая, звук
;  появляется лишь со следующего полного обновления регистров. vec_snd_hush ставит микшер
;  0x3F (всё выкл) и нули в 8/9/10, а заодно делает прежнюю уборку ВИ53 и сбрасывает кэш
;  делителей — то есть покрывает старые три out целиком. Порядок «глушение -> часы» СОХРАНЁН.
	call	vec_snd_hush
;  Часы музыки заводим ЗДЕСЬ, а не раньше: это глушение бьёт по всем трём каналам, включая
;  тот, что служит часами (замер: канал 2 стоял, счётчик не двигался, тик выпадал в старую
;  схему по работе). Порядок «сначала заглушить всё, потом завести часы» соблюдают и
;  vec_snd_apply, и пауза.
	call	vtm_start
;  P2-ЧИСТКА: генератор LUT бит-реверса УДАЛЁН (vnsx_rev16 реверсит битово на лету).
;  P2-ФИНАЛ: vini_ms (построение vec_mixslot LUT) УДАЛЁН — slot теперь линейный скан
;  vec_mixtiles на лету (vec_slot_of). Init mixslot больше не нужен.
;  [mummy-zx] startCode идёт следом (было jp startCode).
startCode:
		di
		ld	a, 0x0C3
		ld	(H_TIMI), a
		ld	hl, tickMain
		ld	(H_TIMI+1), hl	; Ставит процедуру прерывания, ведущую логику игры

		ld	sp, stackTop	; Устанавливает стек
		ld	hl, GameStatus
		ld	de, subStatus
;  ЗАДАЧА#37: длина была ИММЕДИАТОМ 0x6FF (1791) — очистка доходила до 0x72FF, то есть
;  на 748 Б ЗАЛЕЗАЛА В ЗОНУ СТЕКА (при старой раскладке безвредно: стек лежал выше SP).
;  После уплотнения раскладки такая длина снесла бы живой стек и карту, поэтому чистим
;  РОВНО область игровых переменных, выражением от границы (GameStatus..varsEnd-1).
;  ЗАДАЧА#48: граница называется varsEnd, а не stackArea — стек уехал в другую зону p3 и
;  больше не стоит впритык за переменными. ЧИСЛО НЕ ИЗМЕНИЛОСЬ (620): длина этой очистки
;  входит во время бута, а через него — в фазу свободно бегущего timer и в эталоны концовки.
		ld	bc, varsEnd-GameStatus-1
		ld	(hl), 0
	call vec_ldir_fwd	; Инициализирует область переменных игры

		ld	a, 1
		ld	(tickInProgress), a ; Не даёт выполняться логике игры во время инициализации железа
		call	initHardware	; Инициализирует видеорежим и PSG

		xor	a
		ld	(tickInProgress), a ; Разрешает выполнение логики игры на следующем прерывании
		call	RDVDP		; Сбрасывает флаг прерывания
		ei
	jp	dummyLoop
initHardware:
;  [snd-vi53] Был `SetPSGMixer(0xB8)` — запись микшера AY (тоны вкл, шум выкл). Микшера больше нет: у проигрывателя
;  ВИ53 канал включают события потока. Заодно прежняя запись пересчитывала каналы по тени регистров, а тень тут
;  уже согласована с чипом, так что состояние выхода она не меняла.
		ld	a, 0x20		; Тишина
		call	setMusic

		ld	de, 0		; (!?) Не должно ли быть HL? Хотя антикопия использует DE, процедура "setFillVRAM" использует HL
		ld	bc, 0x4000
		xor	a
		call	setFillVRAM
	ret	; [mummy-zx] было проваливание в SetVideoMode — тот снят (холостые WRTVDP)
;  Потолок 0x7800 проверяет tools/rom_pad.py.
