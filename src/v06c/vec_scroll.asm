;  === СДВИГ ВИДИМЫХ ПЛОСКОСТЕЙ ПРИ ПЕРЕХОДЕ КОМНАТЫ (2026-07-30) ======================
;  ЧТО БЫЛО: каждый из 8 шагов скролла (по 4 знакоместа) перерисовывал ВСЕ 704 тайла
;  комнаты из карты => 5632 блита на переход, 307 кадров (6 секунд).
;  ЧТО СТАЛО: сдвиг на 4 знакоместа означает, что 28 столбцов из 32 просто ПЕРЕЕЗЖАЮТ на
;  новое место, и рисовать заново надо только 4 новых столбца (88 тайлов вместо 704).
;  ПОЧЕМУ СДВИГ ДЕШЁВЫЙ: раскладка фреймбуфера Вектора — адрес = плоскость + столбец*256 +
;  (255-Y), то есть СТОЛБЕЦ ЭКРАНА ЭТО 256 ПОДРЯД ИДУЩИХ БАЙТ, а горизонтальный сдвиг на
;  знакоместа = копирование целых блоков между страницами (никакой битовой возни).
;  Игровое поле — тайл-ряды 1..22 (ряд 0 = табло, ряд 23 = подпись, они при скролле не
;  двигаются): fb-строки lo 72..247, ровно 176 Б на столбец.
;  Копируем ТОЛЬКО видимые p0/p1/p2. p3 (0xE000+) — слоты save-under и кэши, НЕ ТРОГАТЬ.
;  POP-ХАЙДЖЕК (та же техника, что vec_su_save/restore, ср. GrApp_ScrollLeft в Boulder
;  Dash для ПК-8000): SP наводится на столбец-ИСТОЧНИК, `pop de` читает 2 Б за 10 т, пара
;  `ld (hl),r`+`inc l` пишет ПРИЁМНИК => ~17 т/Б вместо ~39 т/Б петли на `ld a,(de)`.
;  ПРАВИЛА ХАЙДЖЕКА (как в vec_saveunder.asm): DI на всё время подмены SP, внутри ни
;  call, ни push, SP восстановить на всех путях. Хайджек берётся НА ОДИН СТОЛБЕЦ
;  (~3.2К такта), между столбцами ei — вложенное прерывание успевает крутить звук, поэтому
;  кооперативный тик updateSound здесь не нужен (в отличие от vec_nr_win, который держит
;  DI сквозь блиттер).
;  НАПРАВЛЕНИЕ: копировать надо от ДАЛЬНЕГО края к ближнему, иначе столбцы затирают сами
;  себя (источник и приёмник разнесены всего на 4 страницы).
;    sentidoProta 2 (вправо): содержимое едет НАЛЕВО, приёмник 0->27, источник = приёмник+4
;    sentidoProta 1/3 (влево): содержимое едет НАПРАВО, приёмник 31->4, источник = приёмник-4
;  Новые (мусорные после сдвига) столбцы — 28..31 при движении вправо и 0..3 при движении
;  влево; их дорисовывает vec_nr_win из карты. Клоб A,BC,DE,HL.
vec_scroll_shift:
	ld	a, (sentidoProta)	; бит0: 1 = влево (1/3), 0 = вправо (2)
	rra
	jp	c, vss_left
	xor	a	; ВПРАВО: приёмник с 0-го столбца, вверх
	ld	(vss_d0), a
	ld	a, 4	; источник = приёмник + 4
	ld	(vss_soff), a
	ld	a, 1
	ld	(vss_step), a
	jp	vss_p0
vss_left:
	ld	a, 31	; ВЛЕВО: приёмник с 31-го столбца, вниз
	ld	(vss_d0), a
	ld	a, 0x0FC	; источник = приёмник - 4
	ld	(vss_soff), a
	ld	a, 0x0FF
	ld	(vss_step), a
;  ПОРЯДОК ПЕТЕЛЬ: снаружи СТОЛБЕЦ, внутри 3 плоскости. Наоборот (плоскость снаружи)
;  быстрее ни на такт, зато на 1-2 кадра шага экран стоит с ПЕРЕЕХАВШЕЙ p0 и ещё не
;  переехавшими p1/p2 => вся комната вспыхивает чужими цветами (проверено глазами:
;  белые лестницы становились красными). Со столбцом снаружи каждый столбец переезжает
;  сразу во всех плоскостях: в любой момент луч видит слева новую позицию, справа старую —
;  ровно тот же вертикальный шов, что был у построчной перерисовки, но цвета целы.
vss_p0:
	ld	a, (vss_d0)	; текущий столбец-приёмник
	ld	(vss_col), a
	ld	c, 28	; переезжают 28 столбцов из 32
vss_colloop:
	ld	a, 0x80	; для этого столбца — все три видимые плоскости
	ld	(vss_pl), a
vss_plane:
	ld	hl, vss_col	; hi приёмника = плоскость + столбец
	ld	a, (vss_pl)
	add	a, (hl)
	ld	(vss_dhi), a
	di	; === начало SP-хайджека (один столбец одной плоскости) ===
	ld	hl, 0
	add	hl, sp
	ld	(vss_sp), hl
	ld	hl, vss_soff	; SP = столбец-источник, lo=72 (низ ряда 22)
	ld	a, (vss_dhi)
	add	a, (hl)
	ld	h, a
	ld	l, 72
	ld	sp, hl
	ld	a, (vss_dhi)	; HL = столбец-приёмник, lo=72
	ld	h, a
	ld	l, 72
	ld	b, 11	; 11 x 16 Б = 176 Б (lo 72..247 = тайл-ряды 1..22)
vss_row:
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	pop	de
	ld	(hl), e
	inc	l
	ld	(hl), d
	inc	l
	dec	b
	jp	nz, vss_row
	ld	hl, (vss_sp)	; === конец хайджека: вернуть настоящий SP ===
	ld	sp, hl
	ei	; окно для вложенного прерывания (звук)
	ld	a, (vss_pl)	; p0 -> p1 -> p2; на 0xE0 (p3) плоскости кончились
	add	a, 0x20
	ld	(vss_pl), a
	cp	0x0E0
	jp	nz, vss_plane
;  _COOPSND: кооперативный тик музыки раз в 4 столбца (под DI, БЕЗ ei — как vec_nr_row).
;  Почему не надеемся на вложенное прерывание: окна `ei` между столбцами занимают ~2%
;  времени, запрос прерывания в них почти не попадает (замерено: за фазу сдвига проходит
;  ~9 тиков вместо 40). Без этого музыка на время скролла проваливается вдвое по темпу.
;  BC живой (счётчик столбцов) — спасаем через стек: SP уже настоящий, хайджек закрыт.
;  ДРОБНОЕ ПРОРЕЖИВАНИЕ (2026-07-30): было «каждый 4-й столбец» — маска, подобранная под
;  прежнюю стоимость шага. После ускорения скролла темп уехал на 18% вперёд. Теперь общий
;  с vec_nr_row аккумулятор vsnd_acc: столбец добавляет свою долю кадра, тик = переполнение.
	ld	a, (vtm_have)	; [mus-jitter] без часов (канал C под долгой нотой) тик идёт по счёту опросов, и при k=112
	dec	a	; скролл давал 0.62 тика/кадр (по 3 опроса на тик) — тогда опрашиваем на каждом столбце:
	or	vsnd_k_col	; vtm_have 0/1 -> 0xFF/0 -> k=255 без часов, k=vsnd_k_col с часами
	ld	hl, vsnd_acc
	add	a, (hl)
	ld	(hl), a
	jp	nc, vss_nosnd
	di
	push	bc
	call	vsnd_tick_coop
	pop	bc
	ei
vss_nosnd:
	ld	hl, vss_step	; следующий столбец
	ld	a, (vss_col)
	add	a, (hl)
	ld	(vss_col), a
	dec	c
	jp	nz, vss_colloop
	ret
