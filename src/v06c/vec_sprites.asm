;  флеш стирает в тике N (уже после пачки кадра N), подготовка идёт тиком N+1, вывод
;  пачкой кадра N+2.
;  ПОЧЕМУ ФЛЕШ ВООБЩЕ СТОЯЛ ЗДЕСЬ. loadAnimation перегенерирует ДАННЫЕ спрайта героя
;  (vec_spr_shadow), НЕ МЕНЯЯ ни Y, ни X, ни НОМЕР паттерна. Детектор изменений (фаза F)
;  сравнивает ровно эти три байта, поэтому сам он смены не увидит и герой остался бы на
;  экране со старой графикой навсегда. Флеш решал это грубо: prev := «скрыт» у всех.
;  ПОЧЕМУ СТИРАТЬ БОЛЬШЕ НЕ НУЖНО. Стирание давно идёт не паттерном, а СОХРАНЁННЫМ ФОНОМ
;  (restore-under): пачка вернёт фон по ШАПКЕ слота, то есть ровно по тому габариту, в
