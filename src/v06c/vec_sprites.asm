; ===== Нативные спрайты 8C (vec_nat_sprites) =====
;  --- скретч ТИКА в свободном обрезке p3 0xFD04-0xFD37 (опись у vsm_z в vec_boot.asm;
;      замер 8998 кадров: R=0, W=0, X=0). Обе ячейки write-before-read внутри одного
;      объекта подготовки, зануления не требуют. ---
vnc_dupb:      equ 0x0FD0D	; 1B: база ВТОРОЙ СВОЕЙ плоскости спрайта (0 = одноплоскостный)
vom_dl:        equ 0x0FD0E	; 1B: !=0 — у текущего объекта vom_check есть своя 2-я плоскость
; Читает sprAttrib(6 записей)+enemyAttrib(8 записей) ПРЯМО из игровой RAM (одна
; сплошная таблица с шагом 4Б, sprAttrib..sprAttrib+0x37) — валидированный JS-прототип
; (tools/verify/native_spr_proto.js) читает те же 14 записей.
; ТЕКУЩАЯ СХЕМА (8C): спрайты рисуются в ВИДИМЫЕ планы p1/p2 rot-петлями
; (OR-draw; створки ворот — masked ANDN, см. vec_rotblit), под спрайтом фон
; сохраняется в save-under слоты в невидимом p3 (vec_spr_save, vec_saveunder.asm);
; стирание = restore слота. Порядок кадра: фаза F (детект изменений cur/prev +
; липкий vfl_dirty + форс по смене GameStatus) -> фаза P (распространение по
; пересечениям) -> Pass-R (restore по флагам 20->0) -> forward (save+draw 0->20).
; [история] Ранний нативный этап (Задача 2.4) рисовал МОНО-спрайты XOR-ом в тогда
; свободный p3 (XOR self-erase, без save-under); от него остались снапшот прошлого
; кадра vec_nsp_prev (14 x [Y,X,pat], теперь это детект изменений) и XOR-термины в
; комментариях ниже.
; Вызывается из игрового тика (H_TIMI, vec_isr_depth==1); вложенные vblank
; (depth>=2) исполняют только звуковой драйвер и тик не зовут, поэтому конкурентно
; сама с собой процедура вызваться не может.
vec_nat_sprites:
;  ОПТ обхода (2026-07-12): в фазе F указатели cur (HL, шаг 4) и prev (DE, шаг 3) держим
;  в РЕГИСТРАХ, без per-iter LHLD/SHLD (было ~150т/спрайт только на перезагрузку/advance).
;  + ранний skip невидимых: cur Y>=0xD0 и prev Y>=0xD0 -> спрайт мимо (erase+draw были
;  бы no-op'ами vec_nsx; prev нужен лишь для erase, скрытый prev => erase no-op, значит
;  устаревание prev при обоюдном скрытии визуально безопасно).
;  ВАЖНО про СТЕК: в РЕДКОМ draw-пути НЕ спиллим регистры в стек (это углубляло бы стек
;  на 4 байта и оставляло иной "мусор" под SP, который читается => дрейф игры). Вместо
;  этого спиллим cur в память vec_nsp_ptr (SHLD, без push) — стек-футпринт подготовки
;  идентичен оригиналу.
;  _8C_RLG: Фаза F (флаги = гейт cur/prev) -> Фаза P (распространение по пересечениям
;  bbox 16x16, cur И prev флагового, до 2 проходов c early-exit) -> Pass-R restore ПО
;  ФЛАГАМ 20->0. Все сейвы группы дальше снимают ЧИСТЫЙ фон => в слотах не бывает чужих
;  спрайт-пикселей (см. коммент у _8C_RLG).
;  ЗАДАЧА#36 (2026-07-31): ГЕЙТ «НИЧЕГО НЕ ИЗМЕНИЛОСЬ». Замер 1192 кадров геймплея:
;  после фазы P флагов НОЛЬ в 71.0% кадров (средн. 0.73 флага, видимых объектов 2.97,
;  максимум 4). А список видимых, фаза P и цикл подготовки шли БЕЗУСЛОВНО по всем 21
;  слоту — 6.6 тыс. тактов на кадр, в котором ни один спрайт не шевельнулся. Теперь
;  фаза F накапливает в vfl_any «был ли хоть один флаг», и при нуле подготовка кончается
;  сразу за фазой F: список не строится, распространение не гоняется, цикл подготовки не
;  идёт. Семантика та же — при нулевых флагах все три прохода и так были no-op'ами.
	ld	a, (GameStatus)	; смена фазы -> форс всех
	ld	hl, vfl_lastgs
	cp	(hl)
	jp	z, vflf_nofc
	ld	(hl), a
	ld	hl, vfl_dirty
	ld	b, 21
vflf_fc:
	ld	(hl), 1
	inc	l
	dec	b
	jp	nz, vflf_fc
	ld	a, 1	; форс идёт через sticky => открыть гейт слияния
	ld	(vfl_dany), a
vflf_nofc:
	xor	a
	ld	(vsp_dpg), a	; ЗАДАЧА#37: цепочка «предыдущий подготовленный» начинается пустой
	ld	(vfl_any), a
;  ЗАДАЧА#53: прошлый тик отложил часть флагов по бюджету — гейт «ничего не изменилось»
;  обязан пропустить подготовку, иначе отложенные объекты застынут до своего следующего
;  шевеления. Флаги их уже стоят (consume-clear их не трогал), нужен только гейт.
	ld	a, (vns_defer)
	or	a
	jp	z, vns_nodef
	xor	a
	ld	(vns_defer), a
	inc	a
	ld	(vfl_any), a
vns_nodef:
	ld	a, vfl_act&255	; ЗАДАЧА#53: курсор списка видимых — на начало
	ld	(vfs_wr+1), a
	ld	hl, sprAttrib	; === Фаза F ===
	ld	de, vec_nsp_prev
	ld	bc, 4	; шаг cur для add hl,bc (10 т вместо 4x inc hl = 20); портит
			; его только редкая ветка vflf_f1 — она же и восстанавливает
;  ЗАДАЧА#47 (2026-08-04): ФАЗА F ТЕПЕРЬ SET-ONLY. Замер vflf_cost.js на живой сборке:
;  скан стоил 3099 т/тик — крупнейшая статья тика (11% от avg 27975), при этом флагов
;  ноль в 39-71% тиков. Гейт «до цикла» здесь НЕВОЗМОЖЕН: цикл не читает флаги, он их
;  ВЫЧИСЛЯЕТ сравнением cur/prev (vfl_any — его ВЫХОД, а писатели sprAttrib в игровом
;  коде пишут таблицу КАЖДЫЙ тик теми же значениями — см. attrib_writers_census.js —
;  так что писательский dirty-бит без compare-before-store не гейтил бы ничего).
;  Поэтому дешевеет сам детектор:
;   - нулевые флаги НЕ ПИШУТСЯ: их возвращает подготовка (consume-clear в vns_draw),
;     инвариант «на входе фазы F все флаги = 0» держат vfl_any-гейт (флаг не может
;     остаться неупотреблённым) и зануление 0xFC00-0xFC29 на буте;
;   - BC цикла свободен: адрес флага редкая ветка считает из L (страница 0xFD цельная,
;     idx = (L-9Bh)/4), петля закрывается по L, а не по счётчику;
;   - развёртка x3 (21 = 3x7): цена петли делится на три;
;   - шаг cur = add hl,bc (BC=4 весь скан), а не 4x inc hl.
;  Оба скрыты (17-18 слотов из 21): 80 тактов вместо 121. Скан целиком: 2278 т/тик
;  (замер vflf_cost.js, было 3099) — выигрыш 821 т/тик. Редкие пути (видимый/исчезнувший
;  слот) идут через общий компаратор vflf_cmp: те же 3 байта Y,X,pat, результат байт в
;  байт. Остаток (~2.3К) — неустранимый без игровых крючков минимум: писатели пишут
;  каждый тик, поэтому детект = чтение 21 cur-Y (+prev-Y) обязателен каждый тик.
vflf_loop:
	ld	a, (hl)	; --- слот 3k ---
	add	a, 0x30	; «скрыт» = 0xD0..0xEF (парковка 0xE0/0xE1); 0xF0..0xFF = Y<0
	cp	0x20
	jp	nc, vflf_curA	; cur видим -> в список видимых + полный компаратор
	ld	a, (de)	; cur скрыт: prev видим -> изменение (Y разойдутся в vflf_cmp)
	add	a, 0x30	; «скрыт» = 0xD0..0xEF (парковка 0xE0/0xE1); 0xF0..0xFF = Y<0
	cp	0x20
	jp	nc, vflf_curA
vflf_nxA:
	add	hl, bc
	inc	de
	inc	de
	inc	de
	ld	a, (hl)	; --- слот 3k+1 ---
	add	a, 0x30	; «скрыт» = 0xD0..0xEF (парковка 0xE0/0xE1); 0xF0..0xFF = Y<0
	cp	0x20
	jp	nc, vflf_curB	; cur видим -> в список видимых + компаратор
	ld	a, (de)
	add	a, 0x30	; «скрыт» = 0xD0..0xEF (парковка 0xE0/0xE1); 0xF0..0xFF = Y<0
	cp	0x20
	jp	nc, vflf_curB
vflf_nxB:
	add	hl, bc
	inc	de
	inc	de
	inc	de
	ld	a, (hl)	; --- слот 3k+2 ---
	add	a, 0x30	; «скрыт» = 0xD0..0xEF (парковка 0xE0/0xE1); 0xF0..0xFF = Y<0
	cp	0x20
	jp	nc, vflf_curC	; cur видим -> в список видимых + компаратор
	ld	a, (de)
	add	a, 0x30	; «скрыт» = 0xD0..0xEF (парковка 0xE0/0xE1); 0xF0..0xFF = Y<0
	cp	0x20
	jp	nc, vflf_curC
vflf_nxC:
	add	hl, bc
	inc	de
	inc	de
	inc	de
	ld	a, l
	cp	255&(sprAttrib+84)	; 21 слот пройден (страница 0xFD не рвётся: 9Bh..EFh)
	jp	nz, vflf_loop
	jp	vflm_gate
;  Редкий путь (~3 видимых слота на тик): CALL — та же глубина стека, что у штатных
;  call vsp_fastmark/vso_sortord этого же тика, футпринт под SP не углубляется.
;  ===== СПИСОК ВИДИМЫХ СТРОИТСЯ ЗДЕСЬ (ЗАДАЧА#53, 2026-08-05) ======================
;  Раньше он собирался ОТДЕЛЬНЫМ проходом по 21 слоту (vfla_loop) сразу после фазы F —
;  2244 такта на тик, при том что фаза F прямо перед этим уже прочла Y всех 21 слота и
;  ЗНАЕТ, кто видим. Профиль подготовки ОДНОГО объекта: обвязка (четыре обхода массива
;  слотов) съедает 7856 из 22480 тактов = 35%, и этот проход — самый бессмысленный.
;  ПОЧЕМУ ЧЕРЕЗ САМОМОД, А НЕ ЧЕРЕЗ РЕГИСТР: в фазе F заняты все пары (HL=cur, DE=prev,
;  BC=шаг), а спиллить в стек НЕЛЬЗЯ — глубина стека подготовки зафиксирована, иной
;  мусор под SP читается игрой и даёт дрейф (проверено: герой замирает). Указатель
;  записи живёт в ОПЕРАНДЕ инструкции, регистры не нужны вовсе.
;  Список теперь — ОДИН БАЙТ на видимый слот (индекс); Y и X фаза P читает из sprAttrib
;  по индексу, там они всё равно под рукой.
vflf_cur_see:
	ld	a, l	; idx = (L - sprAttrib&255)/4, страница 0xFD цельная
	sub	255&sprAttrib
	rrca
	rrca
vfs_wr:
	ld	(vfl_act), a	; ОПЕРАНД: курсор записи, правится строкой ниже
	ld	a, (vfs_wr+1)
	inc	a
	ld	(vfs_wr+1), a
	ret
vflf_curA:
	call	vflf_cur_see
	call	vflf_cmp
	jp	vflf_nxA
vflf_curB:
	call	vflf_cur_see
	call	vflf_cmp
	jp	vflf_nxB
vflf_curC:
	call	vflf_cur_see
	call	vflf_cmp
	jp	vflf_nxC
;  «Исчезнувшие» (cur скрыт, prev видим) тоже идут в список: фаза P обязана разослать
;  их флаг соседям по СТАРОМУ габариту, иначе останется след. Внутренний цикл фазы P
;  поэтому снова проверяет скрытость (7 тактов на запись) — раньше в списке скрытых не было.
;  ДУБЛЬ vflf_visA/B/C СНЯТ 2026-08-06 (задача #51, фаза 3): три хвоста по 9 Б были
;  ПОБАЙТНО равны vflf_curA/B/C (те же два call и тот же jp), и различались только именем
;  в комментарии. Обе развилки скана теперь ведут в vflf_curA/B/C — 27 Б, ноль тактов.
;  Компаратор слота: HL = cur (sprAttrib+4*idx), DE = prev; сравнить Y,X,pat, при
;  расхождении флаг[idx]=1 + vfl_any. HL/DE возвращаются на начало записей.
vflf_cmp:
	ld	a, (de)
	cp	(hl)
	jp	nz, vflf_f1
	inc	hl
	inc	de
	ld	a, (de)
	cp	(hl)
	jp	nz, vflf_f1r1
	inc	hl
	inc	de
	ld	a, (de)
	cp	(hl)
	jp	nz, vflf_f1r2
	dec	hl
	dec	de
	dec	hl
	dec	de
	ret		; равны: флаг остаётся 0 (нули держит consume-clear)
vflf_f1r2:
	dec	hl
	dec	de
vflf_f1r1:
	dec	hl
	dec	de
vflf_f1:
	ld	a, l	; адрес флага из cur-указателя: idx = (L - sprAttrib&255)/4
	sub	255&sprAttrib
	rrca
	rrca
	ld	c, a
	ld	b, 255&(vfl_flags>>8)
	ld	a, 1
	ld	(bc), a	; флаги в одной странице
	ld	(vfl_any), a
	ld	bc, 4	; вернуть циклу шаг cur
	ret
;  Слияние sticky-dirty (фон переписан под спрайтом) в флаги + сброс sticky.
;  ЗАДАЧА#36: гейт vfl_dany — sticky взведён лишь в 0.5% кадров, а проход шёл каждый.
vflm_gate:
	ld	a, (vfl_dany)
	or	a
	jp	z, vflm_done
;  ЗАДАЧА#53: sticky метит слот НЕ через фазу F, поэтому его может не быть в списке
;  активных. В такие тики (0.5% кадров) цикл подготовки идёт по всем 21 слоту, как
;  раньше — список тут не источник истины, а ускоритель.
	ld	(vns_full), a
	xor	a
	ld	(vfl_dany), a
	ld	hl, vfl_dirty
	ld	bc, vfl_flags
	ld	d, 21
vflm_loop:
	ld	a, (hl)
	or	a
	jp	z, vflm_next
	ld	(hl), 0
	ld	a, 1
	ld	(bc), a
	ld	(vfl_any), a
;  ЗАДАЧА#49 (2026-08-04): sticky взведён => vec_su_fixup ПЕРЕПИСАЛ блок фона этого слота
;  свежим содержимым fb, и «блок целиком нулевой» (ZFLAG слота, +0xD1) больше не доказано.
;  Снимаем — иначе слитая запись пропустила бы сдвиг блока, в котором теперь лежит
;  нарисованная клетка, и писала бы спрайт без неё. Место выбрано потому, что это
;  ЕДИНСТВЕННЫЙ проход, который заведомо видит КАЖДЫЙ слот, тронутый fixup'ом (сам fixup
;  живёт в vec_blit.asm). Пачку, которая идёт МЕЖДУ fixup'ом и этим проходом, закрывает
;  гейт vfl_dany в vso_merge1. Цена — только на редком пути (sticky в 0.5% кадров).
	push	hl
	ld	a, c	; idx = позиция в vfl_flags -> страница слота 0xE0+idx
	sub	vfl_flags&255
	add	a, 0x0E0
	ld	h, a
	ld	l, 0x0D1
	ld	(hl), 0
	pop	hl
vflm_next:
	inc	l
	inc	c
	dec	d
	jp	nz, vflm_loop
vflm_done:
	ld	a, (vfl_any)	; ни одного флага -> ни списка, ни фазы P, ни подготовки
	or	a
	jp	nz, vfla_go
	ld	(vsp_n), a	; A=0: список вывода пуст (как и делала голова цикла подготовки)
	ret
vfla_go:
;  ЗАДАЧА#53: сам список уже собран фазой F (см. vflf_cur_see) — здесь только терминатор.
	ld	a, (vfs_wr+1)
	ld	l, a
	ld	h, 255&(vfl_act>>8)
	ld	(hl), 0x0FF
	jp	vflp_start
;  === Компактный список ВИДИМЫХ слотов: тройки (idx, Y, X), терминатор 0xFF ==========
;  Внутренний цикл фазы P раньше шёл по всем 21 ячейкам, хотя видимых объектов ~3.7:
;  на каждый скрытый слот тратились чтение атрибута, сравнение и 4 inc hl. Замер:
;  51.7 итераций внутреннего цикла на проход = ~85% вхолостую.
;  СБОРЩИК СПИСКА (vfla_dead, 41 Б: свой проход по всем 21 слотам) СНЯТ 2026-08-06.
;  Задача#53 перенесла сборку в ФАЗУ F (vflf_cur_see пишет тройку прямо там, где уже
;  прочитаны Y и X), а старый проход остался лежать за безусловным `jp vflp_start` —
;  на него не ссылалась ни одна инструкция (механический скан «метка не упомянута ни в
;  одной строке кода» по всему src/). Здесь остаётся только терминатор (vfla_go выше).
;  === Фаза P: распространение ===
;  ЗАДАЧА#36: внешний индекс держим в РЕГИСТРЕ D (в редкой «флагованной» ветке он
;  клоббируется, поэтому там же сохраняется в vfl_ai и восстанавливается на выходе).
;  Было 101 такт на нефлагованный слот (три обращения к vfl_ai в памяти), стало 53.
;  D = МЛАДШИЙ БАЙТ адреса флага: это законно только потому, что vfl_flags выровнен на
;  страницу (vfl_flags&255 == 0, см. раскладку 0xFC00 в vec_boot.asm). B держим 0xFC на
;  всю фазу: внутренний цикл его не трогает (пишет только C).
vflp_start:
	ld	a, 2
	ld	(vfl_pass), a
	ld	b, 255&(vfl_flags>>8)
vflp_pass:
	xor	a
	ld	(vfl_chg), a
	ld	a, vfl_act&255	; ЗАДАЧА#53: внешний цикл идёт по СПИСКУ АКТИВНЫХ (4-5 записей),
	ld	(vfl_ai2), a	; а не по всем 21 слотам — 53 такта на каждый пустой слот
vflp_aloop:
	ld	a, (vfl_ai2)
	ld	l, a
	ld	h, 255&(vfl_act>>8)
	ld	a, (hl)
	cp	0x0FF	; конец списка
	jp	z, vflp_pdone
	ld	d, a	; D = индекс активного слота
	ld	a, l
	inc	a
	ld	(vfl_ai2), a
	ld	b, 255&(vfl_flags>>8)
	ld	c, d
	ld	a, (bc)	; не флагован -> дальше
	or	a
	jp	z, vflp_anext
	ld	a, d
	ld	(vfl_ai), a	; координаты флагового a
	ld	l, a
	ld	h, 0
	add	hl, hl
	add	hl, hl
	ld	de, sprAttrib
	add	hl, de
	ld	a, (hl)
	ld	(vfa_yc), a
	inc	hl
	ld	a, (hl)
	ld	(vfa_xc), a
	ld	a, (vfl_ai)
	ld	l, a
	ld	h, 0
	ld	d, h
	ld	e, a
	add	hl, hl
	add	hl, de
	ld	de, vec_nsp_prev
	add	hl, de
	ld	a, (hl)
	ld	(vfa_yp), a
	inc	hl
