;  ===== СМЕНА ПРЕДМЕТА В РУКАХ БЕЗ ГАШЕНИЯ ЭКРАНА (2026-08-06) ======================
;  ЖАЛОБА/ЗАМЕР: при КАЖДОМ подборе и сбросе предмета (cogeObjeto/quitaObjeto) ВСЕ
;  спрайты сцены мигали. Виноват был vec_spr_flush: он снимает с экрана ВСЕХ и
