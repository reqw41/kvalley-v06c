;  ===== КИРКА: ШУМ КАК НА MSX (2026-11-10) =====
;  На MSX кирка — единственный шумовой звук игры: 6 тиков шума AY на канале C (замер исходного драйвера
;  в режиме AY: N=28 гр.15, 28/15, 28/8, 28/8, N=6 гр.12, 6/12). В режиме ВИ53 шума не было — снятый
;  поток давал тишину и «хвост» тона. Здесь, как в Bruce Lee (src/vec/sound.asm, nz_bit): случайные биты
;  (Галуа 16, маска 0xB4) на выход счётчика 2 ВИ53 — канала эффектов. В отличие от Bruce Lee бит — ОДНА
;  запись управляющего слова без счёта: режим 0 — выход внизу, режим 2 — выход вверху, счётчик стоит
;  (так и в vector06js, и в Emu80, и по описанию 8253). Счёт не пишется вовсе, поэтому «полузагруженного»
;  счёта не бывает. Шаг бита — как у шума AY MSX (16*N / 1.79 МГц = ~26.8*N тактов 3 МГц): виток простоя
;  ~210 тактов + 15 на единицу задержки.
;  Громкости у ВИ53 нет: огибающая 15/8/12 — только «звучит».
;  ГДЕ ИДУТ БИТЫ: в простое главного цикла (dummyLoop, вместо halt) и вспышкой ~3 мс в тике звука, как в Bruce Lee.
;  Пока идёт остальной игровой тик (~половина кадра при копании), шума нет — 1-битному каналу без громкости
;  нечем его заполнить (меандр-заполнитель пробовали: красит шум в тон).
;  КАНАЛ: токен NZ берёт канал 3 у часов, как нота (vtm_grab); END/OFF/нота на канале 3 и глушение
;  снимают шум (vnz_stop), END возвращает канал часам штатно (vc_off -> vtm_start).
vnz_dly:	equ	0x0FD00	; 1Б: задержка бита шума (0 = не шумит); бывший vkn_list, в игре мёртв
vnz_r:	equ	0x0FD01	; 2Б: регистр Галуа
vnz_in:	equ	0x0FD03	; 1Б: 1 = цикл простоя шумит (vnz_idle)
vnz_rel:	equ	0x0FD35	; 1Б: 1 = кирка кончилась, пока шумел цикл: канал часам вернёт он (хвост vcm_p2, мёртв)

vnz_ptab:
	dw	vnz_pick
;  4 тика N=28 (бит ~750 тактов: задержка 36), 2 тика N=6 (~160: задержка 1), конец. Шаг бита — период шума AY
;  (16*N тактов AY 1.79 МГц = 26.8*N тактов 3 МГц), та же формула, что в Bruce Lee (48*N для AY 1 МГц у CPC).
vnz_pick:
	db	0x04, 4, 0x08, 36, 0x04, 2, 0x08, 1, 0x00

;  Токен NZ n (ожидающий; только голос 3): HL -> n.
vpl_nz:
	ld	a, (hl)
	inc	hl
	push	af
	push	hl
	call	vw_addr	; хочу-состояние канала: выключен (после паузы шум не воскресает)
	ld	(hl), 0
	pop	hl
	call	vpl_fin
	pop	af
	ld	b, a
	ld	a, (vec_snd_mode)	; режим S: 2 = тишина
	cp	2
	ret	nc
	ld	a, b
	ld	(vnz_dly), a
	ld	hl, (vnz_r)	; регистр Галуа из нуля не выходит (на буте p3 занулена): засеять — иначе все биты 0, шума нет
	ld	a, h
	or	l
	jp	nz, vpz_s
	ld	hl, 0x0ACE1
	ld	(vnz_r), hl
vpz_s:
	ld	a, (vec_vch+2)
	or	a
	ret	nz	; канал уже наш (прошлый NZ)
	jp	vtm_grab

;  C = канал. Канал 3 шумит -> шум снять, счётчик вернуть в режим 3.
vnz_stop:
	ld	a, c
	cp	2
	ret	nz
	ld	a, (vnz_dly)
	or	a
	ret	z
	xor	a
	ld	(vnz_dly), a
	ld	a, 0x0B6	; счётчик 2 снова режим 3: нота допишет делитель, vc_off вернёт канал часам
	out	(0x08), a	; (vec_vch+2 остаётся 1 — канал наш с NZ)
	or	a	; NZ: шум был и снят
	ret

;  vc_off, C = канал. Канал 3 шумит -> шум снять; если шумит цикл простоя — канал часам вернёт он: NZ.
vnz_off:
	ld	a, c
	cp	2
	jp	nz, vno_z
	call	vnz_stop
	ret	z
	ld	a, (vnz_in)
	or	a
	ret	z
	ld	(vnz_rel), a
	ret
vno_z:
	xor	a
	ret
;  Вспышка в тике звука (как в Bruce Lee, src/vec/sound.asm, но длиннее): 28 бит при N=28 (~21 тыс. тактов),
;  100 при N=6 (~16 тыс.). При копании игровой тик берёт ~30 тыс. из 60 тыс. кадра, так что вместе с простоем шум
;  звучит ~3/4 кадра и в кадр укладывается (с 12 битами — 25-50%, на слух «не как на MSX»). Тик звука
;  всегда идёт под DI (шапка ISR, кооп-тики DI-серий, опрос после пачки). В остальное время игрового тика
;  счётчик стоит на последнем бите (тишина) — тон-заполнитель снят: он красил шум в 2-4 кГц.
vnz_burst:
	ld	hl, (vnz_r)
	ld	e, 28
	ld	a, (vnz_dly)
	cp	2
	jp	nc, vnb_l
	ld	e, 100
vnb_l:
	call	vnz_nx
	ld	a, (vnz_dly)
	or	a
	jp	z, vnb_x
	ld	b, a
	ld	a, c
	out	(0x08), a
	call	vnz_dl
	dec	e
	jp	nz, vnb_l
vnb_x:
	ld	(vnz_r), hl
	ret

;  Простой главного цикла: биты, пока шумит; прерывание (тик игры) может шум снять.
;  ГОНКА (жалоба «музыка зависает»): прерывание между проверкой «шумит?» и записью бита заканчивало
;  кирку и сразу заводило часы (vtm_arm), а наш бит перебивал им режим — счётчик вставал. DI на бит
;  терял кадровые IRQ. Поэтому возврат канала часам, пока шумит цикл, делает САМ цикл, на выходе
;  (vnz_off ставит vnz_rel, а не зовёт vtm_start), — после своего последнего бита.
vnz_idle:
	ld	a, 1
	ld	(vnz_in), a
	ld	hl, (vnz_r)
vni_l:
	ld	a, (vec_paused)
	or	a
	jp	nz, vni_x
	call	vnz_nx
	ld	a, (vnz_dly)
	or	a
	jp	z, vni_x
	ld	b, a
	ld	a, c
	out	(0x08), a
	call	vnz_dl
	jp	vni_l
vni_x:
	ld	(vnz_r), hl
	di
	xor	a
	ld	(vnz_in), a
	ld	a, (vnz_rel)
	or	a
	jp	z, vni_e
	xor	a
	ld	(vnz_rel), a
	ld	c, 2
	call	vc_off	; шум уже снят -> канал часам (vtm_start)
vni_e:
	ei
	jp	dummyLoop

;  Следующий бит: HL = регистр Галуа -> C = управляющее слово счётчика 2 (0xB0 режим 0 = выход внизу,
;  0xB4 режим 2 без счёта = выход вверху). Портит A.
vnz_nx:
	ld	a, h
	or	a
	rra
	ld	h, a
	ld	a, l
	rra
	ld	l, a
	ld	c, 0x0B0
	ret	nc
	ld	a, h
	xor	0xB4
	ld	h, a
	ld	c, 0x0B4
	ret
vnz_dl:
	dec	b
	jp	nz, vnz_dl
	ret
