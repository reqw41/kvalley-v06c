;  vec_sprout.asm перед выравниванием свободно 7 байт: любые лишние байты ТАМ выталкивают
;  pre-align через границу страницы и растят образ сразу на 256 Б (проверено: первая
;  редакция правки, положенная в vsp_wrec, дала +256 Б и переполнение потолка). Это тот
;  же приём, что уже применён к vec_ending/vec_hoptab/vec_repair — см. src/kvalley_8c.asm.
;
;  ЗАЧЕМ ПРАВКА. Сортировка порядка вывода vso_sortord — вставочная, КВАДРАТИЧНАЯ по длине
;  списка. Замер tools/verify/sortord_cost.js (база b2c7799, 4000 кадров, прогулка + чит N
;  раз в 350 кадров, 8 форс-кадров в выборке):
;    обычный кадр  avg 1396 т;
;    ФОРС-КАДР (смена GameStatus: vfl_lastgs метит все 21 слот) n=8, ПИК 6800 т,
;    и состав списка на нём РОВНО ПОПОЛАМ — 4 видимых объекта и 4 СКРЫТЫХ, у которых слот
;    УЖЕ невалиден (32 и 32 за восемь форс-кадров). Вторая половина — чистый балласт: она
;    ничего не рисует, не стирает и не сохраняет, но сортируется наравне со всеми.
;  ПОСЛЕ: пик 6800 -> 4416 т (-35%, n=8 -> n=6), средняя форс-кадра 5516 -> 2884 т (-48%),
;  ОБЫЧНЫЙ кадр 1396 -> 1210 т (-13%), сумма тактов сортировки за 4000 кадров
;  814976 -> 700868 (-14%), скрытых с невалидным слотом в списках 155 -> 0.
;  Бюджет кадра не тронут (frame_budget work%: 40.0/48.5 -> 39.9/48.8).
;  ЗАЯВЛЕННЫХ ЗАДАЧЕЙ n=21 / 37.7 тыс. тактов БОЛЬШЕ НЕ СУЩЕСТВУЕТ: бюджет подготовки
;  задачи#53 (слоты 0-5 всегда + не более двух из 6-20) режет список до 8 ещё до нас.
;
;  ЧТО ДЕЛАЕТ ПАЧКА СО СКРЫТЫМ ОБЪЕКТОМ (pending=2), по порядку:
;    1) vec_su_restore — стереть его прошлый вывод;
;    2) vec_su_save -> vsu_hide — обнулить шапку слота;
;    3) vso_prev — снимок Y,X,pat в vec_nsp_prev.
;  Если слот УЖЕ невалиден, (1) выходит на первой же проверке (`ld a,(hl) / or a / ret z`),
;  а (2) пишет ноль в ноль. Обе работы пустые, и место в списке вывода объекту не нужно.
;  ШЛЕЙФА ЗДЕСЬ БЫТЬ НЕ МОЖЕТ ПО ПОСТРОЕНИЮ: снимаем ровно по тому же байту (+0x00), по
;  которому стирание и так выходит вхолостую. Гейт spr_resid_gate (4000 кадров, 11 смен
;  сцены) — 0 пачек по всем четырём пунктам, пункт C (нарисовано вне габаритов валидных
;  слотов) в том числе.
;
;  ПОЧЕМУ (3) ОБЯЗАТЕЛЬНА И ДЕЛАЕТСЯ ЗДЕСЬ. vec_nsp_prev — вход детектора изменений
;  (фаза F). Не обновив его, получаем «cur скрыт, prev видим» НАВСЕГДА: объект флагуется
;  КАЖДЫЙ тик, и гейт «ничего не изменилось» больше никогда не закрывается. ЭТО ЗАМЕРЕНО,
;  а не предположено. Проба (4000 кадров): ветка снимает объект из списка 159 раз, и в 6
;  из них prev БЫЛ ВИДИМ — слоты 4 (одежда героя: дедуп общей плоскости выдаёт соседу
;  pending=3, и тот выходит из пачки с видимым prev и невалидным слотом) и 19/20 (спрайты
;  карты долины). Сборка БЕЗ этой строки (проверено прямой заменой на ret): вызовов
;  подготовки за те же 4000 кадров 1029 против 567 — тик гоняется впустую на 81% чаще.
;  ПОЧЕМУ prev В ТИКЕ ЗАКОННО (шапка vec_sprout.asm требует обновлять его ПАЧКОЙ): правило
;  защищает от потери ВЫВОДА, если пачка не успела отработать. Здесь выводить нечего и
;  стирать нечего — терять нечего.
;
;  ПОЧЕМУ «ПОЛОЖИТЬ И ВЫНУТЬ», А НЕ «НЕ КЛАСТЬ». Запись вывода (+0x96..+0x9E) объекту
;  нужна в любом случае — её читают vso_static, цепочка дедупа и быстрый повтор подготовки,
;  — а пишет её vsp_wrec тем же куском кода, что и постановку в список. Разрезать vsp_wrec
;  надвое стоило бы 17 байт ПЕРЕД выравниванием (то есть 256 Б образа), а снять хвост
;  списка обратно — это `dec (hl)` по vsp_n. Вложенная пачка лишний элемент увидеть не
;  может: список она забирает только по vsp_rdy, а тот поднимается в самом конце подготовки.
;  ЦЕНА: 18 Б образа (pre-align при этом ОСВОБОДИЛОСЬ 2 Б), на скрытый объект с валидным
;  слотом +98 тактов (за 4000 кадров таких 16), на снятый — минус целая итерация сортировки.
vsp_hidep:
	ld	a, 2	; pending=2: только стереть и инвалидировать слот
	call	vsp_wrec
	call	vec_su_ptr
	ld	a, (hl)
	or	a
	ret	nz
	jp	vsp_hdrop

