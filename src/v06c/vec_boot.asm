;  === АППАРАТНЫЙ ВЕРТИКАЛЬНЫЙ СКРОЛЛ (порт 0x03 = PA PPI1) ============================
;  Значение = fb-строка, с которой начинается вывод кадра; дальше строки идут по убыванию
;  циклически. 0xFF (старое) = вывод с fb 255 => MSX-экран (наши Y 0..191 = fb 255..64)
;  прижат к ВЕРХУ, а fb 63..0 (Y 192..255) висят внизу пустой полосой.
;  0x1F = вывод с fb 31 => сверху 32 строки (fb 31..0), затем весь игровой экран
;  (fb 255..64), затем снизу 32 строки (fb 63..32) — поле ПО ЦЕНТРУ кадра.
;  Сдвиг чисто аппаратный: блиттер, спрайты и save-under пишут по прежним адресам,
;  добавленных тактов ноль (то же число out'ов, другое непосредственное значение).
;  ПОБОЧНАЯ ВЫГОДА: луч сначала проходит 32 статичные строки (32 x 192 = 6144 такта) и лишь
;  потом входит в игровое поле => безопасное окно рендера растёт с ~10.7К до ~16.8К тактов.
;  ВНИМАНИЕ: порт 0x03 совмещён с выбором ряда клавиатуры (vec_scan_keys) — после скана
;  ОБА восстановления обязаны класть сюда vec_vscroll, а не 0xFF.
;  === ЗАДАЧА#43 (2026-08-03): ПОЛЕ ПРИЖАТО К НИЗУ КАДРА ==============================
