;  затем весь игровой экран (fb 255..64) до последней видимой строки, снизу НИЧЕГО.
;  Это ФИЗИЧЕСКИЙ ПРЕДЕЛ прижатия: картинка 256 строк, поле 192, значит сверху можно отдать
