;  процедуры размером 15..29 Б через `.align` переводит образ в годную раскладку
;  (зазор 241+22-256 = 7 Б, хвост 29-22 = 7 Б); резерв от переноса не меняется —
;  см. docs/DESIGN-2026-08-06-sprout-unification.md §0. Такты не меняются ни на один:
;  вызовы абсолютные, тело то же.
;  vec_rc (ФАЗА 5 УНИФИКАЦИИ, 2026-08-06): АДРЕС В NAME TABLE -> РЯД/СТОЛБЕЦ БЛИТТЕРА.
;  Вход HL = адрес клетки name table. Выход C = столбец = L & 31, B = ряд =
;  (H&0x3F - 0x38)*8 + L>>5. Клоб A, B, C, E; HL не трогает.
;  Один и тот же расчёт стоял ТРИЖДЫ по 21-22 Б: vec_text_blit, dt_vec_draw (замена MSX
;  drawTile) и drawCortinilla2 (шторка). `and 0x3F` нужен только vec_text_blit, для двух
;  других он холостой: у них H = 0x38..0x3B по построению (cellhi 0..2, 24 ряда шторки).
;  Цена — +34 такта на вызов поверх полного блита тайла (~1500 тактов), то есть 2%.
vec_rc:
	ld	a, l	; C = col = L & 31
	and	0x1F
	ld	c, a
	ld	a, l	; E = L>>5
	and	0x0E0
	rlca
	rlca
	rlca
	ld	e, a
	ld	a, h	; cellhi 0..2
	and	0x3F
	sub	0x38
	add	a, a	; cellhi*8
	add	a, a
	add	a, a
	add	a, e	; B = ряд = cellhi*8 + L>>5
	ld	b, a
	ret

