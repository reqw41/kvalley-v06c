; ============================================================================
; vec_ending.asm — ЦВЕТ ФИНАЛЬНОГО ЭКРАНА (задача #15).
; Отдельный модуль и ПОСЛЕ vec_tables.asm намеренно: код концовки холодный, а зазор
; выравнивания перед vec_revtab всё равно пропадал бы впустую (см. шапку kvalley_8c.asm,
; правило про перенос процедур в хвост). Всё, что здесь лежит, зовётся ровно из двух мест:
; setupEnding (vec_ct_ending) и патч-сайтов vbt8_ecj / vec_brillo_pal.
; ============================================================================
;  vec_ct_ending: ЧЕТВЁРТЫЙ ПРОФИЛЬ ЦВЕТА — финальный экран (задача #15). Зовётся из
;  setupEnding сразу после распаковки тайлсета концовки, до первой отрисовки сцены.
;  ПОЧЕМУ ЭТО ВОСЕМЬ БАЙТ, А НЕ ЕЩЁ ОДНА ТАБЛИЦА НА 256+120. Профиль концовки в оригинале
;  = профиль этапа, у которого перезаписаны РОВНО тайлы 0x90-0x97 (setupEnding грузит
;  endingColors только на них; всё остальное — табло, шрифт, дверь — остаётся от уровня и
;  на Векторе уже лежит верным). Дельта посчитана офлайн из MSX color table сцены
;  (tools/gfx/msx2vec.py, профиль `ending`) и против vec_ct_stage_a отличается тремя
;  байтами: 0x45/0x46/0x47 теряют белый флаг (он и делал белые куски на малых пирамидах,
;  белый пол и белые звёзды), а пол становится solid (сплошной фон под шашку, см.
;  vec_end_floor). Полная таблица дала бы те же три байта ценой ~200 Б образа.
;  Z = vec_fr_par==0 и tickInProgress==0. После старта tickMain ставит par=2.
vec_25_logic:
	ld	a, (vec_fr_par)
	ld	hl, tickInProgress
	or	(hl)
	ret
vec_ct_ending:
	ld	hl, vec_ct_ending_modes
	ld	de, vec_tilemode+0x40
	ld	bc, 8
	call	vec_ldir_fwd
	ld	a, 0x028	; развилка кирпича 0x40-0x44 -> диапазон концовки 0x40-0x67
	ld	(vbt8_ecp+1), a
	ld	hl, vec_end_tile
	ld	(vbt8_ecj+1), hl
	di	; палитра сцены вместо покадровой схемы камней (тот же приём, что у карты)
	ld	a, 0x0C3
	ld	(vec_brillo_pal), a
	ld	hl, vbp_end
	ld	(vec_brillo_pal+1), hl
	ei
;  ЗАДАЧА #21: ПАЛИТРУ ФИНАЛА СТАВИМ ПРЯМО ЗДЕСЬ И ДОЖИДАЕМСЯ. Одного патча диспетчера мало:
;  сцена концовки строится дальше под ДЛИННЫМ DI (vec_end_* рисует пирамиду и звёзды), внутрь
;  которого прерывание не попадает, и vbp_end впервые исполнялся уже ПОСЛЕ отрисовки — замер
;  показывал 5244 пикселя, разом менявших цвет на 12-м кадре после появления картинки. Экран в
;  этой точке пуст (шторка доела уровень, 0 нефоновых пикселей), так что смену видеть некому.
	ld	hl, vec_pal_end+15
	jp	vsp_sync
;  vec_ct_base: вернуть развилку тайлов 0x40-0x44 в базу (двухтонный кирпич лабиринта).
;  Зовётся из waitEnding сразу после `GameStatus = Stage Clear`, то есть патч живёт РОВНО
;  столько, сколько сама концовка. Палитру здесь НЕ трогаем: сцену ещё съедает шторка, и
;  доедать её надо в цветах концовки; штатную вернёт setupPergamino (карта) или setupStage.
vec_ct_base:
	ld	a, 5
	ld	(vbt8_ecp+1), a
	push	hl
	ld	hl, vbt8_brick
	ld	(vbt8_ecj+1), hl
	pop	hl
	ret
;  Байт режима: bit7 white, биты 6-3 счётчик строк, биты 2-0 режим (1 pat, 3 solid).
vec_ct_ending_modes:
	db	0x041,0x041	; 0x40/0x41 кладка   (MSX 60/A0: fg есть, фон прозрачный -> pat)
	db	0x041,0x041	; 0x42/0x43 лев.грань (MSX 80 -> pat)
	db	0x041,0x041	; 0x44/0x45 прав.грань (MSX 60 -> pat; БЫЛО C1 = белая заливка)
	db	0x043		; 0x46 пол   (MSX 8A/6A: фон A не прозрачен -> solid)
	db	0x041		; 0x47 звезда (MSX 50 -> pat)

;  ====== ФИНАЛЬНЫЙ ЭКРАН (задача #15) — post-align хвост =================================
;  ЭТАЛОН СНЯТ С ОРИГИНАЛА, НЕ ПОДОБРАН НА ГЛАЗ. Картридж legacy/msx/kvalley_z80.rom
;  прогнан в headless-WebMSX (MCP msx-emu), GameStatus=0x0A / subStatus=0, и снята MSX
;  color table сцены. Тайлы концовки (MSX 0x90-0x97 = Вектор 0x40-0x47), 8 строк цвета:
;    0x40 грань кирпича | 0x41 заливка кирпича : 60 60 A0 A0 60 60 A0 A0
;         => строки 0,1 и 4,5 цвет 6 (тёмн.красный), строки 2,3 и 6,7 цвет A (тёмн.жёлтый)
;         — это и есть КЛАДКА большой пирамиды: два тона по парам строк на чёрном фоне;
;    0x42 лев.грань   | 0x43 заливка : 80 x8 => цвет 8 (средн.красный) — СВЕТЛАЯ грань
;         малых пирамид (лососевая);
;    0x44 прав.грань  | 0x45 заливка : 60 x8 => цвет 6 — ТЁМНАЯ грань (терракота);
;    0x46 пол         : 8A 8A 8A 8A 6A 6A 6A 6A => фон A (песок) + крошка 8/6 (красная);
;    0x47 звезда      : 50 x8 => цвет 5 на backdrop 4. На Векторе небо idx0 чёрное
;         (8c: отдельного backdrop нет), поэтому звезда — idx12 БЕЛЫЙ, иначе голубые точки.
;  РАСКЛАДКА ПО СЛОТАМ (8 цветов не режем, инвариант color[2k]==color[2k+1] держим):
;    idx0  чёрное небо            idx8  терракота 056h (MSX 6): тон A кладки, прав.грань,
;    idx2  одежда героя (серый)         крошка пола
;    idx4  (свободен; на финале пуст)  idx10 песок 077h (MSX A): тон B кладки, фон пола
;    idx6  оверлапы героя         idx12 белый: табло, тексты, ЗВЁЗДЫ, уступ двери
;                                 idx14 лосось 05Fh (MSX 8): светлая грань малых пирамид
;  idx4 на финале пуст (гемы/аура не живут). Звёзды — idx12 БЕЛЫЙ: MSX цвет 5 на backdrop 4
;  (R7=#E4); у Вектора idx0 чёрный, и тот же 5 в idx4 читался голубыми точками.
;  MSX 6 и 8 на 3-битном ЦАП Вектора почти неразличимы (обе просятся в 05Fh), и титул их
;  честно слил. ЗДЕСЬ СЛИВАТЬ НЕЛЬЗЯ — двухтонность малых пирамид это ровно они, поэтому
;  тёмный тон опущен на ступень по R и G: 056h = (192,64,64) против 05Fh = (224,96,64).
vec_end_tile:	; A = тайл-0x40 (0x00..0x27); вход из патча vbt8_ecj. p0 уже заблитен vbt_core
	cp	8
	jp	nc, vet_door	; 0x48-0x67: вход в большую пирамиду и дыра между диапазонами
	ld	hl, kv_end_planes
	call	ADD_A_HL	; BC/DE целы (add a,l / ld l,a / inc h)
	ld	a, (hl)
	cp	0x0FF
	jp	z, vbt8_brick	; кладка: двухтонная по парам строк, маска 0x33 = MSX 6/A
	cp	0x0FE
	jp	z, vec_end_floor
	jp	vbt8_planes	; остальные — штатной раскладкой плоскостей
vet_door:
;  Диапазон патча расширен до 0x40-0x67 ради ВХОДА В ПИРАМИДУ (тайлы 0x63-0x67). Дыра
;  0x48-0x62 внутрь патча попала попутно — своей таблицы ей не заводим (на финальном
;  экране этих тайлов нет: name table сцены = 0x00, шрифт табло 0x10-0x3F, 0x40-0x47 и
;  0x63-0x67), просто уводим на штатный путь. Дешевле 27 байт наполнителя в таблице.
	sub	0x23	; 0x63-0x40
	cp	5
	jp	nc, vbt8_p1
;  [2026-08-04] СОБСТВЕННЫЙ ПОСТРОЧНЫЙ КОМПОЗИТОР vec_end_door СНЯТ (шаг из
;  docs/BLITTER_UNIFICATION.md): его модель «P = (fg несёт бит P ? паттерн : 0) |
;  (bg несёт бит P ? ~паттерн : 0)» на каждой строке даёт РОВНО одну из четырёх заливок
;  сегментного движка vbt8_seg (оба -> 0xFF, только fg -> шейп, только bg -> ~шейп,
;  никто -> ноль), а строки в тайлах входа идут группами. Пять тайлов = пять сегментных
;  программ (0x67 совпал с готовой kv_pg_stair — у лестницы проёма та же раскладка
;  «белый шейп на сплошном сером»). Раскладки перегнаны из масок kv_end_door построчно,
;  бит в бит; исходные цвета и вывод модели — в блоке-эталоне выше. Источник паттерна
;  тот же: vbt8_ad ведёт тайлы 0x63-0x67 (folded 0x318-0x33F) в pat_maze_base — ровно
;  адрес pat_maze_base+тайл*8 старого композитора. Было 104 Б кода + 30 Б масок + 3 Б
;  ved_* скретча нулевой страницы; стало 14 Б диспетчера + 10 Б таблицы + 31 Б программ.
	add	a, a	; A = (тайл-0x63)*2 — индекс в таблице программ
	ld	hl, kv_end_doorpg
	call	ADD_A_HL	; BC/DE целы (add a,l / ld l,a / inc h)
	ld	a, (hl)
	inc	hl
	ld	h, (hl)
	ld	l, a	; HL = сегментная программа тайла
	jp	vbt8_seg
kv_end_doorpg:	; тайлы 0x63..0x67 входа в большую пирамиду
	dw	kv_pg_door63, kv_pg_door64, kv_pg_door65, kv_pg_door66, kv_pg_stair
;  Байт = ровно тот формат, что читают штатные шаги vbt8_p1/p2/p0 (см. kv_gem_planes):
;  бит7 -> p1 = шейп, бит0 -> p2 = шейп, бит1 -> p0 гасится. 0FFh и 0FEh — свои пути.
kv_end_planes:
	db	0x0FF, 0x0FF	; 0x40/0x41 кладка большой пирамиды -> vbt8_brick (idx8+idx10)
	db	0x081, 0x081	; 0x42/0x43 левая грань малых: p0+p1+p2 -> idx14 ЛОСОСЬ
	db	0x000, 0x000	; 0x44/0x45 правая грань малых: только p0 -> idx8 ТЕРРАКОТА
	db	0x0FE		; 0x46 пол -> vec_end_floor
	db	0x080		; 0x47 звезда: p0+p1 = шейп -> idx12 БЕЛЫЙ (не idx4: на чёрном небе MSX-5 читается голубым)
;  ПОЛ: в профиле у тайла 0x46 режим 3 (solid), т.е. vbt_core уже залил p0 = 0FFh — фон
;  клетки НЕ чёрный. Второй цвет даёт p2 = ~паттерн: пиксель паттерна -> p2=0 -> idx8
;  (терракотовая крошка), фон -> p2=1 -> idx10 (песок). Это ровно шашка оригинала
;  (fg 8/6 на bg A), а не сплошная полоса. Паттерн перечитываем: p0 его уже не хранит.
vec_end_floor:
	ld	hl, pat_maze_base+0x46*8
	ld	a, c	; DE = приёмник p2 (0xC0+col : 255-row*8)
	add	a, 0x0C0
	ld	d, a
	ld	a, (vbt8_e)
	ld	e, a
	ld	b, 8
vef_l:
	ld	a, (hl)
	cpl
	ld	(de), a
	inc	hl
	dec	e
	dec	b
	jp	nz, vef_l
	ld	a, c	; p1 = 0 (иначе клетка донашивает чужие пиксели)
	add	a, 0x0A0
	ld	d, a
	ld	a, (vbt8_e)
	ld	e, a
	xor	a
	jp	vbt8_wrow
;  ====== ВХОД В БОЛЬШУЮ ПИРАМИДУ, тайлы 0x63-0x67 (правый нижний угол) ==================
;  ЖАЛОБА ВЛАДЕЛЬЦА (2026-07-31, по железу): «в углу справа вход в пирамиду белый, в
;  оригинале он многоцветный — жёлтый и бело-серые ступени». Скос и ступени у нас слились
;  в один белый.
;  ЭТАЛОН СНЯТ С КАРТРИДЖА (headless-WebMSX, GameStatus=0x0A / subStatus=0). ВАЖНАЯ
;  НАХОДКА: тайлы двери НЕ сдвинуты на 0x50, как тайлсет сцены, — в оригинале это те же
;  0x63-0x67 (проверено чтением name table: ряды 16-18, столбцы 30-31 = 63 64 / 00 65 /
;  66 67). Их цвет не входит в endingColors и достаётся от уровня. Восемь строк цвета:
;    0x63 EA EA EA EA EA A0 A0 A0   0x64 EA A0 A0 A0 A0 A0 A0 A0   (скос: fg E серый / A жёлт)
;    0x65 F0 F0 F0 F0 F0 E0 F0 E0   0x66 F0 F0 F0 E0 E0 FE FE FE   (ступени: F белый / E серый)
;    0x67 FE FE FE FE FE FE FE FE
;  Итого нужны ЧЕТЫРЕ цвета, и все уже есть в палитре сцены — нового слота не потребовалось:
;    MSX A т.жёлтый -> idx10 песок 077h    MSX F белый -> idx12 0FFh
;    MSX E серый    -> idx2  0F6h (192,192,192 против MSX 204,204,204 — попадание в тон;
;                     на финальном экране idx2 занят только одеждой героя, 33 пикселя)
;    MSX 0 прозрачный -> idx0 чёрный
;  МАСКИ НЕ ЗАВИСЯТ ОТ УРОВНЯ. Тайлы входа берутся из тайлсета этапа, а не из endingTiles,
;  поэтому важно, что цвет 0x63-0x67 у ВСЕХ пятнадцати пирамид одинаков (сверено по снимкам
;  color table всех уровней: между ними различаются только кирпич 0x40-0x44 и блёстки гем
;  0x51-0x53). Значит чит E из первой пирамиды и настоящая концовка после пятнадцатой дают
;  один и тот же вход.
;  ПОЧЕМУ НЕ ДВУХТОННАЯ МЕХАНИКА КИРПИЧА. У kv_stone_scheme/vbt8_brick тон меняется ПО
;  СТРОКАМ при одном и том же «шейп/фон», а здесь по строкам меняется И цвет шейпа, И цвет
;  фона (у 0x63 сверху серый-на-жёлтом, снизу жёлтый-на-чёрном), причём фон бывает НЕ
;  чёрным. Двумя тонами это не выражается — нужен общий построчный композитор.
;  МОДЕЛЬ (историческая, теперь исполняется движком vbt8_seg): для строки с цветом шейпа
;  Cf и цветом фона Cb плоскость P = (у Cf есть бит P ? паттерн : 0) | (у Cb есть бит P ?
;  ~паттерн : 0). Биты цветов (p0,p1,p2): чёрн 000, серый 001, песок 101, белый 110.
;  На языке сегментов: оба бита -> 0xFF, только Cf -> шейп, только Cb -> ~шейп, ни
;  одного -> ноль. Ниже — прежние маски строк, ПЕРЕГНАННЫЕ в сегментные программы
;  построчно (порядок плоскостей p1, p2, p0 — как требует движок; MSB маски = строка 0).
;  [2026-08-04] vec_end_door + kv_end_door (104+30 Б) СНЯТЫ, см. vet_door.
;  Формат байта сегмента — в шапке vbt8_seg (vec_blit.asm).
;  0x63 скос слева: строки 0-4 «серый шейп на песке», строки 5-7 «песочный шейп на чёрном».
;  Было масками (p0,p1,p2): 07/F8, 00/00, FF/F8.
kv_pg_door63:
	db	0x09C	; p1: 8 строк нулём (ни у серого, ни у песка нет бита p1)
	db	0x011, 0x08A	; p2: 5 строк 0xFF (серый на песке: p2 у обоих) + 3 строки шейпом
	db	0x013, 0x08A	; p0: 5 строк ~шейп (p0 только у песка-фона) + 3 строки шейпом
;  0x64 скос справа: строка 0 «серый на песке», строки 1-7 «песочный шейп на чёрном».
;  Было масками: 7F/80, 00/00, FF/80.
kv_pg_door64:
	db	0x09C	; p1: 8 строк нулём
	db	0x001, 0x09A	; p2: строка 0 = 0xFF + 7 строк шейпом
	db	0x003, 0x09A	; p0: строка 0 = ~шейп + 7 строк шейпом
;  0x65 ступени справа: белый шейп, у строк 5 и 7 шейп серый; фон везде чёрный.
;  Было масками: FA/00, FA/00, 05/00 (FA = строки 0-4,6; 05 = строки 5,7).
kv_pg_door65:
	db	0x012, 0x000, 0x002, 0x080	; p1: 5 шейп, 1 ноль, 1 шейп, 1 ноль
	db	0x010, 0x002, 0x000, 0x082	; p2: 5 ноль, 1 шейп, 1 ноль, 1 шейп
	db	0x012, 0x000, 0x002, 0x080	; p0: как p1 (белый = p0+p1)
;  0x66 ступени слева-снизу: строки 0-2 белый шейп, 3-4 серый шейп, 5-7 белый на сером.
;  Было масками: E7/00, E7/00, 18/07.
kv_pg_door66:
	db	0x00A, 0x004, 0x08A	; p1: 3 шейп, 2 ноль, 3 шейп
	db	0x008, 0x006, 0x08B	; p2: 3 ноль, 2 шейп (серый шейп), 3 ~шейп (серый фон)
	db	0x00A, 0x004, 0x08A	; p0: как p1
;  0x67 «белые полосы на сплошном сером» (было масками FF/00, FF/00, 00/FF) — это
;  побайтно kv_pg_stair (лестница проёма), своей программы не заводим (см. kv_end_doorpg).
;  Скретч ved_* (нулевая страница 0x3B-0x3D) больше не нужен — участок снова СВОБОДЕН,
;  опись в vec_boot.asm обновлена.
;  vbp_end: ветка vec_brillo_pal на время концовки (патч-сайт тот же, что у карты долины).
;  Базовый vbp каждый кадр переписывает idx4 (аура) и idx8/idx10 (схема камней) — без патча
;  звёзды и кладка съезжали бы уже в следующем кадре. Палитру сцены ставит ОДИН раз
;  vsp_sync в vec_ct_ending; сюда каждый кадр больше не грузим: полный vsp_load (~2 тыс.
;  тактов, 16 слотов) на вложенном ISR вылезал в видимый верх (дёрганье/глитч каймы).
vbp_end:
	ret
vec_pal_end:
	db	0x000,0x000,0x0F6,0x0F6, 0x0E3,0x0E3,0x05F,0x05F, 0x056,0x056,0x077,0x077, 0x0FF,0x0FF,0x05F,0x05F


;  ====== ПЕРЕНЕСЕНО ИЗ vec_ldir.asm (ЗАДАЧА#53, post-align хвост) ======================
;  Эмуляция Z80-идиом (`ex af,af'`, `(ix+n)`) — холодный по размещению код: он ничем не
;  связан с соседями, а в pre-align занимал ровно те 76 байт, из-за которых `.align 256`
