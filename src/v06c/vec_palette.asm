;  === ФАЗА 1 8-ЦВЕТ (KV_8COLOR): p3 СХЛОПНУТ -> color[2k]==color[2k+1]. idx=(p0<<3)|(p1<<2)|(p2<<1)|p3.
;  8 цветов от (p0,p1,p2) на чётных idx (slot cc = p0*4|p1*2|p2, idx=cc*2):
;    idx0/1  void 0x00        (cc000)             idx8/9   gold-стены 0x77   (cc100)
