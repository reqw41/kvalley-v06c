;  === vec_ct_expand: развернуть RLE-поток (счётчик, значение; счётчик 0 = конец) =======
;  Вход: HL = поток, DE = приёмник. Клоббер: A, B, HL, DE. Один и тот же разворот нужен
;  трижды — профиль сцены, хвост второй пирамиды и режимы тайлов карты
;  (vec_map_whiteforce в vec_blit.asm), поэтому он вынесен сюда, а не расписан по месту.
vec_ct_expand:
