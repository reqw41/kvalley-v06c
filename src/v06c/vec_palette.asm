;  ФИКС ЦВЕТА ПИРАМИД 2026-07-29: idx8/9 был 0x1F ОРАНЖ (реликт: тайлы пирамид/GOAL шли
;  сплошным p0), теперь 0x57 КРАСНЫЙ = MSX medium red (цвета 6/8/9 таблицы colorTableMap).
