;  (данные vec_mixtiles вынесены в хвост post-align — экономят pre-align padding до revtab)
;  vec_ct_load: HL = упакованная таблица режимов, DE = 120Б построчного цвета.
;  Разворачивает пары (счётчик, значение) в vec_tilemode и копирует mixbuf. Это замена
;  рантайм-сведению: цвет тайлов посчитан офлайн и лежит готовым (см. tools/gfx/msx2vec.py).
vec_ct_load:
;  СТРАХОВКА ОТ ПАТЧА КОНЦОВКИ (задача #15). Тайлы 0x40-0x47 на финальном экране — грани
;  пирамид, пол и звёзды, а в лабиринте те же номера означают КИРПИЧ. Штатно развилку
;  возвращает сама концовка (waitEnding -> vec_ct_base), но профиль сцены и развилка тайлов
;  описывают ОДНО И ТО ЖЕ — раскладку тайлсета, поэтому любая смена профиля обязана видеть
;  базовую развилку, чем бы ни кончился предыдущий экран.
	call	vec_ct_base
	push	de
	ld	de, vec_tilemode
	call	vec_ct_expand
;  ПОСТРОЧНЫЙ ЦВЕТ РАЗВОРАЧИВАЕТСЯ ИЗ ПУЛА СЛОТОВ. Профиль — это не 120 Б сырья, а 15
;  ИНДЕКСОВ в vec_ct_slots: одинаковые 8-байтные слоты (сплошной чёрный, сплошной 0xF0
;  и т.п.) повторяются и внутри профиля, и между профилями, разных всего 15 на 30.
;  Экономия 90 Б данных ценой 22 Б кода; разворот идёт раз на смену сцены, такты дёшевы.
	pop	hl	; таблица из 15 индексов слотов
	ld	de, vec_mixbuf
	ld	b, 15
vctl_sl:
	ld	a, (hl)	; индекс слота
	inc	hl
	push	hl	; курсор таблицы индексов
