vec_setpal_a:	; PER-SCREEN: A+ палитра. idx8 (золото геймплей / синий меню)
;  даёт vec_brillo_pal в VBlank по flagPiramideMap. НЕ писать idx8 здесь mid-frame: на железе
;  запись палитры вне VBlank латчится в индекс пикселя под растром → золото утекало в idx0 (фон).
	ld	hl, vec_pal+15
vsp_defer:	; отложить до VBlank (применит vec_isr); прямая запись только на буте
	ld	(vec_pal_ptr), hl
	ret
;  vsp_sync: ЗАКАЗАТЬ ПАЛИТРУ И ДОЖДАТЬСЯ ЕЁ ПРИМЕНЕНИЯ (задача #21). Нужна там, где сразу за
;  заказом идёт ДЛИННЫЙ УЧАСТОК ПОД DI, внутри которого сцена уже рисуется: обычный vsp_defer
;  ждёт прерывания, а прерываний там нет, и палитра приезжает только к концу постройки — на
;  готовую картинку (замер финального экрана: заказ на кадре 3040, применение на 3052, разом
;  5244 перекрашенных пикселя). Здесь мы отпускаем прерывания и крутимся, пока ISR не заберёт
;  запрос (hi указателя обнуляется) — это не больше кадра. СТОРОЖ BC: если прерывания почему-то
;  не придут (все вызовы идут из игрового тика, но подстрахуемся), выходим через ~5 кадров
;  вместо вечного зависания. Вход: HL = таблица+15, как у vsp_defer/vsp_load.
vsp_sync:
	call	vsp_defer
	ld	bc, 8000
	ei
vspn_w:
	ld	a, (vec_pal_ptr+1)
	or	a
	ret	z	; запрос забран прерыванием — палитра уже на экране
	dec	bc
	ld	a, b
	or	c
	jp	nz, vspn_w
	ret
vsp_load:
;  Полная таблица перебивает ВСЕ 16 слотов, в том числе idx8/9 и idx10/11 схемы камней ->
;  кэш vec_brillo_pal (vbp_cv, см. vbp_scheme в vec_blit.asm) обязан протухнуть, иначе
;  brillo решит, что схема уже в палитре, и цвет кирпича останется от таблицы.
	xor	a
	ld	(vbp_cv), a
	ld	de, 0x100F
vec_setpal2:
	ld	a, e
	out	(0x02), a
	ld	a, (hl)
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
	out	(0x0C), a
;  ПОРЯДОК ВАЖЕН (2026-07-30): dec hl/e/d стоят ПОСЛЕ последнего out (0x0C), а не вперемешку
;  с ним. Запись цвета защёлкивается не мгновенно — она догоняет луч примерно через 20
;  тактов, и если за это время сменить индекс слота (out 0x02 в начале следующей итерации),
;  цвет уедет В СОСЕДНИЙ СЛОТ. Раньше между последним out и сменой индекса было 15 тактов:
;  ловилось как idx7 != idx6 в титульной раскладке, а нарушенная пара = ВИДИМАЯ плоскость p3,
;  то есть служебное ОЗУ (слоты save-under, кэши, переменные) проступало мусором на экране
;  Konami. Теперь после последнего out идут три dec + jp + ld a,e = ~30 тактов.
	dec	hl
	dec	e
	dec	d
	jp	nz, vec_setpal2
	ret
vec_pal:	; записи 0..15 (процедура читает в обратном порядке)
;  Задача 2.4 layout (spec 0.3): idx=(p0<<3)|(p1<<2)|(p2<<1)|p3. p3=1 -> sprite
; цвет, ПРИОРИТЕТ над фоном (каждый нечётный индекс, независимо от p0/p1/p2).
; p3=0 -> цвет фона из (p0,p1) (4 слота); p2 инвариантен (скрытая
; RAM плана 2). fon0/fon1/fon2/fon3 = ТЕ ЖЕ 4 значения, что фон уже
; использовал (без изменений — лабиринт/HUD хранят точные цвета) — лишь fon1/fon3
; (p1=1) пока недостижимы (vec_nat_room/vec_blit_tile пишут только
