;  ВТОРАЯ И ДАЛЬШЕ ПИРАМИДЫ — ЭТО ПРОФИЛЬ ПЕРВОЙ ПЛЮС ЗАПЛАТКА НА ХВОСТ. Проверено
;  декодером профилей: клетки 0x00-0x9F у stage_a и stage_b СОВПАДАЮТ полностью, отличия
;  только в 0xC0-0xE7, а построчный цвет у них и вовсе один. Поэтому вместо второго
;  полного потока (83 Б) лежит только его хвост vec_ct_stage_btail (15 Б, клетки
