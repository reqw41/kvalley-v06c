;  В 8C p3 = СЛУЖЕБНОЕ ОЗУ (слоты save-under 0xE000-0xF4FF, кэш зеркал спрайтов 0xF500,
;  буфер спрайт-паттернов 0xF6A0, паттерны лабиринта 0xF9A0, шрифт 0xFC00, переменные 0xFD..),
;  и видимая p3 вываливала всё это на пергамент (мерцающий мусор справа на карте).
;  Спрайты карты (силуэт + стрелка) идут в p2 (vns_pbher, col&8) => для их видимости хватает
