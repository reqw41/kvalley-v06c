;  idx4/5 (p0=0,p1=1) на карте занят ТОЛЬКО буквами GOAL: 0xD2 = MSX dark blue (цвет 4 в
;  colorTableMap, строки 1-6 тайлов 0xCC-0xCE). Больше нигде на пергаменте не встречается
