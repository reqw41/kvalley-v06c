vec_setpal_menu:	; PER-SCREEN: ТОЛЬКО палитра (БЕЗ PPI). p2/p3-НЕВИДИМАЯ (карта/пергамент):
;  для каждого (p0,p1) все 4 (p2,p3)=один цвет фона -> pat_shadow(p2)/
