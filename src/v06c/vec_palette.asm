	ld	de, vec_tilemode+0x0A0
	jp	vec_ct_expand
vec_setpal:	; BOOT: PPI-конфиг(out 00h=0x88) + ЧЁРНАЯ палитра. Donor Gorodetsky 0x10D8
	ld	a, 0x88	; 8255 PPI mode — ТОЛЬКО на boot (переконфиг mid-game = чёрный экран!)
	out	(0x00), a
;  ЧЁРНАЯ, А НЕ ИГРОВАЯ (2026-07-30): распаковка графики после бута идёт прямо в
;  фреймбуфер, и в игровой палитре её видно — экран «светится» мусором и полурисованными
