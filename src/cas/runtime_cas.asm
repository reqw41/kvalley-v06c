; РАНТАЙМ 1 ДЛЯ ЧИСТО ШТАТНОЙ ЛЕНТЫ (вариант .cas, без нашего турбо).
; Ложится в 0x7800 тем же переездом из ступени 1, что и турбо-вариант.
;
; ЗАЧЕМ ОН НУЖЕН, ЕСЛИ ФОРМАТ ШТАТНЫЙ. Штатное ПЗУ умеет загрузить ровно
; ОДНУ непрерывную цепочку страниц, а потом уходит в свой цикл ожидания.
; Нам нужно три куска подряд (ступень 1, заставка, игра) и разная работа
; между ними, поэтому второй и третий кусок разбираем сами. Но БИТЫ с ленты
; читает по-прежнему ПЗУ — его процедурой по 0x0448: она уже откалибрована
; (калибровка прошла по ракорду ступени 1) и проверена живым железом.
;
; ЧТО МЫ ПРИ ЭТОМ ВЫИГРЫВАЕМ: ПЗУ, разбирая блоки само, рисует карту
; прогресса по адресам 0xC018 + (N%32)*0x100 + (N/32)*0x18 — то есть ПРЯМО
; В ЭКРАН, в плоскость 2. Для 117-страничного образа это четыре полосы по
; восемь строк во всю ширину. Свой разборщик карту не рисует, поэтому
; заставка остаётся целой, а прогресс показываем каймой.
;
; ФОРМАТ, КОТОРЫЙ РАЗБИРАЕМ (тот же, что пишет любой конвертер в v06c-rom):
;   на страницу: заголовок 35 Б после 0xE6 (b0=0, b31=страница, b32=всего
;   страниц, b33=номер сверху вниз, b34=сумма b0..b33) и восемь подблоков
;   по 35 Б (b0=0x80..0x87, b1=тег заголовка, 32 байта данных, b34=сумма).
;   Сумма каждой группы проверяется — это и есть контроль целостности.

ROMRD	equ 0x0448		; процедура ПЗУ «прочитать байт с ленты»
				; A=0xFF — с поиском синхробайта 0xE6, A=0x08 — просто 8 бит
				; сохраняет BC и DE, HL не трогает
BORDER	equ 0x02
RT2	equ 0x7900		; куда переезжает рантайм 2
RT2SRC	equ 0x0800		; куда его кладёт лента
RT2LEN	equ 512

	org 0x7800

	jp start		; 0x7800 — вход из ступени 1
	jp loadprog		; 0x7803 — «загрузить очередную программу»

start:
	di
	ld sp, 0x8000
	ld a, 0x88		; ППА: порт B ВЫХОД (кайма). 0x8A даёт mode512
	out (0x00), a
	call loadprog		; программа 2: рантайм 2 + сжатая заставка
	ld hl, RT2SRC		; рантайм 2 приехал в нижнее ОЗУ — переносим его
	ld de, RT2		; выше образа игры, иначе игра его затрёт
	ld bc, RT2LEN
mv:
	ld a, (hl)
	ld (de), a
	inc hl
	inc de
	dec bc
	ld a, b
	or c
	jp nz, mv
	jp RT2

; --- загрузить одну программу штатного формата ----------------------------
; Возвращается, когда принят последний подблок последней страницы.
loadprog:
	xor a
	out (BORDER), a
hdr:
	call rdgroup
	jp nz, hdr		; сумма не сошлась — ищем следующий 0xE6
	ld a, (buf)
	or a
	jp nz, hdr		; не заголовок — ждём заголовок
; Цепляемся за ЛЮБОЙ заголовок, а не обязательно за первый: у каждой страницы
; свой заголовок со своим номером и тегом, а номер идёт сверху вниз, поэтому
; он же и говорит, сколько страниц осталось. Это снимает всякие требования к
; тому, успел ли загрузчик к началу программы: первая страница каждой
; программы отдана под этот промах и ничего не значит.
	ld a, (buf+33)		; номер страницы сверху вниз = сколько осталось
	ld (left), a
	jp usehdr

sub:
	call rdgroup
	jp nz, sub
	ld a, (buf)
	or a
	jp z, usehdr		; заголовок очередной страницы
	ld hl, buf+1		; тег: подблок обязан быть от нашего заголовка
	ld a, (tag)
	cp (hl)
	jp nz, sub
	ld a, (buf)
	and 0x07
	add a, a
	add a, a
	add a, a
	add a, a
	add a, a		; смещение в странице = (id & 7) * 32
	ld l, a
	ld a, (page)
	ld h, a
	ld de, buf+2
	ld c, 32
cp32:
	ld a, (de)
	ld (hl), a
	inc de
	inc l
	dec c
	jp nz, cp32
	ld a, h
	and 0x0F
	out (BORDER), a		; полосы каймы в такт подблокам
	ld a, (buf)
	cp 0x87
	jp nz, sub		; страница ещё не кончилась
	ld a, (left)
	dec a
	ld (left), a
	jp nz, sub
	xor a
	out (BORDER), a
	ret

usehdr:
; ЛОВУШКА, НА КОТОРОЙ Я УЖЕ ОБЖЁГСЯ: поле b31 — это НЕ номер текущей
; страницы, а старший байт адреса ВСЕЙ ПРОГРАММЫ, и он одинаков во всех
; заголовках. Страницу ПЗУ считает само (inc b), а нам её надо восстановить:
;     страница = b31 + (всего страниц - номер сверху вниз)
; Первый вариант брал страницу прямо из b31 — и вся программа ложилась в
; одну и ту же страницу поверх себя. Заодно эта арифметика позволяет
; цепляться к программе с ЛЮБОГО заголовка, а не только с первого.
	ld a, (buf+32)		; всего страниц
	ld hl, buf+33
	sub (hl)		; минус номер сверху вниз = порядковый индекс
	ld hl, buf+31
	add a, (hl)		; плюс начальная страница программы
	ld (page), a
	ld a, (buf+34)
	ld (tag), a
	jp sub

; --- принять группу из 35 байт после синхробайта --------------------------
; выход: Z — сумма сошлась; буфер buf; портит A,B,C,H,L
rdgroup:
	ld hl, buf
	ld c, 35
	ld b, 0			; накопитель суммы
	ld a, 0xFF		; первый байт — с поиском 0xE6
rg:
	call ROMRD
	ld (hl), a
	inc hl
	add a, b
	ld b, a
	ld a, 0x08		; дальше просто по восемь бит
	dec c
	jp nz, rg
	dec hl			; -> байт суммы
	ld a, b
	sub (hl)
	sub (hl)		; сумма всех 35 минус удвоенная контрольная
	ret			; == 0, если сумма первых 34 равна контрольной

page:	db 0
tag:	db 0
left:	db 0
buf:	ds 35, 0
