; РАНТАЙМ 2 — распорядитель кассетной версии. Приезжает первым турбо-блоком
; в 0x7900 и дальше сам заказывает ленте остальное:
;
;   блок 2 — сжатая заставка  -> 0x0800, распаковывается в видеопамять
;   блок 3 — образ игры       -> 0x0100, экран при этом НЕ трогаем
;
; ПОЧЕМУ СЖАТАЯ ЗАСТАВКА ЛОЖИТСЯ В 0x0800, А НЕ В 0x0100:
; штатное ПЗУ никуда не девается — оно перекрывает ЧТЕНИЕ адресов
; 0x0000-0x07FF до самого БЛК+СБР. Писать туда можно, читать — нельзя:
; вместо своих данных распаковщик получил бы байты ПЗУ.
;
; ПОЧЕМУ ИГРА ВСЁ-ТАКИ ГРУЗИТСЯ В 0x0100: туда мы только ПИШЕМ. Запускается
; она уже после БЛК+СБР, когда ПЗУ отключено — по адресу 0x0000 мы заранее
; кладём jp 0x0100.
;
; ПРО ПРЕРЫВАНИЯ: свой обработчик поставить нельзя — вектор 0x0038 читается
; из ПЗУ. К счастью, там лежит ровно 0xC9 (ret), поэтому ei/halt работает как
; «дождаться кадрового прерывания и вернуться» — этого хватает, чтобы попасть
; палитрой в гашение.

LOADBLK	equ 0x7803		; «загрузить очередной блок» — в рантайме 1
SPLASH	equ 0x0800		; сжатая заставка
SCREEN	equ 0x8000		; распакованная заставка = видеопамять
GAME	equ 0x0100		; образ игры

	org 0x7900

start2:
; --- блок 2: сжатая заставка ---------------------------------------------
	call LOADBLK
	ld hl, SPLASH
	ld de, SCREEN
	call unlz

; --- палитра: только в кадровом гашении -----------------------------------
; Первое прерывание после долгого di — холостое: INT накопился и приходит
; посреди кадра. Ждём второго, вот оно и есть начало гашения.
	ei
	halt
	ei
	halt
	di
	ld a, 0xFF
	out (0x03), a
	ld hl, pal+15
	ld de, 0x100F
ploop:
	ld a, e
	out (0x02), a
	ld a, (hl)
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	dec hl
	dec e
	dec d
	jp nz, ploop
	xor a
	out (0x02), a

; --- блок 3: образ игры. Экран не трогаем, прогресс — только каймой -------
	call LOADBLK
	xor a
	out (0x02), a		; кайма чёрная

; --- запуск ---------------------------------------------------------------
; По 0x0000 кладём jp 0x0100 — это точка входа после БЛК+СБР.
	ld a, 0xC3
	ld (0x0000), a
	ld hl, GAME
	ld (0x0001), hl
; Проверяем, отключилось ли ПЗУ. На машинах с ПЗУ «Старт-1200» запись в порт
; 0x0C (а мы только что писали палитру) снимает ПЗУ с 0x0000 — тогда можно
; стартовать самим. На штатном двухкилобайтном ПЗУ этого не происходит, и
; запуск остаётся за человеком: БЛК+СБР.
	ld a, (0x0000)
	cp 0xC3
	jp z, 0x0000
hold:
	jp hold			; заставка на экране, ждём БЛК+СБР

pal:
	incbin "../../docs/cas/v16_pal.bin"

	include "unlz.asm"
