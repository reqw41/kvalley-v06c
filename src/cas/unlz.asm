; ============================================================================
; unlz.asm — распаковщик формата G8. Пара к tools/cas/pack_lz.py (формат описан там же).
; ТОЛЬКО команды i8080 (мнемоники Z80): ни ix/iy, ни jr/djnz, ни exx, ни ldir,
; ни sla/srl/bit, ни adc hl,de. add hl,hl (dad h) и add hl,bc — можно.
;
;   вход:  HL = адрес сжатого блока (нижнее ОЗУ), DE = приёмник (0x8000)
;   выход: 32768 байт по 0x8000..0xFFFF; портит все регистры; стек — 2 уровня
;
; ФОРМАТ (подробно — в pack_lz.py):
;   бит 0 -> литерал: следом ЦЕЛЫЙ байт потока
;   бит 1 -> матч: gamma(len-1), gamma(hi+1), ЦЕЛЫЙ байт lo; смещение = hi*256+lo+1
;   ПЕРВЫЙ элемент всегда литерал, и флага для него в потоке НЕТ: в позиции 0 матч
;   невозможен физически (истории ещё нет). Это не экономия бита — это то, что даёт
;   телу литерала ПАДАТЬ в главный цикл, а не прыгать в него (10 тактов * 9470 раз).
;   конец потока -> бит 1 и gamma(65536): переполнение HL в add hl,hl
;   за потоком — план XOR-проходов: пары (старший байт приёмника, старший байт
;   источника), 0x00 — конец списка.
;
; РАСПРЕДЕЛЕНИЕ РЕГИСТРОВ — не косметика, а причина, по которой формат именно такой:
;   A  = буфер бит (приём ZX7: add a,a выдаёт бит в перенос и сам сообщает нулём, что
;        байт кончился). Занят ВСЕГДА, поэтому сравнить что-либо с нулём нечем —
;        отсюда маркер конца через перенос от add hl,hl, а не проверка «D дошёл до 0».
;   DE = указатель сжатого блока (ld a,(de))
;   BC = приёмник (ld (bc),a; второй пары с косвенной записью у i8080 нет)
;   HL = аккумулятор гаммы, затем адрес источника матча
;   На время копирования поток уходит в стек, D принимает буфер бит, E — счётчик.
; ============================================================================

unlz:
	ld b,d
	ld c,e			; BC = приёмник
	ex de,hl		; DE = сжатый блок
	ld a,0x80		; буфер бит пуст: первый же add a,a попросит подкачку

; --- ЛИТЕРАЛ: целый байт потока. Буфер бит прячем в H: HL вне матча свободен ---
unlz_lit:
	ld h,a
	ld a,(de)
	inc de
	ld (bc),a
	inc bc
	ld a,h
; --- главный цикл: флаговый бит ---
unlz_main:
	add a,a
	jp nz,unlz_m1
	call unlz_bits
unlz_m1:
	jp nc,unlz_lit

; --- МАТЧ ---
	call unlz_gamma		; HL = len-1; здесь же ловится маркер конца
	inc hl
	ld (unlz_len),hl	; длину девать некуда: все три пары заняты
	call unlz_gamma		; HL = hi+1
	dec hl
	ld h,l			; H = старший байт (смещение-1)
	ld l,a			; L = буфер бит на время чтения байта
	ld a,(de)		; младший байт — ПОСЛЕДНЕЕ чтение потока в матче,
	inc de			; дальше поток можно прятать
	push de
	ld d,l			; D = буфер бит (пары освободились)
	ld l,a			; HL = смещение-1
	ld a,(unlz_len)
	ld e,a			; E = длина; 0 означает 256 (счётчик дойдёт до 0 за 256)
	ld a,c			; HL = BC - смещение
	sub l
	ld l,a
	ld a,b
	sbc a,h
	ld h,a
	dec hl
unlz_copy:
	ld a,(hl)		; источник — уже распакованный кусок ВИДЕОПАМЯТИ
	inc hl
	ld (bc),a
	inc bc
	dec e
	jp nz,unlz_copy
	ld a,d			; буфер бит обратно
	pop de			; поток обратно
	jp unlz_main

; --- перемежённая гамма Элиаса: hl=1; while бит: hl = hl*2 + бит ---
unlz_gamma:
	ld hl,1
unlz_g0:
	add a,a
	jp nz,unlz_g1
	call unlz_bits
unlz_g1:
	ret nc			; бит продолжения 0 — число кончилось
	add a,a
	jp nz,unlz_g2
	call unlz_bits
unlz_g2:
	jp nc,unlz_g3
	add hl,hl
	inc hl
	jp nc,unlz_g0
	jp unlz_fin
unlz_g3:
	add hl,hl
	jp nc,unlz_g0		; перенос = значение переросло 16 бит = маркер конца.
				; проверка бесплатна: jp nc стоит ровно как jp

; --- обратное XOR-предобразование плоскостей по плану из хвоста блока.
;     Плоскости коррелируют по битам цвета, и эти два прохода стоят 3899 байт
;     потока против 0.16 с работы — на ленте байт дороже такта ---
unlz_fin:
	pop hl			; адрес возврата из unlz_gamma — он больше не нужен
unlz_xp:
	ld a,(de)
	inc de
	or a
	ret z			; 0x00 — план кончился, распаковка завершена
	ld b,a
	ld c,0			; BC = приёмник прохода (плоскость выровнена на 0x2000)
	ld a,(de)
	inc de
	ld h,a
	ld l,0			; HL = источник прохода
	push de			; указатель плана — в стек
	ld d,32			; 32 страницы по 256 байт = 8192
	ld e,0
unlz_xl:
	ld a,(bc)
	xor (hl)
	ld (bc),a
	inc hl
	inc bc
	dec e
	jp nz,unlz_xl
	dec d
	jp nz,unlz_xl
	pop de
	jp unlz_xp

; --- подкачка очередного байта под биты. Перенос на входе всегда 1 (A обнулился
;     только из 0x80), поэтому adc a,a вдвигает единицу-сторож в младший бит ---
unlz_bits:
	ld a,(de)
	inc de
	adc a,a
	ret

unlz_len:
	dw 0			; младший байт — длина матча; ld (nn),hl пишет оба
unlz_end:
