; РАНТАЙМ 2 ДЛЯ ЧИСТО ШТАТНОЙ ЛЕНТЫ. Приезжает второй программой вместе со
; сжатой заставкой (лента кладёт их в 0x0800, рантайм 1 переносит этот кусок
; в 0x7900 и передаёт сюда управление — выше образа игры, иначе игра затрёт).
;
;   лента:  0x0800 = этот код (512 Б),  0x0A00 = сжатая заставка
;   после переезда: 0x7900 = этот код,  распаковка идёт из 0x0A00
;
; Заставка распаковывается ДО загрузки игры: в нижнем ОЗУ им вдвоём не
; поместиться (сжатая заставка + образ с оверлеем больше, чем 32512 байт
; под экраном), поэтому сжатая заставка живёт там ровно до момента, когда
; её развернули в экран, а потом это место занимает образ игры.

LOADPRG	equ 0x7803		; «загрузить очередную программу» — в рантайме 1
SPLASH	equ 0x0A00		; сжатая заставка, как её положила лента
SCREEN	equ 0x8000
GAME	equ 0x0100

	org 0x7900

start2:
	ld hl, SPLASH
	ld de, SCREEN
	call unlz

; --- палитра: только в кадровом гашении -----------------------------------
; Свой обработчик прерываний поставить нельзя — вектор 0x0038 читается из
; ПЗУ, но там ровно 0xC9 (ret), поэтому ei/halt работает как «дождаться
; кадрового и вернуться». Первое прерывание после долгого di — холостое.
	ei
	halt
	ei
	halt
	di
	ld a, 0xFF
	out (0x03), a
	ld hl, pal+15
	ld de, 0x100F
ploop:
	ld a, e
	out (0x02), a
	ld a, (hl)
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	out (0x0C), a
	dec hl
	dec e
	dec d
	jp nz, ploop
	xor a
	out (0x02), a

; --- программа 3: образ игры. Экран не трогаем, прогресс — каймой ---------
	call LOADPRG
	xor a
	out (0x02), a

; --- запуск ---------------------------------------------------------------
	ld a, 0xC3
	ld (0x0000), a
	ld hl, GAME
	ld (0x0001), hl
	ld a, (0x0000)
	cp 0xC3
	jp z, 0x0000		; ПЗУ снялось (машина со «Старт-1200») — стартуем сами
hold:
	jp hold			; заставка на экране, ждём БЛК+СБР

pal:
	incbin "../../docs/cas/v16_pal.bin"

	include "unlz.asm"

	ds 0x7B00-$, 0xFF	; ровно 512 байт: заставка обязана начаться с 0x0A00
