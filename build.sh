#!/bin/sh
mkdir -p build
# Сборка King's Valley 8C из КАНОНИЧЕСКОГО asm (точка заморозки транслятора: c49aaa0,
# тег asm-freeze). Транслятор Z80->i8080 больше НЕ в конвейере — src/kvalley_8c.asm
# и есть исходник. Аварийная перегенерация: см. tools/kv_z80_to_8080.py + тег.
set -e
cd "$(dirname "$0")"
# Карты пирамид: текстовый исходник -> генерируемый asm (байт-в-байт, гейт заморозки следит)
python3 tools/maps_compile.py
# Метка сборки на титуле (11 глифов табло): ДДММ-ЧЧММ-B, где B — буква ВЕТКИ:
# M = основная линия, K = ветка hud6k (4 плоскости). Прежний вид V1-07B-ЧЧММ убран
# 2026-08-20: релизный префикс не различал сборки, а на руках их теперь две, и путать
# их на железе дороже, чем знать номер релиза. Длина та же, 11 глифов, раскладка титула
# не тронута. Глифы табло: цифра = 0x10+цифра, буква = 0x21+номер в алфавите ('A'=0x21),
# '-' = 0x20 (проверено на прежних 'V'=0x36 и 'B'=0x22).
python3 -c "
from datetime import datetime
import os, subprocess
n = datetime.now()
try:
    br = subprocess.run(['git','rev-parse','--abbrev-ref','HEAD'],
                        capture_output=True, text=True).stdout.strip()
except Exception:
    br = ''
if os.environ.get('KV_NO_VERSION'):
    glyphs = [0] * 11
    body = 'blank'
    note = 'титул без метки версии'
else:
    letter = 'K' if br == 'hud6k' else 'M'
    body = n.strftime('%d%m') + '-' + n.strftime('%H%M') + '-' + letter
    glyphs = []
    for c in body:
        if c.isdigit(): glyphs.append(0x10 + int(c))
        elif c == '-':  glyphs.append(0x20)
        else:           glyphs.append(0x21 + ord(c) - ord('A'))
    note = 'титул %s  (ветка %s, сборка %s)' % (body, br or '?', n.strftime('%Y%m%d-%H%M'))
assert len(glyphs) == 11, 'метка обязана быть ровно 11 глифов, а не %d' % len(glyphs)
open('src/gen/kv_version.asm','w').write(
    '; generated by build.sh, не править руками\n'
    'KV_VERSION:\n'
    '\tdb ' + ', '.join('0x%02X' % b for b in glyphs) +
    '  ; ' + body + '\n'
    '\tdb 0x0FF\n')
print('  ' + note)
"
# Потоки звука ВИ53 (src/gen/snd_streams.asm) закоммичены; перегенерация — node tools/snd_gen/snd_gen.js
# (см. tools/snd_gen/README.md), в сборку она не входит: нужен эмулятор для съёмки исходного драйвера.
tools/bin/sjasm -s src/kvalley_8c.asm build/kvalley_8c.rom build/kvalley_8c.lst build/kvalley_8c.sym
# Резидент до romCeil.
python3 tools/rom_pad.py
# КАРТА ПАМЯТИ + гейт переполнения. Код/данные обязаны кончиться ДО 0x6C00 (там начинаются
# игровые переменные) — sjasm об этом молчит, а перехлёст = молча испорченные переменные.
# Заодно печатаем, ГДЕ теряется место: зазоры от .align видны сразу, их можно занять
# переносом процедуры (переносить только целиком, до ret — см. коммит 89f10b8).
python3 tools/mem_map.py
# ЗАМОРОЗКА СНЯТА 2026-08-05. Гейт «ROM байт-в-байт с эталоном» стоял на время разрезки
# на модули: она давно закончена, а эталон build/freeze.md5 последний раз обновлялся 325
# коммитов назад (822a9db). Всё это время каждая сборка печатала FREEZE MISMATCH и
# ОБРЫВАЛАСЬ на exit 1 — то есть НЕ доходила ни до гейта паритета Devector, ни до копий
# в эмулятор и devector/. Проверено вручную: паритет проходит (DEVECTOR PARITY OK).
# Если заморозка снова понадобится (новая разрезка), положить эталон в build/freeze.md5
# и вернуть блок — но с обязательным обновлением эталона в том же коммите, что и правка.
# Гейт паритета Devector: тот же исходник обязан собираться ассемблером Devector байт-в-байт.
node tools/verify/devector_gate.js
# Splash-ROM: обложка 5 с, затем тот же титул и замок читов F1+F3.
python3 tools/cas/make_splash_rom.py build/kvalley_8c.rom docs/cas/v16_planes.raw docs/cas/v16_pal.bin build/kvalley_splash.rom
# Деплой в эмулятор + Devector (прошлый билд сохраняем для отката)
# KV_NO_DEPLOY=1 — собрать и НЕ раскладывать никуда. Нужно для пробных сборок: пока
# заморозка обрывала build.sh на полпути, эксперимент физически не мог доехать до
# железа, а теперь доезжает — экспериментальная сборка «тик через кадр» успела
# заменить рабочую на MiSTer прежде, чем стало ясно, что она ломает старт партии.
if [ -n "$KV_NO_DEPLOY" ]; then
  echo "деплой пропущен (KV_NO_DEPLOY=$KV_NO_DEPLOY): ROM только в build/"
  exit 0
fi
[ -f "$HOME/projects/vector06js/kv8c.rom" ] && cp "$HOME/projects/vector06js/kv8c.rom" "$HOME/projects/vector06js/kv8c_prev.rom"
cp build/kvalley_8c.rom "$HOME/projects/vector06js/kv8c.rom"
cp build/kvalley_8c.rom devector/kvalley.rom
cp build/kvalley_8c.sym devector/kvalley.sym
# MiSTer: ОСНОВНОЙ .rom = чистая игра (без заставки). Splash — отдельный артефакт
# build/kvalley_splash.rom (обложка 5 с); на FAT кладём рядом, не вместо игры.
# Решение 2026-08-14: встроенный splash на железе портил палитру и вис на обложке;
# сжатие/отдельный ROM — пока отдельный файл, основной путь без него.
MISTER_DIR="root@192.168.1.124:/media/fat/games/VECTOR06"
if sshpass -p '1' scp -o PreferredAuthentications=password -o PubkeyAuthentication=no -o ConnectTimeout=3 \
    build/kvalley_8c.rom "$MISTER_DIR/King's Valley.rom" 2>/dev/null; then
  # MGL «Kings Valley» без апострофа — иначе меню берёт старый splash
  sshpass -p '1' scp -o PreferredAuthentications=password -o PubkeyAuthentication=no -o ConnectTimeout=3 \
    build/kvalley_8c.rom "$MISTER_DIR/Kings Valley.rom" 2>/dev/null || true
  # опционально: отдельный ROM с обложкой (не перетирает основной)
  sshpass -p '1' scp -o PreferredAuthentications=password -o PubkeyAuthentication=no -o ConnectTimeout=3 \
    build/kvalley_splash.rom "$MISTER_DIR/King's Valley Splash.rom" 2>/dev/null || true
  echo "deployed: kv8c.rom + devector/ + MiSTer (игра; splash отдельно)"
else
  echo "deployed: kv8c.rom + devector/ (MiSTer недоступен)"
fi
